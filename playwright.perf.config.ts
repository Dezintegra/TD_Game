import { defineConfig } from '@playwright/test';
import base from './playwright.config.js';

/**
 * Набор замеров частоты кадров.
 *
 * Отделён от обычного прогона не из аккуратности, а потому что измерение
 * ведёт себя иначе, чем проверка. Проверка отвечает «да» или «нет»
 * независимо от того, чем занята машина; измерение — отвечает о машине
 * ровно столько же, сколько о коде.
 *
 * Порты, браузер и флаги наследуются от `playwright.config.ts`.
 * Не наследуется одно — право подхватить уже поднятый сервер.
 */
export default defineConfig({
  ...base,

  // Замер поднимает СВОИ процессы и никогда не цепляется к чужим.
  //
  // Обычный прогон это право имеет намеренно: держать дев-сервер
  // открытым и гонять по нему проверки — нормальная работа. Замеру же
  // подхваченный сервер подсовывает чужое дерево вместо своего, и узнать
  // об этом неоткуда: цифра выходит правдоподобная, только относится
  // она к другому коду.
  //
  // Проверено 24.08.2026, и цена ошибки оказалась велика. На 5173 висел
  // дев-сервер основного дерева, поднятый пятнадцатью часами раньше;
  // все замеры в рабочем дереве шли через него. Сравнение «до и после»
  // дважды измерило одну и ту же сборку и уверенно сказало «разницы
  // нет» — вывод верный по случайности, а не по замеру. Когда же
  // в основное дерево приехал код, несовместимый с его собранными
  // пакетами, тот же замер выдал ровные нули.
  //
  // Занятый порт теперь честная остановка: `scripts/perf-run.mjs`
  // проверяет порты до запуска и объясняет, что делать.
  webServer: base.webServer?.map((server) => ({ ...server, reuseExistingServer: false })),

  // Обычный конфиг эти файлы исключает — здесь ровно наоборот.
  testIgnore: [],
  testMatch: ['**/*.perf.spec.ts'],

  // Один поток. Несколько потоков сразу соревнуются за процессор и роняют
  // цифру: замер 22.08.2026 давал при пяти потоках 45–51 кадра при пороге
  // 55, тогда как в одиночку те же тесты проходили. Красный результат
  // от собственной параллельности — худший вид ложной тревоги, ему верят.
  fullyParallel: false,
  workers: 1,

  // Повтор упавшего замера — это второй замер, а не подтверждение первого.
  // Прятать разброс повторами здесь нельзя: разброс и есть предмет разговора.
  retries: 0,
});
