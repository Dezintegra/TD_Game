import { defineConfig, devices } from '@playwright/test';

/**
 * E2E проверяет сквозную вертикаль целиком: клиент, протокол, сервер
 * и компьютерного соперника. Playwright сам поднимает все три процесса
 * перед прогоном и гасит после.
 *
 * Процессов стало три, а не два, и это не усложнение ради усложнения:
 * служба компьютерных дежурных уехала из процесса сервера в свой
 * (`apps/computer`). Поднимать её обязательно — без неё в списке нет
 * ни одной комнаты компьютера, а на них стоит половина проверок.
 */

// Порты читаются из среды теми же именами, которые понимают сами
// приложения: клиент — CLIENT_PORT (apps/client/vite.config.ts),
// сервер — PORT (apps/server/src/config.ts). Благодаря этому прогон
// e2e можно вести из нескольких рабочих деревьев сразу, не деля
// одну пару портов на всех.
const CLIENT_PORT = Number(process.env['CLIENT_PORT'] ?? 5173);
const SERVER_PORT = Number(process.env['PORT'] ?? 3001);

// Служба ничего не слушает по делу, но Playwright умеет ждать только
// адрес. Ждём её показания: порт берётся соседним с серверным, чтобы
// второе рабочее дерево не подралось с первым и здесь тоже.
const COMPUTER_METRICS_PORT = Number(process.env['COMPUTER_METRICS_PORT'] ?? SERVER_PORT + 1);

const CLIENT_URL = `http://127.0.0.1:${CLIENT_PORT}`;
const SERVER_URL = `http://127.0.0.1:${SERVER_PORT}`;

/**
 * Секрет, которым служба заверяет свои личности перед сервером.
 *
 * У прогона он свой и заведомо не боевой. Пустым его оставить нельзя:
 * пустой означает «регистрация закрыта», и служба намеренно не поднимет
 * ни одного дежурного — комнаты компьютера иначе встали бы в списке
 * непомеченными, то есть человеческими на вид.
 */
const COMPUTER_SECRET = process.env['COMPUTER_SECRET'] ?? 'e2e-секрет';

export default defineConfig({
  testDir: './e2e',
  // Замеры частоты кадров сюда не входят. Им нужна тихая машина и живая
  // видеокарта, а обычный прогон идёт и на занятой машине, и на runner'ах
  // GitHub, где видеокарты нет вовсе. Их набор — `playwright.perf.config.ts`,
  // запуск — `pnpm e2e:perf`.
  testIgnore: ['**/*.perf.spec.ts'],
  fullyParallel: true,

  // Сколько времени отпускается ОДНОЙ проверке.
  //
  // Тридцать секунд по умолчанию сюда не годятся, и дело в арифметике,
  // а не в осторожности. `bootGame` объявляет внутри себя сроки
  // 15 + 15 + 20 — то есть до первого собственного утверждения тест
  // вправе прождать пятьдесят секунд; у «карта показывается и матч
  // начинается заново по кнопке» внутренних сроков набирается все
  // девяносто. Проверке, которой отпущено меньше, чем она сама себе
  // разрешила ждать, нечем упасть по делу: она всегда умирает раньше
  // от секундомера Playwright, и в отчёте остаётся «Test timeout
  // of 30000ms exceeded» вместо внятного «панель наехала на поле».
  // Ровно на эту ловушку 24.08.2026 ушёл день разбирательств
  // с проверкой лобби — там внутреннее терпение в 45 с не доживало
  // до своего срока никогда.
  //
  // Замер по прогонам CI 24.08.2026: здоровая проверка стоит 8–21 с,
  // а разброс между соседними прогонами доходит до 1,7 раза. Причина
  // видна из времени начала: на runner'е четыре ядра, и когда проверка
  // лобби (а она ведёт ДВА браузера) совпадает по времени с тяжёлой
  // соседкой, за процессор соревнуются три браузера, сервер и клиент.
  // В спокойном прогоне «панели не перекрывают игровое поле» заняли
  // 20,7 с, в следующем — не уложились в тридцать вовсе.
  //
  // Девяносто — это потолок, а не стоимость: набор целиком проходит
  // за те же 2,3 минуты. Проверке лобби мало и этого, у неё свои 120 с
  // и своё объяснение на месте.
  timeout: 90_000,

  reporter: 'list',
  use: {
    baseURL: CLIENT_URL,

    // Свой срок у ОДНОГО действия — клика, чтения рамки, ввода строки.
    //
    // По умолчанию здесь ноль, то есть срока нет вовсе: вставшее действие
    // ждёт до конца бюджета проверки. Пока бюджет был тридцать секунд,
    // это стоило тридцати; с девяноста стало стоить полутора минут,
    // и в отчёте всё равно осталась бы безликая строка «Test timeout».
    //
    // Различение, которого не хватало 24.08.2026: `smoke.spec.ts:44` упала
    // на `boundingBox()`, и по логу нельзя было понять, встало ли действие
    // или проверка просто не успела к сроку — оба случая выглядят
    // одинаково. Со своим сроком вставшее действие падает раньше бюджета
    // и говорит, чего именно ждало.
    //
    // Тридцать, а не пятнадцать. Сроком ниже законного действия мы завели
    // бы новый плавающий отказ — ровно то, что здесь лечится, — а замера
    // по действиям у нас пока нет: артефактов с падений CI не сохранял
    // (см. `ci.yml`). Появятся — можно ужать по цифрам, а не на глаз.
    // Даже тридцать втрое дешевле прежнего «до конца бюджета».
    actionTimeout: 30_000,

    // Запись хода проверки спит, пока нет повторов, и это нарочно:
    // `retries` здесь не заведены — повтор прячет разброс, а разброс
    // на runner'е и есть предмет разговора. Строка оставлена как есть:
    // заведут повторы — запись включится сама, без правки конфига.
    trace: 'on-first-retry',

    // Снимок экрана с падения. Он бесплатный — у прошедшей проверки
    // снимок не делается вовсе, — а отвечает ровно на тот вопрос,
    // которого не хватало 24.08.2026: по строке «Test timeout
    // of 30000ms exceeded» нельзя отличить «проверка не успела»
    // от «страница встала на месте». На снимке это видно сразу.
    screenshot: 'only-on-failure',
  },
  projects: [
    {
      name: 'chromium',
      use: {
        ...devices['Desktop Chrome'],
        launchOptions: {
          // Без этих флагов headless-Chromium рисует через SwiftShader, то есть
          // процессором, и выдаёт около 16 кадров в секунду на любой сцене.
          // Измерять производительность в таком режиме бессмысленно: цифра
          // говорит о среде, а не о коде.
          args: ['--use-angle=default', '--enable-gpu', '--ignore-gpu-blocklist'],
        },
      },
    },
  ],
  webServer: [
    {
      command: 'pnpm --filter @td/server dev',
      url: `${SERVER_URL}/health`,
      reuseExistingServer: !process.env['CI'],
      timeout: 60_000,
      // Без секрета сервер закрывает регистрацию компьютера, и список
      // комнат остаётся пустым. Значение то же, что у службы: они
      // сверяются им друг с другом.
      env: { COMPUTER_SECRET },
    },
    {
      // Служба дежурных. Сервера она может и не дождаться с первой
      // попытки — и не должна: у объявления есть нарастающая пауза,
      // и падать при неготовом сервере ей запрещено.
      command: 'pnpm --filter @td/computer dev',
      url: `http://127.0.0.1:${COMPUTER_METRICS_PORT}/metrics`,
      reuseExistingServer: !process.env['CI'],
      timeout: 60_000,
      env: {
        COMPUTER_SECRET,
        COMPUTER_METRICS_PORT: String(COMPUTER_METRICS_PORT),
        // Адрес сервера служба выводит из PORT сама, но выводить его
        // из среды прогона надёжнее: так нацеленный на чужой сервер
        // прогон не окажется наполовину своим.
        COMPUTER_API_URL: SERVER_URL,
        COMPUTER_WS_URL: `ws://127.0.0.1:${SERVER_PORT}/game`,
      },
    },
    {
      command: 'pnpm --filter @td/client dev',
      url: CLIENT_URL,
      reuseExistingServer: !process.env['CI'],
      timeout: 60_000,
      // Адрес сервера доезжает до клиента только через VITE_*-переменные,
      // их читают apps/client/src/game/bootstrap.ts и session/lobby-client.ts.
      // Без этой передачи клиент на нестандартном порту сервера стучался бы
      // в зашитый по умолчанию 3001, то есть в чужое рабочее дерево, —
      // и прогон проверял бы чужой код.
      //
      // Явно заданное снаружи значение уважается: так прогон можно нацелить
      // на уже поднятый сервер.
      env: {
        VITE_API_URL: process.env['VITE_API_URL'] ?? SERVER_URL,
        VITE_WS_URL: process.env['VITE_WS_URL'] ?? `ws://127.0.0.1:${SERVER_PORT}/game`,
        // Прогрев кеша спрайтов сквозным проверкам не нужен и вреден.
        //
        // Он печёт впрок базовый набор — около двухсот комбинаций, —
        // чтобы в бою не пропадали кадры. Проверка на плавность
        // не смотрит вовсе, а цену платит целиком, причём на runner'е,
        // где рисует процессор, цена эта в разы выше проектной.
        //
        // Замер 31.08.2026, настоящие проверки лобби в режиме runner'а:
        // `lobby:96` — 17,5 с против 2,5 с, `lobby:121` — 32,2 с против
        // 2,8 с, а `lobby:159` с прогревом не укладывалась в свои
        // 120 с вовсе. Ровно это и роняло `main` три прогона подряд.
        //
        // Снимаются именно ЗАГОТОВКИ. Всё, что проверка должна увидеть
        // на экране, печётся по надобности — так же, как у игрока,
        // которому прогрев не достался.
        VITE_E2E_CHEAP_TEXTURES: '1',
      },
    },
  ],
});
