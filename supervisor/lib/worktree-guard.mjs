/**
 * Отказ запускать супервизор из дополнительного рабочего дерева.
 *
 * Сторож понадобился ровно из-за короткой команды. Раньше путь к обёртке
 * набирали руками, и промахнуться было трудно; корневой же `package.json`
 * лежит в КАЖДОЙ копии репозитория, а значит `pnpm supervisor` есть и в любом
 * дереве из `.claude/worktrees/`. Поиск корня в пускателе идёт вверх до первого
 * `.git` и остановился бы на самом дереве, супервизор взял бы его `.pipeline` —
 * свой замок, свой реестр, — и отсечение двойного запуска перестало бы
 * работать: замки разные, соседа не видно.
 *
 * Заметить это по выводу было бы почти нечем: файла `.env` в дереве нет,
 * поэтому супервизор пожаловался бы на недостающий доступ к доске — жалоба
 * правдоподобная и уводящая совсем в другую сторону.
 *
 * Решение живёт здесь ЦЕЛИКОМ, вместе с текстом отказа, и это не вкусовщина.
 * `bin/launch.mjs` — не модуль, а сценарий: на верхнем уровне он разбирает
 * доводы, ищет корень и порождает процесс, так что ввезти его в тест значило бы
 * поднять супервизор прямо в прогоне тестов. Всё, что осталось бы в нём,
 * оказалось бы за пределами всех проверок сразу — причём именно та половина,
 * в которой ошибиться легче всего: выбор между запуском и отказом и текст.
 *
 * Ни диска, ни внешних программ: содержимое `.git` передают снаружи. Пускатель
 * отвечает раньше, чем супервизор проверит окружение, и обязан быть осмысленным
 * на машине, где `git` ещё не поставлен.
 */

/**
 * `<основное дерево>/.git/worktrees/<имя>` — так выглядит ссылка у воркри.
 *
 * Оба разделителя пути приняты нарочно: файл пишет git той машины, где дерево
 * заводили, и на Windows там встречаются и косые, и обратные косые черты.
 */
const WORKTREE_LINK = /[\\/]\.git[\\/]worktrees[\\/]/;

/** Строка ссылки в файле `.git`: `gitdir: <путь>`. */
const GITDIR_LINE = /^\s*gitdir:\s*(.+?)\s*$/m;

/**
 * Основное рабочее дерево по ссылке из файла `.git`, либо `null`.
 *
 * Всё непонятое считается «не воркри» намеренно. Файл `.git` бывает и у
 * подмодуля (`gitdir: ../.git/modules/<имя>`), и отказ на нём был бы отказом
 * там, где запуск законен. Сторож обязан ловить свой случай, а не всякий
 * необычный.
 */
export function mainWorktreeOf(gitFile) {
  if (typeof gitFile !== 'string') return null;
  const found = GITDIR_LINE.exec(gitFile);
  if (!found) return null;
  const gitdir = found[1];
  if (!WORKTREE_LINK.test(gitdir)) return null;
  const [main] = gitdir.split(WORKTREE_LINK);
  return main.length > 0 ? main : null;
}

/**
 * Текст отказа: и путь основного дерева, и что там набрать.
 *
 * Собирается здесь, а не в пускателе, чтобы проверяться дословно.
 */
function refusal(root, main) {
  return [
    'ЗАПУСК ИЗ ДОПОЛНИТЕЛЬНОГО РАБОЧЕГО ДЕРЕВА ОТКЛОНЁН.',
    '',
    `Здесь: ${root}`,
    `Основное рабочее дерево: ${main}`,
    '',
    'Хозяйство конвейера — замок, реестр рабочих деревьев и файл переменных',
    'окружения — живёт при основном дереве. Запущенный отсюда супервизор взял бы',
    'своё, соседа бы не увидел, и двойного запуска ничто бы не отсекло.',
    '',
    'Наберите в основном дереве:',
    `  cd ${main}`,
    '  pnpm run supervisor',
    '',
    'Если корень выбран сознательно, назовите его вслух — тогда отказа не будет:',
    `  node supervisor/bin/launch.mjs --root=${main}`,
    `  либо переменной окружения PIPELINE_ROOT=${main}`,
  ].join('\n');
}

/**
 * Запускать или отказать.
 *
 * @param {object} params
 * @param {string} params.root       корень, который нашёл пускатель
 * @param {string|null} params.gitFile содержимое файла `.git` в этом корне;
 *   `null`, если `.git` — каталог, а не файл, либо прочесть не удалось
 * @param {string|null} params.explicitRoot корень, названный доводом `--root=`
 *   или переменной `PIPELINE_ROOT`; `null`, если не назван
 * @returns {{ launch: boolean, message: string|null, mainWorktree: string|null }}
 */
export function decideLaunch({ root, gitFile = null, explicitRoot = null }) {
  const main = mainWorktreeOf(gitFile);

  // Названный вслух корень снимает отказ: выбор сделан человеком, а не угадан.
  // Проверяется до разбора ссылки, но после него в отчёте всё равно видно,
  // из какого дерева запускались, — поле сохраняется.
  if (explicitRoot) return { launch: true, message: null, mainWorktree: main };

  if (!main) return { launch: true, message: null, mainWorktree: null };

  return { launch: false, message: refusal(root, main), mainWorktree: main };
}
