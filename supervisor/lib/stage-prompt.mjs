/**
 * Промпт назначения: всё, что этапу нужно знать, одним куском.
 *
 * Прежде это была пара файлов рядом со слотом — само назначение и выписка
 * задачи с журналом. Файлы существовали не от хорошей жизни: решал один
 * (оркестратор), а работал другой (сессия, проснувшаяся по расписанию),
 * и передать что-либо иначе как через диск они не могли.
 *
 * Теперь порождает тот же, кто решает, — и передаёт прямо в промпт. Ни
 * слота, ни выписки, ни окна, в котором выписка успевает разойтись
 * с бэклогом.
 *
 * Правила этапа сюда НЕ входят: они приходят отдельно, файлом в системный
 * промпт. Здесь только то, что меняется от задачи к задаче.
 */

/** Обрезать длинное, назвав обрезанное вслух. Молчаливая обрезка обманывает. */
function clip(text, limit) {
  if (!text || text.length <= limit) return text ?? '';
  return `${text.slice(0, limit)}\n\n[…обрезано, целиком — в журнале задачи…]`;
}

/**
 * Взять у длинного текста голову и хвост, назвав пропущенное числом.
 *
 * Нужно логу упавшего этапа: смысл там лежит по краям. В голове — сводка
 * исхода и отказанные действия, в хвосте — то, на чём всё оборвалось;
 * середина же бывает в сотни килобайт вывода сборки.
 *
 * Пропущенное называется числом знаков намеренно. Вердикт о причине выносят
 * по этому тексту, и читателю надо знать, велика ли дыра, в которую он
 * не смотрит.
 */
export function clipMiddle(text, head, tail) {
  const source = String(text ?? '');
  if (source.length <= head + tail) return source;
  const skipped = source.length - head - tail;
  return [
    source.slice(0, head),
    '',
    `[…пропущено ${skipped} знаков; целиком — в файле лога…]`,
    '',
    source.slice(-tail),
  ].join('\n');
}

/**
 * Собрать промпт назначения.
 *
 * @param {object} params
 * @param {object} params.assignment `taskId`, `stage`, `branch`, `path`,
 *                                   `continuation`, `reason`
 * @param {object} params.task       задача из бэклога
 * @param {string} params.journal    журнал задачи
 * @param {object[]} params.board    опись доски: по строке на задачу
 * @param {number} [params.journalLimit] сколько знаков журнала брать
 * @returns {string}
 */
export function stagePrompt({
  assignment,
  task,
  journal = '',
  board = [],
  journalLimit = 12000,
  stageLog = null,
}) {
  const lines = [];

  lines.push(
    `Ты — сессия-исполнитель конвейера. Делаешь ровно один переход состояния: ` +
      `${assignment.stage}. Правила этапа — в системном промпте.`,
    '',
    '## Назначение',
    '',
    '```json',
    JSON.stringify(
      {
        taskId: assignment.taskId,
        stage: assignment.stage,
        branch: assignment.branch ?? null,
        worktree: assignment.path ?? null,
        continuation: Boolean(assignment.continuation),
        reason: assignment.reason ?? null,
      },
      null,
      2,
    ),
    '```',
  );

  // Продолжение называется первой же строкой после назначения, а не мелким
  // полем. Возобновлённая сессия помнит свой ход мысли, но не знает, что её
  // прервали, — а прерванная работа почти всегда оставляет незавершённое.
  if (assignment.continuation) {
    lines.push(
      '',
      '**Это продолжение прерванного этапа.** Прежде всякой новой работы',
      'разберись, что уже сделано: незакоммиченные правки, неотправленные',
      'коммиты, отмеченные пункты списка задач. Найденный хвост дошли',
      'немедленно — неотправленный коммит для остальной машинерии',
      'не существует вовсе.',
    );
  }

  lines.push('', '## Задача', '', '```json', JSON.stringify(taskDigest(task), null, 2), '```');

  // Журнал читается обязательно: там лежит вердикт аудита, а аудит мог
  // пропустить предложение с оговорками, и оговорки эти нигде больше
  // не записаны.
  lines.push('', '## Журнал задачи', '', clip(journal, journalLimit) || '_пусто_');

  // Лог упавшего этапа — то единственное, чего нет ни у кого, кроме разбора,
  // и ради чего разбор затеян. Он приходит выдержкой, а не путём к файлу:
  // имя файла складывается из двух полей и его легко перепутать, лог бывает
  // в сотни килобайт, а перечислять каталог через оболочку исполнителю
  // запрещено — составная команда оборачивается молчаливым отказом.
  if (stageLog) {
    lines.push(
      '',
      `## Лог упавшего этапа (${stageLog.stage})`,
      '',
      `Файл: \`${stageLog.path}\``,
      '',
      stageLog.text
        ? ['```', clipMiddle(stageLog.text, 4000, 6000), '```'].join('\n')
        : '_Лога нет: этап либо не породился, либо супервизор умер прежде, ' +
            'чем записал. Это само по себе улика._',
    );
  }

  // Опись доски нужна сверкам, которым мало своей задачи: аудит ищет
  // пересечения с задачами в работе, разбор — дубликаты. Целиком бэклог
  // исполнителю не нужен и вреден: чем больше он о нём знает, тем сильнее
  // соблазн его править, а править бэклог ему нельзя.
  if (board.length > 0) {
    lines.push(
      '',
      '## Прочие задачи на доске',
      '',
      '```json',
      JSON.stringify(board, null, 2),
      '```',
    );
  }

  lines.push(
    '',
    '## Отчёт',
    '',
    'Верни отчёт **последним сообщением**, объектом JSON. Файлов с отчётом',
    'не создавай: ответ приходит туда же, откуда пришёл вопрос. Поясняющий',
    'текст вокруг JSON допустим.',
  );

  return lines.join('\n');
}

/**
 * Что из задачи нужно исполнителю.
 *
 * Не вся запись целиком: машинные поля вроде владельца и счётчиков попыток
 * ему ни к чему, а `attempts` — как раз наоборот, по нему видно, сколько
 * заходов уже сожжено.
 */
function taskDigest(task) {
  if (!task) return null;
  return {
    id: task.id,
    title: task.title,
    type: task.type,
    status: task.status,
    description: task.description ?? null,
    run: task.run ?? null,
    links: task.links ?? {},
    relates: task.relates ?? [],
    returnTo: task.returnTo ?? null,
    question: task.question ?? null,
    attempts: task.attempts ?? {},
  };
}
