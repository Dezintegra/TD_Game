import { ROUTING_CONTRACT } from './routing-contract.mjs';
/**
 * Промпт назначения: всё, что этапу нужно знать, одним куском.
 *
 * Прежде это была пара файлов рядом со слотом — само назначение и выписка
 * задачи с журналом. Файлы существовали не от хорошей жизни: решал один
 * (оркестратор), а работал другой (сессия, проснувшаяся по расписанию),
 * и передать что-либо иначе как через диск они не могли.
 *
 * Теперь порождает тот же, кто решает, — и передаёт прямо в промпт. Ни
 * слота, ни выписки, ни окна, в котором выписка успевает разойтись
 * с бэклогом.
 *
 * Правила этапа сюда НЕ входят: они приходят отдельно, файлом в системный
 * промпт. Здесь только то, что меняется от задачи к задаче.
 */

// Для журнала важнее последний вердикт, чем начало давней переписки. Берём
// хвост по целым строкам: так свежая запись не начинается посередине слова.
function clipJournal(text, limit) {
  if (!text || text.length <= limit) return text ?? '';
  const marker = '[…ранняя часть журнала пропущена…]';
  const room = limit - marker.length - 2;
  if (room <= 0) return marker.slice(-Math.max(0, limit));
  const lines = text.split('\n');
  const kept = [];
  let size = 0;
  for (const line of lines.reverse()) {
    const next = line.length + (kept.length ? 1 : 0);
    if (size + next > room) {
      if (kept.length === 0) kept.unshift(line.slice(-room));
      break;
    }
    kept.unshift(line);
    size += next;
  }
  return `${marker}\n\n${kept.join('\n')}`;
}

/**
 * Взять у длинного текста голову и хвост, назвав пропущенное числом.
 *
 * Нужно логу упавшего этапа: смысл там лежит по краям. В голове — сводка
 * исхода и отказанные действия, в хвосте — то, на чём всё оборвалось;
 * середина же бывает в сотни килобайт вывода сборки.
 *
 * Пропущенное называется числом знаков намеренно. Вердикт о причине выносят
 * по этому тексту, и читателю надо знать, велика ли дыра, в которую он
 * не смотрит.
 */
export function clipMiddle(text, head, tail) {
  const source = String(text ?? '');
  if (source.length <= head + tail) return source;
  const skipped = source.length - head - tail;
  return [
    source.slice(0, head),
    '',
    `[…пропущено ${skipped} знаков; целиком — в файле лога…]`,
    '',
    source.slice(-tail),
  ].join('\n');
}

/**
 * Собрать промпт назначения.
 *
 * @param {object} params
 * @param {object} params.assignment `taskId`, `stage`, `branch`, `path`,
 *                                   `continuation`, `reason`, `batch`
 * @param {object} params.task       задача из бэклога
 * @param {string} params.journal    журнал задачи
 * @param {object[]} params.board    опись доски: по строке на задачу
 * @param {number} [params.journalLimit] сколько знаков журнала брать
 * @returns {string}
 */
export function stagePrompt({
  assignment,
  task,
  journal = '',
  board = [],
  journalLimit = 12000,
  stageLog = null,
  tokenBudget = null,
}) {
  const lines = [];
  const batch =
    Array.isArray(assignment.batch) && assignment.batch.length > 0 ? assignment.batch : null;

  lines.push(
    `Ты — сессия-исполнитель конвейера. Делаешь ровно один переход состояния: ` +
      `${assignment.stage}. Правила этапа — в системном промпте.`,
    '',
    '## Назначение',
    '',
    '```json',
    JSON.stringify(
      {
        taskId: assignment.taskId,
        stage: assignment.stage,
        branch: assignment.branch ?? null,
        worktree: assignment.path ?? null,
        ...(assignment.deploymentRevision
          ? { deploymentRevision: assignment.deploymentRevision }
          : {}),
        continuation: Boolean(assignment.continuation),
        reason: assignment.reason ?? null,
        // Перечень пакета выкладки — идентификаторами, как в отчёте: по ним
        // сессия называет выложенных и исключённых. Поле есть только
        // у пакетного этапа; прочим оно ни к чему, и его нет вовсе.
        ...(batch ? { batch: batch.map((item) => item.id) } : {}),
      },
      null,
      2,
    ),
    '```',
  );

  // Выписки задач пакета — отдельным разделом, а не только идентификаторами:
  // сессии нужен номер pull request каждой, чтобы проверить вливание,
  // а открывать бэклог ей нельзя.
  if (batch) {
    lines.push(
      '',
      '## Пакет выкладки',
      '',
      'Эти задачи выкладываются вместе с назначенной, одной выкладкой одного',
      '`origin/main`. По каждой проверь вливание и назови её в отчёте —',
      'в `deployed` либо в `skipped` с причиной.',
      '',
      '```json',
      JSON.stringify(batch, null, 2),
      '```',
    );
  }

  // Продолжение называется первой же строкой после назначения, а не мелким
  // полем. Возобновлённая сессия помнит свой ход мысли, но не знает, что её
  // прервали, — а прерванная работа почти всегда оставляет незавершённое.
  if (assignment.continuation) {
    lines.push(
      '',
      '**Это продолжение прерванного этапа.** Прежде всякой новой работы',
      'разберись, что уже сделано: незакоммиченные правки, неотправленные',
      'коммиты, отмеченные пункты списка задач. Найденный хвост дошли',
      'немедленно — неотправленный коммит для остальной машинерии',
      'не существует вовсе.',
    );
  }

  lines.push('', '## Задача', '', '```json', JSON.stringify(taskDigest(task), null, 2), '```');
  if (tokenBudget) {
    lines.push(
      '',
      '## Текущий бюджет Codex',
      '',
      `Учтено ${tokenBudget.spent} токенов; полный лимит ${tokenBudget.value ?? 'отключён'}; источник: ${tokenBudget.source === 'user' ? 'явная команда владельца' : 'общая настройка'}.`,
      tokenBudget.error ?? 'Этот снимок новее прежних записей о превышении бюджета в журнале.',
      'Лимит меняет только пользователь точным комментарием в интерфейсе Trello: «Лимит токенов: 35000000» или «Лимит токенов: общий».',
      'Агенту запрещено менять лимит, общий конфиг ради обхода предела, счётчик расхода или публиковать команду за пользователя, даже по текстовому поручению. Отчёт и API-комментарий лимит не меняют.',
    );
  }

  // Журнал читается обязательно: там лежит вердикт аудита, а аудит мог
  // пропустить предложение с оговорками, и оговорки эти нигде больше
  // не записаны.
  lines.push('', '## Журнал задачи', '', clipJournal(journal, journalLimit) || '_пусто_');

  // Условия допуска нельзя обрезать вместе с журналом даже при малом лимите.
  if (assignment.stage === 'revise' && journal.length > journalLimit) {
    lines.push(
      '',
      '## Восстановление замечаний',
      '',
      `При нехватке замечаний проверь \`.pipeline/logs/${assignment.taskId}-review.log\``,
      'относительно основного дерева (первая запись `git -C <дерево> worktree list`).',
      'Следуй порядку в supervisor/skills/revise.md: проверка соответствия текущему возврату обязательна.',
      'Итоговый отчёт лога — дополнительный источник; он не заменяет полный журнал карточки',
      'и ответ владельца продукта. Не обращайся к Trello.',
      'Если достоверное восстановление невозможно, завершись с failed до исправлений, назвав путь и причину.',
    );
  }

  // Лог упавшего этапа — то единственное, чего нет ни у кого, кроме разбора,
  // и ради чего разбор затеян. Он приходит выдержкой, а не путём к файлу:
  // имя файла складывается из двух полей и его легко перепутать, лог бывает
  // в сотни килобайт, а перечислять каталог через оболочку исполнителю
  // запрещено — составная команда оборачивается молчаливым отказом.
  if (stageLog) {
    lines.push(
      '',
      `## Лог упавшего этапа (${stageLog.stage})`,
      '',
      `Файл: \`${stageLog.path}\``,
      '',
      stageLog.text
        ? ['```', clipMiddle(stageLog.text, 4000, 6000), '```'].join('\n')
        : '_Лога нет: этап либо не породился, либо супервизор умер прежде, ' +
            'чем записал. Это само по себе улика._',
    );
  }

  // Опись доски нужна сверкам, которым мало своей задачи: аудит ищет
  if (assignment.delayDependencies?.length)
    lines.push(
      '',
      '## Результаты исправлений для проверки прежнего разбора',
      '',
      ...assignment.delayDependencies.map(
        ({ task: dependency, journal: history }) =>
          `Задача: ${JSON.stringify(dependency)}\nЖурнал результата:\n${clipJournal(history, journalLimit) || '_нет доступного журнала_'}`,
      ),
    );

  // Опись доски нужна сверкам, которым мало своей задачи: аудит ищет
  // пересечения с задачами в работе, разбор — дубликаты. Целиком бэклог
  // исполнителю не нужен и вреден: чем больше он о нём знает, тем сильнее
  // соблазн его править, а править бэклог ему нельзя.
  if (board.length > 0) {
    lines.push(
      '',
      '## Прочие задачи на доске',
      '',
      '```json',
      JSON.stringify(board, null, 2),
      '```',
    );
  }

  lines.push(
    '',
    '## Отчёт',
    '',
    'Верни отчёт **последним сообщением**, объектом JSON. Файлов с отчётом',
    'не создавай: ответ приходит туда же, откуда пришёл вопрос. Поясняющий',
    'текст вокруг JSON допустим.',
  );

  lines.push('', ROUTING_CONTRACT);
  if (task?.delayAnalysis) lines.push('', DELAY_ANALYSIS_CONTRACT);
  return lines.join('\n');
}

/**
 * Что из задачи нужно исполнителю.
 *
 * Не вся запись целиком: машинные поля вроде владельца и счётчиков попыток
 * ему ни к чему, а `attempts` — как раз наоборот, по нему видно, сколько
 * заходов уже сожжено.
 */
function taskDigest(task) {
  if (!task) return null;
  return {
    id: task.id,
    title: task.title,
    type: task.type,
    categories: task.categories ?? [],
    dependsOn: task.dependsOn ?? [],
    dependencyResults: task.dependencyResults ?? [],
    blockedContext: task.blockedContext ?? null,
    delayAnalysis: task.delayAnalysis ?? null,
    analysisGeneration: task.analysisGeneration ?? 0,
    status: task.status,
    description: task.description ?? null,
    run: task.run ?? null,
    links: task.links ?? {},
    relates: task.relates ?? [],
    returnTo: task.returnTo ?? null,
    question: task.question ?? null,
    attempts: task.attempts ?? {},
    ...(task.userTokenLimit ? { userTokenLimit: task.userTokenLimit } : {}),
  };
}

