import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';

// Сторож контракта инструкции, не имитация решения модели по синтетическому логу.
const skill = readFileSync(new URL('../skills/revise.md', import.meta.url), 'utf8');
const recovery = skill
  .split('**Восстановление неполных замечаний.**')[1]
  ?.split('## Порядок работы')[0];

describe('допуск резервного источника замечаний в revise', () => {
  it('предписывает точный источник основного дерева без Trello', () => {
    for (const part of [
      'даже без маркера обрезки',
      '.pipeline/logs/<taskId>-review.log',
      'первая запись',
      'git -C <дерево> worktree list',
      '<основное дерево>/.pipeline/logs/<taskId>-review.log',
      'Не обращайся',
      'к Trello',
    ])
      expect(recovery).toContain(part);
  });

  it('проверяет шапку и полный итог, а не черновой stdout', () => {
    const block = recovery.split('**Шапка и итог.**')[1].split('**Именно текущий заход.**')[0];
    for (const part of [
      '`задача`, `этап`, `сессия`, `начат`',
      'непустая сессия, корректное время начала',
      '--- итоговый текст ---',
      '--- stdout ---',
      '`taskId`, `stage: review`, `outcome: rejected`',
      'ссылки change/PR должны совпадать',
      'не заменяет исход отчёта',
      'stdout/stderr не являются итоговыми замечаниями',
    ])
      expect(block).toContain(part);
  });

  it('требует доказать текущий заход и отвергает совпадение только задачи и даты', () => {
    const block = recovery.split('**Именно текущий заход.**')[1].split('**Полнота.**')[0];
    for (const part of [
      'Ссылка на сессию/начало',
      'должна совпасть с шапкой',
      'отличает',
      'его от прежних заходов',
      'временные отметки и последовательность',
      'событий на противоречия',
      'совпадение taskId/PR',
      'повторяющийся вердикт недостаточны',
      'актуальность не доказана',
    ])
      expect(block).toContain(part);
  });

  it('останавливает до исправлений при отсутствии, несовпадении и неполноте источника', () => {
    for (const part of [
      'Если файла нет, чтение недоступно',
      'источник относится к другому заходу',
      'связь или полнота не доказаны',
      '`outcome: failed` **до исправлений**',
      '`summary` укажи путь и конкретную причину',
      'Оборванный JSON, другой исход',
      'отсутствующий необходимый ответ',
      'Пересказ ответа владельца в логе не заменяет',
      'Лог не заменяет полный журнал карточки и актуальную спецификацию',
      '`summary` и `decisions`',
      'путь, сессию, начало и конкретное основание допуска',
      'только восстановленную часть',
    ])
      expect(recovery).toContain(part);
    expect(skill).toMatch(
      /5\. \*\*Собери список[\s\S]*без достоверного полного перечня исправления не начинай[\s\S]*6\. \*\*Подтяни/,
    );
  });

  it('сохраняет отдельный путь текущего красного CI', () => {
    const block = recovery.split('**Причина возврата.**')[1].split('**Шапка и итог.**')[0];
    expect(block).toContain('`review → revise`');
    expect(block).toContain('нужна явная привязка текущего возврата');
    expect(block).toContain('`pr → revise`');
    expect(block).toContain('проверки текущего PR штатным порядком шага 7');
    expect(block).toContain('старый review.log не подменяет причину возврата');
  });
});
