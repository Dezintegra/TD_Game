/**
 * Покрытие команд правилами разрешений: пропустит ли среда то, что этапу
 * предписано его скиллом.
 *
 * Мерка живёт в коде инструмента, а не в теле теста, потому что читателей
 * у неё двое и отвечают они на один вопрос: сторож набора («настройка ещё
 * годится?») и сканер («выдавать ли сессию этому этапу?»). Разойтись их
 * ответы могли бы только молча — сторож зеленел бы на настройке, при которой
 * сканер держит задачи, либо наоборот. Цена такого молчания уже заплачена:
 * задача 0143-storozh чинила сторожа, отбрасывавшего хвост `:*` безусловно
 * и потому зеленевшего на настройке, где среда отказывает каждой команде.
 */

/** Оболочки, которыми этап пользуется. Правило одной о правах в другой молчит. */
export const SHELLS = ['Bash', 'PowerShell'];

/**
 * Разбор правила: обёртка оболочки снята, тело отдано вместе с признаком
 * формы. Форм две, и среда мерит их по-разному:
 *
 * - хвост `:*` (`Bash(gh pr:*)`) означает «с любыми доводами» — приставка;
 * - без хвоста (`Bash(gh pr view)`) правило совпадает с командой целиком —
 *   точная форма.
 *
 * Разницу подтверждает сторож «перечень сценариев открыт точной формой»
 * в `transitions.test.mjs`: он целиком держится на том, что `Bash(pnpm run)`
 * без хвоста НЕ открывает `pnpm run verify`. Мерить обе формы приставкой
 * значило бы держать две противоположные мерки одного синтаксиса — и однажды
 * на этом ошибиться.
 *
 * Для чужой оболочки возвращается `null` — правило `Bash(...)` о правах
 * в PowerShell не говорит ничего.
 */
export const patternOf = (rule, shell) => {
  const wrapped = new RegExp(`^${shell}\\((.*)\\)$`).exec(rule);
  if (!wrapped) return null;
  const body = wrapped[1];
  return body.endsWith(':*') ? { body: body.slice(0, -2), exact: false } : { body, exact: true };
};

/**
 * Сверка команды с правилом — той же меркой, какой её меряет среда, и порознь
 * для каждой формы:
 *
 * - приставка закрывается границей слова (`\s` либо конец строки): без неё
 *   `gh pr` покрыло бы выдуманное `gh press`, и сторож зеленел бы
 *   на настройке, которой в действительности не соответствует ничего;
 * - точная форма закрывается концом строки: команда с доводами таким
 *   правилом не покрыта вовсе.
 *
 * Звёздочка **внутри** тела (`git -C * push`) стоит вместо довода и толкуется
 * одинаково у обеих форм: речь тут только о хвосте.
 */
export const coversCommand = (pattern, command) => {
  const body = pattern.body
    .split('*')
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&'))
    .join('.*');
  return new RegExp(`^${body}${pattern.exact ? '$' : '(\\s|$)'}`).test(command);
};

/**
 * Перечень команд, не покрытых настройкой, с именем оболочки у каждой.
 * Команда покрыта, только если совпала хотя бы с одним правилом `allow`
 * и не совпала ни с одним правилом `deny`: запрет, оказавшийся приставкой
 * собственного разрешения, уже отнимал у этапа работу (см. `$cleanupNote`
 * в stage-settings.json).
 *
 * Запреты меряются той же меркой, что разрешения, а не строже. Сторож,
 * объявляющий непокрытой команду, которую среда пропускает, лечится
 * единственным доступным способом — ослаблением настройки ради успокоения
 * теста: правят не сторожа, а то, что он сторожит.
 */
export const uncoveredCommands = (permissions, commands) => {
  const guilty = [];
  for (const shell of SHELLS) {
    const patterns = (rules) =>
      (rules ?? []).map((rule) => patternOf(rule, shell)).filter((pattern) => pattern !== null);
    const allow = patterns(permissions.allow);
    const deny = patterns(permissions.deny);
    for (const command of commands) {
      const allowed = allow.some((pattern) => coversCommand(pattern, command));
      const denied = deny.some((pattern) => coversCommand(pattern, command));
      if (!allowed || denied) guilty.push(`${shell}: ${command}`);
    }
  }
  return guilty;
};

/**
 * Что этап зовёт такого, чей запуск решают правила разрешений.
 *
 * Перечни короткими не бывают по договорённости: сюда идёт **каждая** команда
 * скилла, чей запуск решают правила, а не выборка из них. Выборка годится
 * там, где спрашивают «жив ли путь», и не годится там, где спрашивают
 * «пройдёт ли этап целиком»: правило приставкой покрывает только свою
 * приставку, правило точной формы — только свою строку.
 *
 * Единственное исключение названо прямо — `review`, чей перечень достался
 * от прежнего сторожа вливания осознанной выборкой; подробности у него же.
 */
export const STAGE_COMMANDS = {
  /**
   * Команды, которыми этап ревью доводит изменение до `main`. Список короткий
   * нарочно: сторожить надо тот путь, отказ на котором обнаружится только там,
   * где рядом нет человека, — посреди вливания.
   */
  review: ['gh pr view 1 --json state,isDraft', 'gh pr ready 1', 'gh pr merge 1 --merge'],

  /** Все удалённые проверки, замеры и выкладка из deploy.md. */
  deploy: [
    'node scripts/deploy-remote.mjs "stat -c %y ~/td"',
    'node scripts/deploy-remote.mjs "curl -fsS https://dezintegra.net/health"',
    'node scripts/deploy-remote.mjs "true"',
    'node scripts/deploy-remote.mjs "grep -o \'^[A-Z_]*\' ~/td/.env"',
    'pnpm e2e:perf -- --check-only',
    'pnpm e2e:perf',
    'pnpm e2e:perf -- --history',
    'node scripts/deploy.mjs --ref <хеш> --no-perf',
  ],
};

/**
 * Непокрытые команды этапа. Этап, которому команд не объявлено, не задержится
 * никогда: молчание перечня значит «не проверяли», а не «всё плохо».
 *
 * Перечень отдан доводом нарочно. Он нужен проверкам сканера: боевой перечень
 * объявлен `review` и `deploy`, а из очереди задача уходит в `design`,
 * `benchmark` или `triage` — на настоящем перечне та ветка сегодня не может
 * сработать, и написанная на нём проверка была бы вечнозелёной.
 */
export const uncoveredForStage = (permissions, stage, commands = STAGE_COMMANDS) =>
  uncoveredCommands(permissions, commands[stage] ?? []);
