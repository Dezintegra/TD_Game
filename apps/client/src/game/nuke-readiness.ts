import { TICKS_PER_SECOND } from '@td/shared';
import type { PlayerState, WorldState } from '@td/sim';

/**
 * Сколько секунд ждать до следующего пуска ядерной ракеты.
 *
 * Отдельным модулем, а не строкой в сборке снимка, ровно по одной
 * причине: здесь есть решение, которое можно принять неправильно,
 * и его надо проверить тестом. Сборка снимка живёт в `bootstrap.ts`
 * вместе со сценой PixiJS, и вытащить оттуда одну функцию в тест
 * не получится.
 */

/**
 * Ноль означает «установка готова».
 *
 * Округление ВВЕРХ, а не к ближайшему. «Осталось 0 секунд» при
 * неостывшей установке — это обещание, которого интерфейс не сдержит:
 * игрок нажмёт, а ядро откажет. Пусть лучше единица подержится лишний
 * кадр, чем ноль появится раньше готовности.
 *
 * Отрицательного не возвращает никогда: тик готовности в прошлом
 * означает «давно готова», а не «просрочено на минуту».
 */
export const nukeWaitSeconds = (world: WorldState, player: PlayerState): number =>
  Math.max(0, Math.ceil((player.nukeReadyAtTick - world.tick) / TICKS_PER_SECOND));

/** Остыла ли установка. То же условие, что и в ядре при пуске. */
export const isNukeReadyFor = (world: WorldState, player: PlayerState): boolean =>
  world.tick >= player.nukeReadyAtTick;
