/**
 * Плотность запекания — во сколько раз запечённая текстура подробнее
 * показа при единичном масштабе.
 *
 * Величина здесь одна на всю сцену намеренно. До этого модуля её выбирало
 * каждое место запекания само: машины брали плотность экрана, дуги —
 * двойку, а скалы и командный центр — единицу, то есть выбрасывали
 * плотность экрана, ради которой `app.init` её и запрашивает. Разъезд
 * произошёл молча, и заметен он стал только с появлением зума.
 *
 * Почему плотность вообще нужна с запасом: поле масштабируется
 * приближением до четырёхкратного, а запечённая текстура растягивается
 * вместе с ним. Запас отодвигает начало растяжения, но не отменяет его —
 * полная чёткость на пределе приближения стоила бы шестнадцатикратной
 * памяти, и это названный компромисс, а не недоделка.
 */

/**
 * Запас плотности на приближение.
 *
 * Двойка, а не четвёрка: память растёт квадратом, и четырёхкратный запас
 * стоил бы шестнадцатикратной памяти ради чёткости на самом пределе
 * приближения, где игрок бывает редко. Двойка снимает половину
 * растяжения за четверть этой цены.
 */
export const ZOOM_OVERSAMPLE = 2;

/**
 * Потолок плотности запекания.
 *
 * Нужен потому, что плотность экрана входит в произведение. Телефон
 * сообщает `devicePixelRatio = 3`, и без потолка запас потребовал бы
 * шестикратной плотности, то есть тридцатишестикратной памяти против
 * нынешней. Потолок означает: на плотном экране запас съедается самой
 * плотностью экрана — и это верный порядок, там и без запаса видно
 * больше.
 */
export const MAX_BAKE_DENSITY = 3;

/**
 * Бюджет видеопамяти под слой запечённых скал, в мегабайтах.
 *
 * Скалы — единственный слой, чья суммарная площадь растёт вместе
 * со стороной карты, поэтому множитель им не годится: на карте
 * для двоих двукратный запас стоит около сорока мегабайт, а на карте
 * для четверых — почти сто двадцать. Бюджет ведёт себя ровно наоборот:
 * плотность сама опускается на большой карте, и слой занимает свои
 * шестьдесят четыре мегабайта при любом размере.
 */
export const ROCK_BAKE_BUDGET_MB = 64;

/**
 * Средняя площадь запечённой скальной клетки, в точках.
 *
 * Измерено 29.08.2026 той же формулой, какой габариты считает
 * `buildCellMesh`: пять карт 38×38, 186–236 скальных клеток,
 * 2,48–3,30 Мпикс суммарно. На клетку выходит 13 300–14 000 точек,
 * наибольшая клетка — 97×271.
 *
 * Оценки достаточно, и точный обход тут не нужен: габариты клетки даёт
 * тот же цикл по шестистам вершинам, что и построение сетки, то есть
 * самая дорогая часть запекания. Пройти его дважды ради уточнения,
 * которое даёт полпроцента плотности, значило бы удвоить работу
 * при старте матча.
 */
export const ROCK_CELL_AREA_PX = 14_000;

/** Точка текстуры — четыре байта: RGBA. */
const BYTES_PER_PIXEL = 4;

/**
 * Во сколько раз мип-уровни удорожают текстуру.
 *
 * Сумма 1 + 1/4 + 1/16 + … сходится к четырём третям: каждый следующий
 * уровень вчетверо меньше предыдущего. Учитывается в бюджете, иначе слой
 * скал вышел бы за него ровно на эту треть.
 */
const MIPMAP_OVERHEAD = 4 / 3;

/**
 * Плотность запекания для сцены целиком.
 *
 * Считается от плотности пикселей экрана: на подробном экране запечённое
 * обязано быть подробнее, а не крупнее.
 */
export const sceneBakeDensity = (screenDensity: number): number =>
  Math.min(Math.max(screenDensity, 1) * ZOOM_OVERSAMPLE, MAX_BAKE_DENSITY);

/**
 * Плотность запекания слоя скал.
 *
 * Наибольшая, при которой слой укладывается в бюджет, но не выше общей
 * плотности сцены: подробнее сцены скалам быть незачем, а беднее —
 * приходится, когда карта велика.
 *
 * Карта без скал возвращает плотность сцены, а не бесконечность: делить
 * на нулевую площадь нельзя, а запекать в этом случае всё равно нечего.
 */
export const rockBakeDensity = (sceneDensity: number, rockCells: number): number => {
  if (rockCells <= 0) return sceneDensity;

  const budgetPx = (ROCK_BAKE_BUDGET_MB * 1024 * 1024) / (BYTES_PER_PIXEL * MIPMAP_OVERHEAD);
  const area = rockCells * ROCK_CELL_AREA_PX;

  return Math.min(sceneDensity, Math.max(1, Math.sqrt(budgetPx / area)));
};
