import { TELEMETRY_EVERY_MS } from '@td/shared';
import type { ReadingMoment, ReadingRows } from '@td/shared';

/**
 * Отправка показаний серверу.
 *
 * Отдельным модулем, а не десятком строк внутри игрового модуля,
 * по одной причине: игровой модуль тянет за собой PixiJS и сцену,
 * то есть проверяется только сквозной проверкой. Здесь же проверять
 * есть что — часы, счётчик снимков и поведение при неудаче.
 *
 * ## Часы, а не такты и не кадры
 *
 * Расписаний в клиенте три: номер такта, кадр отрисовки и местные
 * часы. Такт двигается миром, кадр — браузером, и оба замирают ровно
 * тогда, когда приборам есть что сказать: мир встал колом, вкладка
 * ушла в фон. Часы не замирают.
 *
 * Фоновые таймеры браузер придерживает — не чаще раза в секунду, —
 * но не останавливает. На пятисекундном шаге это не меняет ничего.
 *
 * ## Почему повтор безвреден
 *
 * Копилки накопительные: снимок несёт всё, что скопилось с начала
 * матча. Сервер вливает в общие ряды разность с прошлым снимком того же
 * билета, поэтому отправить копилку хоть сорок раз — то же самое, что
 * отправить один раз в конце. Отсюда и отсутствие отметки «уже
 * отправлено», которая была обязательна, пока сервер вливал целиком.
 */
export interface ReadingsSender {
  /** Отправить снимок сейчас: исход матча, выход в меню, закрытая вкладка. */
  send(): void;
  /** Остановить часы. Последний снимок отправляет вызывающий. */
  stop(): void;
}

export interface ReadingsSenderOptions {
  /** Адрес службы: к нему дописывается `/api/telemetry`. */
  readonly apiUrl: string;
  /**
   * Билет матча.
   *
   * По нему сервер опознаёт матч и сторону. Ни того ни другого клиент
   * не сообщает вовсе: точка приёма смотрит в интернет, и верить тому,
   * что клиент о себе говорит, ей нельзя.
   */
  readonly ticket: string;
  /** Снять показания в момент отправки. */
  readonly collect: () => ReadingRows & ReadingMoment;
  readonly everyMs?: number;
  /** Чем отправлять. Внедрено ради проверок. */
  readonly post?: (url: string, init: RequestInit) => Promise<unknown>;
}

export const createReadingsSender = (options: ReadingsSenderOptions): ReadingsSender => {
  const everyMs = options.everyMs ?? TELEMETRY_EVERY_MS;
  const post = options.post ?? ((url, init) => fetch(url, init));

  let seq = 0;

  const send = (): void => {
    seq += 1;

    const body = JSON.stringify({
      ticket: options.ticket,
      seq,
      ...options.collect(),
    });

    // Неудача отправки на матч влиять не должна ни в каком виде:
    // диагностика не имеет права ломать игру. Отсюда и молчаливый
    // перехват, и `void` у вызова.
    void post(`${options.apiUrl}/api/telemetry`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body,
      // Переживает выгрузку страницы: последний снимок уходит как раз
      // тогда, когда вкладку закрывают.
      keepalive: true,
    }).catch(() => {
      // Не дошло — не беда. Игрок об этом знать не должен.
    });
  };

  const timer = setInterval(send, everyMs);

  return {
    send,

    stop() {
      clearInterval(timer);
    },
  };
};
