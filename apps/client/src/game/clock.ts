import { MS_PER_TICK } from '@td/shared';

/**
 * Часы кадра: перевод целого номера тика в дробный.
 *
 * Зачем они нужны. Мир идёт тридцатью тиками в секунду, монитор показывает
 * шестьдесят кадров и больше. Всё, что в отрисовке считается от номера тика,
 * обновляется вдвое реже кадров: искра стоит на месте два кадра, потом
 * прыгает. На покачивании юнита этого почти не видно — оно медленное,
 * — а на взрыве длиной в полсекунды видно сразу.
 *
 * Часы решают это, не трогая ни мир, ни сеть: они запоминают, когда номер
 * тика изменился в последний раз, и добавляют к нему долю реального
 * времени, прошедшего с той поры.
 *
 * Почему не интерполяция состояний. Чтобы получить промежуточный кадр
 * честно, пришлось бы смешивать положения сотен сущностей между двумя
 * снимками мира. А нужна ровно одна величина — время, — и она берётся
 * из часов браузера напрямую.
 *
 * Время сюда передаётся, а не читается изнутри. Так часы остаются чистой
 * функцией от своих входов и проверяются без подмены `performance`.
 */
export interface FrameClock {
  /**
   * Дробный номер тика: целый плюс доля прошедшего времени.
   * Вызывается один раз на кадр — он же и отмечает смену тика.
   */
  sample(tick: number, nowMs: number): number;
}

/**
 * Наибольшая допустимая доля тика.
 *
 * Строго меньше единицы, и это важно. При прижатии к единице дробный номер
 * сравнялся бы со следующим целым, и застрявший кадр показал бы взрыв
 * на тик вперёд, а следующий за ним — снова назад. Дёрганье вперёд-назад
 * заметнее, чем остановка: остановку глаз принимает за задержку, скачок
 * назад — за поломку.
 */
const MAX_TICK_FRACTION = 0.999;

export const createFrameClock = (): FrameClock => {
  let lastTick = Number.NaN;
  let lastTickAtMs = 0;

  return {
    sample(tick, nowMs) {
      // Номер тика может не только вырасти, но и упасть: предсказание
      // пересобирается откатом, и мир на кадре бывает младше, чем
      // на предыдущем. Любая смена номера — начало отсчёта заново.
      if (tick !== lastTick) {
        lastTick = tick;
        lastTickAtMs = nowMs;
        return tick;
      }

      // Часы браузера между вкладками не обязаны быть монотонными,
      // а кадр может застрять на секунду. Обе беды лечит одно прижатие.
      const fraction = (nowMs - lastTickAtMs) / MS_PER_TICK;

      return tick + Math.max(0, Math.min(MAX_TICK_FRACTION, fraction));
    },
  };
};
