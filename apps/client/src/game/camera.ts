import { CELL_SCREEN_HEIGHT_PX, MAP_BOUNDS } from './iso.js';

/**
 * Сколько клеток по вертикали обязано остаться игроку.
 *
 * Число не про красоту раскладки, а про дальность стрельбы. До появления
 * масштаба телефон в ландшафте показывал 4,3 клетки: 375 точек экрана
 * минус 94 верхней полосы минус 64 тулбара давали полю 217, а клетка
 * занимает 50,91. При четырёх клетках стрелок и его мишень на экране
 * одновременно не помещаются НИ ДЛЯ ОДНОГО вида юнита — то есть игрок
 * не видит, кто в него стреляет, и ведёт генерала вслепую.
 *
 * Десять — то, что запросил игрок словами «хотя бы 10, пусть мелко».
 * Если замер кадров покажет, что уменьшение картинки не по силам
 * телефону, разговор пойдёт про девять или восемь — и это разговор
 * с игроком, а не правка исподтишка.
 */
export const MIN_VISIBLE_ROWS = 10;

/**
 * Предел уменьшения. Предохранитель, а не расчёт.
 *
 * Окно высотой в двести точек потребовало бы 0,39 и превратило бы юнита
 * в четыре пикселя. Десять нечитаемых клеток хуже девяти читаемых,
 * поэтому уменьшение здесь останавливается.
 *
 * На настоящих телефонах предохранитель не срабатывает: худший случай —
 * ландшафт, где полю остаётся 311 точек, а это 0,611.
 */
export const MIN_SCALE = 0.4;

/** Насколько игрок вправе приблизить картинку относительно дефолта. */
export const MAX_ZOOM = 4;

/**
 * Дефолтный масштаб: столько, чтобы полю хватило клеток по вертикали.
 *
 * Считается ИЗ ВЫСОТЫ ПОЛЯ, а не задаётся отдельной величиной на каждый
 * размер экрана. Отдельная величина разошлась бы с высотами полос при
 * первой же правке раскладки, и разошлась бы молча: проверка сторожила бы
 * число, которого на экране уже нет.
 *
 * Единица — верхняя граница, и это обещание широкому экрану: на мониторе
 * полю достаётся пятнадцать клеток и без всякого масштабирования,
 * увеличивать там нечего. Картинка уменьшается, когда высоты не хватает,
 * и никогда не растёт сама.
 */
export const defaultScale = (fieldHeight: number): number => {
  const needed = MIN_VISIBLE_ROWS * CELL_SCREEN_HEIGHT_PX;

  return Math.min(1, Math.max(MIN_SCALE, fieldHeight / needed));
};

/** Приближение игрока: от дефолта (1) до четырёхкратного. */
export const clampZoom = (zoom: number): number => Math.min(MAX_ZOOM, Math.max(1, zoom));

/**
 * Действующий масштаб.
 *
 * Приближение хранится КРАТНОСТЬЮ дефолта, а не абсолютным числом.
 * Тогда поворот телефона пересчитывает дефолт, не трогая того, насколько
 * игрок приблизился: он остаётся в бою, а не выбрасывается на общий план.
 * Абсолютное значение после поворота оказалось бы либо ниже нового
 * дефолта, либо выше четырёхкратного — то есть за границей диапазона,
 * и его пришлось бы молча подрезать.
 */
export const scaleOf = (fieldHeight: number, zoom: number): number =>
  defaultScale(fieldHeight) * clampZoom(zoom);

/** Сколько клеток по вертикали видно полю при таком масштабе. */
export const visibleRows = (fieldHeight: number, scale: number): number =>
  fieldHeight / (CELL_SCREEN_HEIGHT_PX * scale);

/**
 * Камера.
 *
 * Хранит точку, на которую смотрит игрок, в экранных координатах мира —
 * то есть уже после проекции, но до сдвига контейнера.
 *
 * Движение камеры не перестраивает ничего: оно превращается в сдвиг
 * контейнера сцены, то есть в два числа. Именно поэтому прокрутка карты
 * стоит примерно ноль независимо от того, сколько геометрии на ней лежит.
 */
export interface Camera {
  readonly x: number;
  readonly y: number;
}

export { MAP_BOUNDS };

/** Камера, смотрящая в центр карты. */
export const createCamera = (): Camera => ({
  x: (MAP_BOUNDS.minX + MAP_BOUNDS.maxX) / 2,
  y: (MAP_BOUNDS.minY + MAP_BOUNDS.maxY) / 2,
});

/**
 * Ограничение камеры границами карты.
 *
 * Если карта по какому-то измерению меньше окна, камера по этому измерению
 * центрируется: иначе она болталась бы, показывая пустоту то с одной
 * стороны, то с другой.
 */
export const clampCamera = (
  camera: Camera,
  viewportWidth: number,
  viewportHeight: number,
): Camera => ({
  x: clampAxis(camera.x, MAP_BOUNDS.minX, MAP_BOUNDS.maxX, viewportWidth),
  y: clampAxis(camera.y, MAP_BOUNDS.minY, MAP_BOUNDS.maxY, viewportHeight),
});

const clampAxis = (value: number, min: number, max: number, viewport: number): number => {
  const half = viewport / 2;

  if (max - min <= viewport) return (min + max) / 2;

  return Math.min(Math.max(value, min + half), max - half);
};

export const moveCamera = (camera: Camera, dx: number, dy: number): Camera => ({
  x: camera.x + dx,
  y: camera.y + dy,
});
