import type { Graphics } from 'pixi.js';
import type { Point } from './iso.js';

/**
 * Окружность на земле — одна реализация на всё приложение.
 *
 * Проекция линейна, но круг она превращает в наклонный эллипс, поэтому
 * рисовать его средствами PixiJS (`graphics.circle`) нельзя: вышел бы круг
 * на ЭКРАНЕ, а не на ЗЕМЛЕ, а это разные фигуры — землю проекция сплющивает
 * поперёк взгляда на `GROUND_SQUASH`. Точки считаются в мире и проецируются
 * по одной.
 *
 * Проекция приходит параметром, потому что мест, где такой круг нужен,
 * два: поле подставляет `worldToScreen`, миникарта — `projectToMinimap`.
 * Второй, независимо написанной окружности здесь нет намеренно: правка
 * углов проекции, шага точек или формулы сплющивания попала бы в одну
 * копию и не попала бы в другую, и две картинки одного удара разошлись бы
 * молча — ровно та беда, о которой предупреждает `minimap.ts` про матрицу
 * проекции.
 *
 * Модуль отдельный, а не экспорт из `overlays.ts`: подсказки поверх поля
 * живут от намерения игрока, миникарта — от состояния мира, и общего
 * у них ровно одна геометрическая функция. Тянуть ради неё весь слой
 * подсказок значило бы тянуть заодно и управление свайпом, и сводку
 * игрока.
 */

/** Куда ложится точка мира: своя у поля, своя у миникарты. */
export type GroundProjection = (cellsX: number, cellsY: number) => Point;

/**
 * Ломаная по окружности радиуса `radiusCells` вокруг клетки `(centreX, centreY)`.
 *
 * Число отрезков — параметр, а не постоянная: круг на поле занимает сотни
 * точек экрана и требует полусотни отрезков, тот же круг на миникарте —
 * два десятка точек, и лишние отрезки там ничего не добавляют изображению,
 * а стоят столько же.
 *
 * Точек получается `steps + 1`: последняя совпадает с первой и замыкает
 * ломаную. `closePath` для этого не годится — вызывающий волен обвести
 * фигуру, а не залить, и незамкнутая обводка оставила бы прореху.
 */
export const traceGroundCircle = (
  graphics: Graphics,
  centreX: number,
  centreY: number,
  radiusCells: number,
  project: GroundProjection,
  steps: number,
): void => {
  for (let index = 0; index <= steps; index += 1) {
    const angle = (index / steps) * Math.PI * 2;
    const point = project(
      centreX + Math.cos(angle) * radiusCells,
      centreY + Math.sin(angle) * radiusCells,
    );

    if (index === 0) graphics.moveTo(point.x, point.y);
    else graphics.lineTo(point.x, point.y);
  }
};
