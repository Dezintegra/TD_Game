import { FillGradient } from 'pixi.js';

/**
 * Общие заготовки эффектов: свет, дым и полёт частицы.
 *
 * Модуль появился, когда у выстрела завелись собственные вспышки. До этого
 * всё перечисленное жило в `blasts.ts` и годилось одному разрушению;
 * теперь тем же светит выстрел, и держать две копии значило бы развести
 * взрыв и вспышку у ствола по разным мирам первой же правкой яркости.
 *
 * Здесь только то, что не зависит ни от вида события, ни от состояния
 * мира: как выглядит свет, как выглядит дым и куда за секунду улетает
 * брошенная частица.
 */

// ─────────────────────────────────────────────────────────────────────────
// Заливки
// ─────────────────────────────────────────────────────────────────────────

/**
 * Радиальные градиенты — то, чем свет и дым отличаются от плоских кружков.
 *
 * Заготовка строится один раз на цвет и назначение, а не на частицу.
 * Ключ здесь в режиме `local`: в нём градиент натягивается на габариты
 * той фигуры, которую заливает, поэтому одна и та же заготовка годится
 * и для искры в три пикселя, и для гриба в двадцать клеток. Без этого
 * пришлось бы строить текстуру на каждую частицу каждого кадра.
 *
 * Цвета приходят из дизайн-токенов и потому неизвестны на загрузке
 * модуля — отсюда кеш, а не константы.
 */
const gradientCache = new Map<number, FillGradient>();

const rgba = (color: number, alpha: number): string =>
  `#${color.toString(16).padStart(6, '0')}${Math.round(Math.max(0, Math.min(1, alpha)) * 255)
    .toString(16)
    .padStart(2, '0')}`;

const radialFill = (
  color: number,
  key: number,
  stops: readonly [number, number][],
): FillGradient => {
  const cacheKey = color * 8 + key;
  const cached = gradientCache.get(cacheKey);
  if (cached !== undefined) return cached;

  const gradient = new FillGradient({
    type: 'radial',
    center: { x: 0.5, y: 0.5 },
    innerRadius: 0,
    outerCenter: { x: 0.5, y: 0.5 },
    outerRadius: 0.5,
    colorStops: stops.map(([offset, alpha]) => ({ offset, color: rgba(color, alpha) })),
    textureSpace: 'local',
  });

  gradientCache.set(cacheKey, gradient);
  return gradient;
};

/**
 * Свет: яркая сердцевина и длинный мягкий спад.
 *
 * Спад именно длинный. Короткий даёт кружок с чётким краем, и на экране
 * это читается диском, а не светом; светится то, у чего не видно границы.
 */
export const glowFill = (color: number): FillGradient =>
  radialFill(color, 0, [
    [0, 1],
    [0.28, 0.62],
    [0.62, 0.18],
    [1, 0],
  ]);

/** Дым: плотное ядро, мягкая кромка. Клубится за счёт наложения нескольких. */
export const smokeFill = (color: number): FillGradient =>
  radialFill(color, 1, [
    [0, 0.9],
    [0.5, 0.5],
    [1, 0],
  ]);

/** Сбросить заготовки. Нужен тестам и смене палитры. */
export const resetEffectPaints = (): void => {
  gradientCache.clear();
};

// ─────────────────────────────────────────────────────────────────────────
// Полёт частицы
// ─────────────────────────────────────────────────────────────────────────

/**
 * Сопротивление воздуха для частиц, в обратных секундах.
 *
 * Без него частицы разлетаются равномерно, и выброс читается расходящимся
 * кольцом точек. С ним частица стартует резко и вязнет — ровно то, что
 * глаз ждёт и от взрыва, и от попадания.
 */
const DRAG = 3.2;

/**
 * Пройденный путь с сопротивлением: интеграл затухающей скорости.
 *
 * Вынесено наружу вместе с `particleHeight` ниже не для повторного
 * использования, а ради проверяемости. Экранная `y` в этой проекции несёт
 * и высоту, и положение на плоскости, поэтому «искра поднялась» по одному
 * лишь нарисованному пикселю не проверить: сдвиг по земле даёт ровно такое
 * же изменение. Выкладка проверяется там, где она однозначна.
 */
export const travel = (speed: number, seconds: number): number =>
  (speed * (1 - Math.exp(-DRAG * seconds))) / DRAG;

/** Ускорение свободного падения, клеток в секунду за секунду. */
const GRAVITY = 9;

/** Высота брошенного вверх тела. Ниже земли не опускается: оно на неё легло. */
export const particleHeight = (start: number, rise: number, seconds: number): number =>
  Math.max(0, start + rise * seconds - (GRAVITY * seconds * seconds) / 2);

// ─────────────────────────────────────────────────────────────────────────
// Кривые угасания
// ─────────────────────────────────────────────────────────────────────────

/** Плавное угасание от единицы к нулю на отрезке. */
export const fadeOver = (value: number, from: number, to: number): number => {
  if (value <= from) return 1;
  if (value >= to) return 0;
  return 1 - (value - from) / (to - from);
};

/** Плавное нарастание от нуля к единице на отрезке. */
export const riseOver = (value: number, from: number, to: number): number => {
  if (value <= from) return 0;
  if (value >= to) return 1;
  return (value - from) / (to - from);
};
