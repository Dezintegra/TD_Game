/**
 * Всё, что нужно знать о разряде, чтобы его разложить.
 *
 * Живёт здесь, а не в `arc-render.ts`, чтобы след выстрела мог о нём
 * говорить, не притаскивая за собой PixiJS: `shots.ts` рисует линиями
 * и о спрайтах знать не обязан.
 */
export interface ArcStyle {
  /**
   * Цвет стороны. Им красится ТОЛЬКО свечение и голова волны — само
   * тело молнии у обеих сторон одинаковое, сине-белое.
   *
   * Иначе зелёная молния перестаёт быть молнией и вдобавок теряется
   * среди прочих зелёных меток своей стороны.
   */
  readonly accent: number;
  /** Общая видимость: свой ярче чужого, догорающий бледнее свежего. */
  readonly alpha: number;
  /** Добивающий разряд толще. */
  readonly lethal: boolean;
  /** Зерно формы: из выстрела. */
  readonly seed: number;
  /** Номер тика: от него пляшет рассинхрон плиток. */
  readonly phase: number;
  /** Где фронт волны, либо `undefined`, если она уже прошла. */
  readonly front: number | undefined;
}

/** Отрезок на экране: от чего до чего. */
export interface ArcLine {
  readonly from: Point;
  readonly to: Point;
}

/**
 * Куда след выстрела складывает разряды. Реализуется отрисовкой.
 *
 * Отрезков ДВА, и это не удобство вызова. `bolt` — сам разряд, он висит
 * на высоте ствола и приходит в корпус цели; `ground` — та же линия
 * по земле, и на неё ложится свет. Свет, оставленный на высоте разряда,
 * читался бы вторым, размытым разрядом, а не отсветом на поле.
 */
export interface ArcSink {
  place(bolt: ArcLine, ground: ArcLine, style: ArcStyle): void;
}
