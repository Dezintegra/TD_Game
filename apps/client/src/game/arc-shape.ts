import type { Point } from './iso.js';

/**
 * Геометрия и арифметика разряда Теслы, собранного из плиток.
 *
 * Здесь нет ни PixiJS, ни видеокарты — только чистые выкладки: какой
 * формы плитка, сколько их укладывается в выстрел, какая плитка берётся
 * на этом тике и как по каналу бежит волна. Отрисовка живёт отдельно
 * (`arc-render.ts`), и разделение это не косметическое: выпечка требует
 * видеокарты и в тестах недоступна, а проверять надо именно то, что
 * лежит здесь.
 *
 * Почему разряд вообще собирается из плиток. Прежде он строился
 * ломаными прямо в `Graphics`, и это стоило дорого: PixiJS режет каждую
 * обводку на треугольники заново каждый кадр, а слой эффектов чистится
 * целиком. Замерено 24.08.2026 на настоящей видеокарте — пятнадцать
 * одновременных разрядов стоили 7–9 мс при бюджете кадра 16,7.
 * Те же пятнадцать спрайтами — 0,1 мс.
 *
 * Плитками, а не одной растянутой картинкой на весь разряд, потому что
 * дальность у Теслы прокачивается без потолка: растянутая молния меняла
 * бы масштаб зигзага вместе с расстоянием, и дальний выстрел выглядел бы
 * резиновым. У плиток зигзаг один и тот же на любой дистанции.
 */

/**
 * Длина плитки в ЭКРАННЫХ пикселях, а не в клетках поля.
 *
 * Клетка проецируется в 36–63 пикселя в зависимости от того, куда
 * стреляют: вдоль мировой оси X она почти вдвое длиннее, чем вдоль Y.
 * Плитка в клетку дала бы крупнозернистую молнию при стрельбе на юг
 * и мелкую при стрельбе на восток — на одном и том же расстоянии.
 */
export const ARC_TILE_PX = 64;

/** Высота плитки: размах ломаной плюс запас на толщину ядра. */
export const ARC_TILE_H = 40;

/** Поперечный размах ломаной внутри плитки. */
export const ARC_SWING = 7;

/**
 * Сколько разных плиток печётся.
 *
 * Восемь — это и разнообразие рисунка, и полтора мегабайта видеопамяти
 * на всё про всё. Меньше — начинает читаться повтор, больше — платится
 * без видимой отдачи: плитки мелкие, и глаз не помнит их настолько
 * хорошо, чтобы отличить восьмую от двенадцатой.
 */
export const ARC_VARIANTS = 8;

/**
 * Предел числа плиток на разряд.
 *
 * Страховка, а не рабочее ограничение. Дальность Теслы растёт прокачкой
 * на десятую часть за уровень и потолка не имеет: при базе в восемь
 * клеток на десятом уровне выстрел уходит за двадцать клеток, то есть
 * за тысячу триста пикселей и двадцать плиток. Предел обрезает этот
 * хвост, а шаг подгоняется под остаток — плитки слегка растягиваются,
 * и на такой длине этого не видно.
 */
export const ARC_MAX_TILES = 16;

/**
 * Сколько звеньев в плитке. Число СВОЁ у каждого варианта.
 *
 * При одинаковом числе звеньев период излома выходит один и тот же —
 * два десятка пикселей, — и сколько вариантов ни пеки, глаз ловит
 * равномерную волну, а не молнию. Проверено картинкой: три звена
 * на все восемь вариантов дали ровную синусоиду. Два, три или четыре
 * вперемешку сбивают ритм.
 */
export const arcStepsOf = (variant: number): number => 2 + (Math.abs(variant) % 3);

/**
 * Детерминированный шум по номеру варианта.
 *
 * Свой, а не общий из `noise.ts`: плитки печутся один раз за запуск
 * и обязаны выходить одинаковыми при каждом, иначе одна и та же карта
 * выглядела бы по-разному от запуска к запуску.
 */
const noiseOf = (seed: number): (() => number) => {
  let state = (seed * 9973 + 7) >>> 0;
  return () => {
    state = (Math.imul(state, 1103515245) + 12345) >>> 0;
    return (state / 0xffffffff) * 2 - 1;
  };
};

/**
 * Жилы одной плитки: первая — главная, остальные побочные.
 *
 * ГЛАВНОЕ ПРАВИЛО: каждая жила входит в плитку и выходит из неё строго
 * по осевой. Тогда любая плитка стыкуется с любой, подбирать пары
 * не нужно, а единственный след стыка — излом наклона. Для молнии это
 * не изъян: молния из изломов и состоит.
 *
 * Узлы гуляют и вдоль, а не только поперёк: равномерно расставленные
 * дают одинаковые звенья, а у молнии они разной длины.
 */
export const arcStrands = (variant: number): readonly (readonly Point[])[] => {
  const noise = noiseOf(variant);
  const steps = arcStepsOf(variant);
  const mid = ARC_TILE_H / 2;

  const strand = (scale: number): Point[] => {
    const nodes: Point[] = [{ x: 0, y: mid }];
    for (let step = 1; step <= steps; step += 1) {
      const last = step === steps;
      nodes.push({
        x: (last ? 1 : (step + noise() * 0.3) / steps) * ARC_TILE_PX,
        y: mid + (last ? 0 : noise() * ARC_SWING * scale),
      });
    }
    return nodes;
  };

  // Побочные жилы первыми: они шире по размаху и рисуются под главной.
  // Две, а не четыре — на плитке в шестьдесят четыре пикселя больше
  // не помещается без того, чтобы пучок превратился в плетёнку.
  const left = strand(-1.4);
  const right = strand(1.4);
  return [strand(1), left, right];
};

/**
 * Сколько плиток укладывается в выстрел длиной `lengthPx`.
 *
 * Не деление нацело: расстояние непрерывно и в целое число плиток
 * не укладывается никогда. Берётся ближайшее целое, а шаг потом
 * подгоняется под остаток — каждая плитка растягивается на единицы
 * процентов, зато разряд начинается точно у ствола и кончается точно
 * в точке попадания.
 *
 * Последнее — не косметика. Облик не имеет права врать о том, куда
 * пришёлся урон: по разряду игрок решает, отводить войско или нет.
 */
export const arcTileCount = (lengthPx: number): number =>
  Math.max(2, Math.min(ARC_MAX_TILES, Math.round(lengthPx / ARC_TILE_PX)));

/**
 * Какая плитка берётся на это место в этот миг.
 *
 * Зависит и от номера места, и от фазы — отсюда рассинхрон: соседние
 * плитки перебирают варианты не в ногу, и потрескивание бежит вдоль
 * канала, а не мигает всей молнией разом.
 */
export const arcVariantAt = (seed: number, index: number, phase: number): number =>
  Math.abs(Math.imul(seed ^ (index * 0x9e3779b9), 0x85ebca6b) + phase * 5) % ARC_VARIANTS;

/**
 * Какую долю жизни разряда занимает пробег волны.
 *
 * Меньше половины, и это не вкус. Урон Тесла наносит на тике выстрела,
 * и здоровье у цели убывает сразу; растяни волну на всю жизнь разряда —
 * и фронт дойдёт до цели тогда, когда полоска уже отыграла, а вспышка
 * попадания давно отгорела. Волна, уложенная в первые полтора десятка
 * сотых секунды, успевает пробежать до того, как что-либо в цели
 * закончится.
 *
 * Физике это не противоречит, а следует: яркий ход настоящей молнии
 * идёт по УЖЕ пробитому каналу, а не прокладывает его.
 */
export const ARC_WAVE_SHARE = 0.45;

/**
 * Где сейчас фронт волны: от нуля у ствола до единицы в цели.
 *
 * `undefined` означает, что волна уже прошла и канал горит ровно.
 */
export const arcWaveFront = (seconds: number, span: number): number | undefined => {
  const window = span * ARC_WAVE_SHARE;
  if (window <= 0 || seconds >= window) return undefined;
  return Math.max(0, seconds / window);
};

/** Ширина фронта в долях длины разряда. */
const WAVE_WIDTH = 0.11;

/** Насколько фронт ярче остального канала. */
const WAVE_GAIN = 1.15;

/** Яркость канала вне фронта. Не ноль: разряд виден весь, а не кусками. */
const WAVE_FLOOR = 0.42;

/**
 * Во сколько раз ярче обычного горит плитка, стоящая на доле `share`.
 *
 * Волна меняет ЯРКОСТЬ, а не форму: канал стоит на месте, по нему бежит
 * свет. Тронь форму — и разряд начнёт извиваться, а за свою четверть
 * секунды он извиваться не должен.
 */
export const arcWaveGain = (share: number, front: number | undefined): number => {
  if (front === undefined) return 1;

  const off = (share - front) / WAVE_WIDTH;
  return Math.min(1, WAVE_FLOOR + WAVE_GAIN * Math.exp(-0.5 * off * off));
};

/**
 * Яркость бегущего пятна — головы волны.
 *
 * Гаснет у обоих концов: у ствола её перебивает вспышка выстрела,
 * в цели — вспышка попадания, и лишний свет там только мешает.
 */
export const arcWaveHeadAlpha = (front: number | undefined): number =>
  front === undefined ? 0 : Math.sin(Math.PI * Math.min(1, Math.max(0, front))) ** 0.6;

