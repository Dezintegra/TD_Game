/**
 * Высота и форма скальной клетки.
 *
 * Раньше здесь жила и отрисовка: каждая клетка строилась усечённой
 * пирамидой из плоско залитых граней с обводкой рёбер. Отрисовка уехала
 * в `relief.ts` и `relief-render.ts` — скала перестала быть телом из
 * граней и стала участком непрерывной поверхности, у которой свет
 * считается в каждой точке.
 *
 * Здесь осталось то, что от способа отрисовки не зависит: сколько клетка
 * весит по высоте и насколько срезана у неё вершина. Эти числа поле
 * высот и берёт за основу.
 *
 * Высота и форма выводятся из хеша координат: хранить их негде и незачем,
 * поскольку на правила игры они не влияют. Ошибка в подборе высоты может
 * испортить вид, но не может испортить матч.
 */

/**
 * Уровни высоты скал в клетках.
 *
 * Разброс намеренно широкий: массив из клеток одной высоты читается как
 * плита, а не как скальный выход. Верхний уровень — редкий острый пик,
 * нижний — почти россыпь щебня у подножия.
 *
 * Верхний предел поднят до двух клеток: на прежних полутора массив
 * читался осыпью, а замысел называет его грядой. Выше поднимать нельзя —
 * антенна командного центра обязана оставаться выше любой скалы,
 * а у неё 3,2 клетки.
 */
const ROCK_LEVELS = [0.34, 0.62, 0.95, 1.42, 2.05] as const;

/**
 * Доля, на которую верхняя площадка уже основания.
 *
 * Ноль означает острый пик, значения побольше — срезанную вершину.
 * Чередование того и другого и создаёт вид настоящей породы: одни клетки
 * вытягиваются в шпили, другие остаются гранёными глыбами.
 */
const TOP_SHRINK = [0, 0, 0.14, 0.3, 0.45] as const;

/**
 * Целочисленный хеш координат клетки.
 *
 * Один хеш даёт и высоту, и форму. Функция чистая, поэтому одна и та же
 * карта всегда выглядит одинаково, но хранить ничего не требуется.
 *
 * Math.imul, а не обычное умножение: на больших числах оператор `*` уходит
 * в плавающую точку и теряет младшие биты, из-за чего хеш вырождается.
 */
const hashCell = (x: number, y: number): number => {
  let hash = Math.imul(x + 0x9e37, 0x85ebca6b) ^ Math.imul(y + 0x79b9, 0xc2b2ae35);
  hash = Math.imul(hash ^ (hash >>> 13), 0x27d4eb2f);
  return (hash ^ (hash >>> 16)) >>> 0;
};

export const rockHeight = (x: number, y: number): number =>
  ROCK_LEVELS[hashCell(x, y) % ROCK_LEVELS.length] ?? ROCK_LEVELS[0];

/** Самая высокая скала, какая может встретиться. Нужна, чтобы база была выше. */
export const MAX_ROCK_HEIGHT = Math.max(...ROCK_LEVELS);

/** Самая низкая. По ней судят о разбросе высот. */
export const MIN_ROCK_HEIGHT = Math.min(...ROCK_LEVELS);

/** Насколько верхняя площадка клетки уже её основания. */
export const rockTopShrink = (x: number, y: number): number =>
  TOP_SHRINK[(hashCell(x, y) >>> 5) % TOP_SHRINK.length] ?? 0;
