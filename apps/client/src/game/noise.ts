/**
 * Повторяемая случайность для отрисовки.
 *
 * Настоящий `Math.random` здесь не годится, и причина не в детерминизме
 * ядра — ядра это не касается вовсе, — а в откате предсказания. Клиент
 * пересобирает предсказанный мир переигрыванием тиков, то есть один и тот же
 * тик рисуется по нескольку раз. Со случайным числом форма разлёта обломков
 * перестраивалась бы на глазах у игрока, а молния меняла бы излом
 * по шестьдесят раз в секунду вместо тридцати.
 *
 * Поэтому форма выводится из чисел, которые у события не меняются: координат,
 * номера тика, срока истечения. Одно и то же событие даёт одну и ту же форму
 * сколько угодно раз, разные события — разные формы.
 *
 * Модуль общий: тем же зерном и тем же потоком пользуются излом разряда
 * Теслы и разлёт обломков.
 */

/** Начальное значение FNV-1a и его множитель. Общие у обеих версий хеша. */
const FNV_OFFSET = 0x811c9dc5;
const FNV_PRIME = 0x01000193;

/** Хеш FNV-1a от набора чисел. Тот же алгоритм, что у контрольной суммы ядра. */
export const hashOf = (values: readonly number[]): number => {
  let hash = FNV_OFFSET;

  for (const value of values) {
    hash = Math.imul(hash ^ (value | 0), FNV_PRIME) >>> 0;
  }

  return hash;
};

/**
 * Тот же хеш от трёх чисел, но без промежуточного массива.
 *
 * Заведён по замеру. Решётчатый шум рельефа спрашивает хеш узла
 * четырежды на выборку и двенадцать раз на октавную сумму, а сумм
 * на вершину приходится несколько — на карту выходит порядка тридцати
 * пяти миллионов вызовов, и `hashOf([x, y, seed])` создавал на каждый
 * массив из трёх чисел.
 *
 * Выигрыш скромнее, чем кажется, и здесь стоит грабля. В браузере
 * выборка рельефа карты — 925 мс до и 809 мс после, то есть 12%: V8
 * в Chrome умеет устранять такое выделение сам, когда `hashOf`
 * встраивается. В Node под `tsx` не умеет, и тот же замер там показал
 * 5704 мс против 602 — девятикратное ускорение, которого в браузере нет
 * и в помине. Меряйте клиентский горячий код В БРАУЗЕРЕ; стенд на Node
 * здесь врёт почти на порядок.
 *
 * Контрольная сумма выборки при этом совпадает до бита на всех
 * проверенных картах — картина не изменилась ни на пиксель.
 *
 * Значение обязано совпадать с `hashOf([a, b, c])` в точности: рельеф
 * от него зависит целиком, и разойдись они — карта перерисовалась бы
 * иначе. За совпадением следит тест.
 */
export const hash3 = (a: number, b: number, c: number): number => {
  let hash = Math.imul(FNV_OFFSET ^ (a | 0), FNV_PRIME) >>> 0;
  hash = Math.imul(hash ^ (b | 0), FNV_PRIME) >>> 0;

  return Math.imul(hash ^ (c | 0), FNV_PRIME) >>> 0;
};

/** Поток чисел из [-1, 1) по зерну. Xorshift32: три сдвига на число. */
export const noiseFrom = (seed: number): (() => number) => {
  let state = seed === 0 ? 1 : seed >>> 0;

  return (): number => {
    state ^= state << 13;
    state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5;
    state >>>= 0;

    return state / 0x80000000 - 1;
  };
};
