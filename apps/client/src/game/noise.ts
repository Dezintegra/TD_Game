/**
 * Повторяемая случайность для отрисовки.
 *
 * Настоящий `Math.random` здесь не годится, и причина не в детерминизме
 * ядра — ядра это не касается вовсе, — а в откате предсказания. Клиент
 * пересобирает предсказанный мир переигрыванием тиков, то есть один и тот же
 * тик рисуется по нескольку раз. Со случайным числом форма разлёта обломков
 * перестраивалась бы на глазах у игрока, а молния меняла бы излом
 * по шестьдесят раз в секунду вместо тридцати.
 *
 * Поэтому форма выводится из чисел, которые у события не меняются: координат,
 * номера тика, срока истечения. Одно и то же событие даёт одну и ту же форму
 * сколько угодно раз, разные события — разные формы.
 *
 * Модуль общий: тем же зерном и тем же потоком пользуются излом разряда
 * Теслы и разлёт обломков.
 */

/** Хеш FNV-1a от набора чисел. Тот же алгоритм, что у контрольной суммы ядра. */
export const hashOf = (values: readonly number[]): number => {
  let hash = 0x811c9dc5;

  for (const value of values) {
    hash = Math.imul(hash ^ (value | 0), 0x01000193) >>> 0;
  }

  return hash;
};

/** Поток чисел из [-1, 1) по зерну. Xorshift32: три сдвига на число. */
export const noiseFrom = (seed: number): (() => number) => {
  let state = seed === 0 ? 1 : seed >>> 0;

  return (): number => {
    state ^= state << 13;
    state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5;
    state >>>= 0;

    return state / 0x80000000 - 1;
  };
};
