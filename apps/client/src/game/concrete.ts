import { fbm } from './relief.js';

/**
 * Материал командного центра: бетон.
 *
 * Устроено ровно как фактура породы (`grain.ts` и `relief.ts`), и это
 * не подражание, а требование связности: если бетон считать другим
 * способом, он и освещаться будет по-другому, а поле распадётся
 * на два мира. Отсюда общий приём — фактура живёт в НАПРАВЛЕНИИ,
 * куда смотрит поверхность, и не входит в её высоту.
 *
 * Числа при этом свои, и это тоже требование. У камня крупные складки
 * породы с частотой 2,6 на клетку; у бетона складок нет вовсе — есть
 * ровная мелкая шероховатость, редкие раковины от пузырьков воздуха
 * и правильные швы опалубки. Возьми бетон числа камня, он и выглядел
 * бы камнем.
 *
 * Фактура разложена на две части, и разложение существенное:
 *
 * - **шум** (шероховатость, раковины) замощается по мировым координатам
 *   и потому запекается в плитку — как у скал;
 * - **швы** считаются прямо в шейдере от координат НА ГРАНИ, потому что
 *   шов обязан идти вдоль стены и обрываться на её краю, а плитка
 *   о рёбрах тела ничего не знает.
 */

/**
 * Сторона плитки в клетках.
 *
 * Три, а не круглое число: замощение бесшовно только тогда, когда
 * период решётки — целое число узлов у КАЖДОЙ октавы. Частоты фактуры
 * равны 6, 11 и 30 на клетку, и тройка — наименьшая сторона, при
 * которой все три произведения целые (18, 33 и 90 узлов).
 *
 * Больше брать незачем: рисунок бетона мелкий и однородный, повтор
 * через три клетки на нём не читается — в отличие от породы, где
 * повторяющаяся складка была бы видна сразу.
 */
export const CONCRETE_TILE_CELLS = 3;

/**
 * Сторона плитки в пикселях.
 *
 * Число выведено тем же расчётом, что у скальной плитки. Клетка
 * занимает на экране 63 пикселя, плитка укрывает три клетки, то есть
 * 189 экранных пикселей. При стороне 256 на клетку приходится 85 точек
 * против 63 экранных — полуторный запас, которого хватает и при
 * увеличении.
 *
 * Вчетверо меньше скальной (256 против 512) и потому вчетверо дешевле:
 * у бетона нет крупных складок, за которыми нужен запас разрешения.
 */
export const CONCRETE_TILE_PIXELS = 256;

/**
 * Во сколько раз уклон уменьшается при укладке в байт.
 *
 * Подобран по размаху фактуры: покрывает почти весь, оставляя запас,
 * поэтому обрезание — редкость, а не правило. Точное число сторожит
 * тест: усилят фактуру — он упадёт раньше, чем обрезание станет видно
 * на картинке.
 */
export const CONCRETE_SLOPE_SCALE = 1.6;

/** Зёрна слоёв. Свои у каждого, чтобы слои не совпали рисунком. */
const ROUGH_SEED = 83;
const PIT_SEED = 89;
const MICRO_SEED = 97;

/**
 * Порог появления раковины.
 *
 * Раковины редки: это пузырьки воздуха, оставшиеся у опалубки, а не
 * рябь по всей стене. Порог 0,58 при шуме из [0, 1) оставляет их
 * примерно на пятой части поверхности, и они собираются гнёздами,
 * а не рассыпаются равномерно, — потому что шум гладкий.
 */
const PIT_THRESHOLD = 0.58;

/**
 * Возмущение поверхности бетона, в клетках высоты.
 *
 * В геометрию НЕ входит — только в нормаль. Три слагаемых отвечают
 * за разное: шероховатость даёт основную зернистость, раковины —
 * редкие вмятины, микрозерно — сыпь на границе различимости.
 *
 * Функция периодична с шагом `CONCRETE_TILE_CELLS`: её уклон
 * запекается в замощаемую плитку, а образцовая реализация обязана
 * считать ровно то же, что видеокарта, — иначе сверять их будет нечем.
 */
export const concreteOffset = (u: number, v: number): number => {
  const period = CONCRETE_TILE_CELLS;

  const rough = fbm(u * 11, v * 11, ROUGH_SEED, 3, 11 * period) - 0.5;
  const micro = fbm(u * 30, v * 30, MICRO_SEED, 2, 30 * period) - 0.5;
  const pit = Math.max(0, fbm(u * 6, v * 6, PIT_SEED, 2, 6 * period) - PIT_THRESHOLD);

  // Раковина — вмятина, поэтому со знаком минус: поверхность в ней
  // проваливается, а не вспучивается.
  return rough * 0.03 + micro * 0.008 - pit * 0.14;
};

/** Шаг численной производной, в клетках. Тот же, что у фактуры породы. */
const STEP = 0.02;

/** Уклон фактуры: то, что кладётся в плитку и складывается с наклоном грани. */
export const concreteSlope = (
  u: number,
  v: number,
): { readonly du: number; readonly dv: number } => ({
  du: (concreteOffset(u + STEP, v) - concreteOffset(u - STEP, v)) / (2 * STEP),
  dv: (concreteOffset(u, v + STEP) - concreteOffset(u, v - STEP)) / (2 * STEP),
});

// ─────────────────────────────────────────────────────────────────────────
// Швы опалубки
// ─────────────────────────────────────────────────────────────────────────

/**
 * Шаг швов по грани, в клетках.
 *
 * Разный по двум осям намеренно: бетонная панель шире, чем выше,
 * и одинаковый шаг дал бы сетку квадратов — рисунок, который читается
 * кафелем, а не монолитом.
 */
export const SEAM_PITCH_ALONG = 0.8;
export const SEAM_PITCH_ACROSS = 0.5;

/** Глубина и ширина канавки шва, в клетках. */
const SEAM_DEPTH = 0.012;
const SEAM_WIDTH = 0.022;

/**
 * Уклон одной канавки на расстоянии `distance` от её середины.
 *
 * Профиль гауссов: `-depth · exp(-(d / w)²)`. Гладкий профиль выбран
 * не ради красоты формулы — у канавки с изломом уклон меняется скачком,
 * и на экране шов получает жёсткую светлую нитку по одному краю
 * и чёрную по другому. Настоящий шов так не выглядит.
 */
const grooveSlope = (distance: number): number => {
  const ratio = distance / SEAM_WIDTH;

  return ((2 * SEAM_DEPTH * distance) / (SEAM_WIDTH * SEAM_WIDTH)) * Math.exp(-ratio * ratio);
};

/** Расстояние до ближайшего шва по оси с заданным шагом, со знаком. */
const toNearestSeam = (coordinate: number, pitch: number): number => {
  const phase = coordinate / pitch;

  return (phase - Math.floor(phase) - 0.5) * pitch;
};

/**
 * Уклон швов в точке грани.
 *
 * Координаты — местные, на грани: вдоль ребра и поперёк него. Мировые
 * здесь не годятся, и это главное отличие швов от шума: у отвесной
 * стены мировые `x` и `y` не меняются по высоте, и швы вытянулись бы
 * в сплошные вертикальные борозды.
 */
export const seamSlope = (
  along: number,
  across: number,
): { readonly du: number; readonly dv: number } => ({
  du: grooveSlope(toNearestSeam(along, SEAM_PITCH_ALONG)),
  dv: grooveSlope(toNearestSeam(across, SEAM_PITCH_ACROSS)),
});

// ─────────────────────────────────────────────────────────────────────────
// Плитка
// ─────────────────────────────────────────────────────────────────────────

export interface ConcreteTile {
  /** RGBA, по четыре байта на точку. R и G — уклон, B и A не заняты. */
  readonly pixels: Uint8ClampedArray;
  readonly size: number;
  /** Сколько клеток мира укладывается в сторону плитки. */
  readonly cells: number;
}

/** Уклон [-scale, +scale] в байт [0, 255]. Половина шкалы означает ноль. */
export const encodeConcreteSlope = (slope: number): number =>
  Math.round(((slope / CONCRETE_SLOPE_SCALE + 1) / 2) * 255);

/** Обратно. Нужна тестам и разбору, в кадре не участвует. */
export const decodeConcreteSlope = (byte: number): number =>
  ((byte / 255) * 2 - 1) * CONCRETE_SLOPE_SCALE;

/**
 * Построить плитку.
 *
 * Значение фактуры считается по разу на пиксель, а уклон берётся
 * разностью с соседями — теми же значениями, что уже посчитаны. Прямой
 * путь, через `concreteSlope` на каждый пиксель, обходится вчетверо
 * дороже: он сам считает фактуру четырежды, по разу на каждую сторону
 * разности. Грабля измерена на скальной плитке и стоила там десяти
 * секунд.
 */
export const buildConcreteTile = (size: number = CONCRETE_TILE_PIXELS): ConcreteTile => {
  const pixels = new Uint8ClampedArray(size * size * 4);
  const perPixel = CONCRETE_TILE_CELLS / size;

  const field = new Float32Array(size * size);
  for (let row = 0; row < size; row += 1) {
    for (let column = 0; column < size; column += 1) {
      field[row * size + column] = concreteOffset(column * perPixel, row * perPixel);
    }
  }

  // Индекс с заворотом: плитка периодична, и разность на её краю обязана
  // брать значение с противоположной стороны, иначе по шву пойдёт полоса
  // неверного уклона.
  const wrap = (n: number): number => (n + size) % size;
  const span = 2 * perPixel;

  for (let row = 0; row < size; row += 1) {
    for (let column = 0; column < size; column += 1) {
      const east = field[row * size + wrap(column + 1)] ?? 0;
      const west = field[row * size + wrap(column - 1)] ?? 0;
      const south = field[wrap(row + 1) * size + column] ?? 0;
      const north = field[wrap(row - 1) * size + column] ?? 0;

      const offset = (row * size + column) * 4;
      pixels[offset] = encodeConcreteSlope((east - west) / span);
      pixels[offset + 1] = encodeConcreteSlope((south - north) / span);
      pixels[offset + 2] = 0;
      pixels[offset + 3] = 255;
    }
  }

  return { pixels, size, cells: CONCRETE_TILE_CELLS };
};
