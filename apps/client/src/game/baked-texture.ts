import type { RenderTexture } from 'pixi.js';

/**
 * Завершение запечённой текстуры: построить мип-уровни.
 *
 * Зачем это нужно. Запечённое хранится плотнее показа — таков запас
 * на приближение (`bake-density.ts`). Значит, на общем плане текстура
 * УМЕНЬШАЕТСЯ, а уменьшение без мип-уровней — это выборка каждой второй
 * точки: тонкие детали то попадают в неё, то нет, и на движении это
 * видно как рябь и переливающийся муар. Проще говоря, запас плотности
 * без мип-уровней меняет мыло на мерцание.
 *
 * Заодно чинится то, что рябит и без всякого запаса: дефолтный масштаб
 * в ландшафте равен 0,611, а на пределе 0,4 — то есть запечённое
 * уменьшается уже сегодня.
 *
 * Почему это безопасно именно здесь. PixiJS предупреждает, что
 * мип-уровни не следует заводить на цели отрисовки, которая меняется
 * каждый кадр: их перестроение недёшево. Наш случай ровно обратный —
 * запечённая текстура по построению неизменна: её рисуют однажды
 * и с тех пор только показывают. Поэтому уровни строятся один раз,
 * сразу после запекания, и больше не трогаются.
 *
 * Память уровни прибавляют на треть: сумма 1 + 1/4 + 1/16 + … сходится
 * к четырём третям. Эта треть учтена в бюджете слоя скал.
 */
export const finishBakedTexture = (texture: RenderTexture): void => {
  texture.source.autoGenerateMipmaps = true;
  texture.source.updateMipmaps();
};
