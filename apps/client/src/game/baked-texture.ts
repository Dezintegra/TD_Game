import { RenderTexture } from 'pixi.js';

/**
 * Запечённая текстура: та, которую рисуют однажды и с тех пор только
 * показывают.
 *
 * Зачем ей мип-уровни. Запечённое хранится плотнее показа — таков запас
 * на приближение (`bake-density.ts`). Значит, на общем плане текстура
 * УМЕНЬШАЕТСЯ, а уменьшение без мип-уровней — это выборка каждой второй
 * точки: тонкие детали то попадают в неё, то нет, и на движении это
 * видно как рябь и переливающийся муар. Проще говоря, запас плотности
 * без мип-уровней меняет мыло на мерцание.
 *
 * Заодно чинится то, что рябит и без всякого запаса: дефолтный масштаб
 * в ландшафте равен 0,611, а на пределе 0,4 — то есть запечённое
 * уменьшается уже сегодня.
 *
 * Почему это безопасно именно здесь. PixiJS предупреждает, что
 * мип-уровни не следует заводить на цели отрисовки, которая меняется
 * каждый кадр: их перестроение недёшево. Наш случай ровно обратный —
 * запечённая текстура неизменна по построению, поэтому уровни строятся
 * один раз, сразу после запекания, и больше не трогаются.
 *
 * Память уровни прибавляют на треть: сумма 1 + 1/4 + 1/16 + … сходится
 * к четырём третям. Эта треть учтена в бюджете слоя скал.
 */

/**
 * Завести текстуру под запекание.
 *
 * **Просить мип-уровни надо ЗДЕСЬ, а не после отрисовки**, и это
 * не стилистика. PixiJS выводит число уровней в тот момент, когда
 * заводит текстуру на видеокарте (`GlTextureSystem.initSource`):
 * если `autoGenerateMipmaps` в эту минуту ложь, `mipLevelCount`
 * остаётся единицей навсегда. А `updateMipmaps` устроен так:
 *
 * ```
 * if (this.autoGenerateMipmaps && this.mipLevelCount > 1) …
 * ```
 *
 * — то есть при единице он молча не делает ничего. Поставь флаг после
 * первой отрисовки в текстуру — уровней не будет, ошибки тоже,
 * а разницу на глаз не увидишь: мыло при ПРИБЛИЖЕНИИ всё равно уйдёт,
 * потому что его лечит плотность, а не уровни. Ровно так эта правка
 * и была написана в первый раз.
 */
export const createBakedTexture = (
  width: number,
  height: number,
  density: number,
  antialias: boolean,
): RenderTexture =>
  RenderTexture.create({
    width,
    height,
    resolution: density,
    antialias,
    autoGenerateMipmaps: true,
  });

/**
 * Построить мип-уровни после запекания.
 *
 * Отдельным вызовом, а не само собой: текстура заводится пустой,
 * и уровни, построенные при заведении, описывали бы пустоту. Строить
 * их надо после того, как в текстуру нарисовали.
 */
export const finishBakedTexture = (texture: RenderTexture): void => {
  texture.source.updateMipmaps();
};
