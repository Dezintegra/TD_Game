/**
 * Записанные звуки.
 *
 * Правило, по которому звук берётся записью, а не выкладкой, одно
 * и оно не про удобство.
 *
 * ЧАСТОЕ СИНТЕЗИРУЕТСЯ. Трассер, луч, разряд, гибель машины случаются
 * десятками в секунду. Одна и та же запись, сыгранная полсотни раз
 * подряд, слышится дребезжанием пулемёта, и никакой разброс скорости
 * этого до конца не лечит: ухо ловит повторяющийся рисунок шума,
 * а не высоту. Выкладка же даёт сколько угодно по-настоящему разных
 * вариантов — они отличаются каждым отдельным толчком обломков.
 *
 * РЕДКОЕ И ТЯЖЁЛОЕ МОЖНО ЗАПИСЬЮ. Ядерный удар случается за матч дважды,
 * постройка гибнет раз в полминуты. Повторяемость там не мешает, зато
 * в записи есть подробность, до которой выкладке далеко.
 *
 * Отсюда и устройство: запись не отменяет выкладку, а перекрывает её.
 * Выкладка считается для всего и всегда — она бесплатна, потому что
 * идёт в рабочем потоке, — и остаётся запасным путём. Не загрузился
 * файл, не дала браузер декодировать, оборвалась сеть — игра звучит,
 * просто иначе.
 *
 * Замысел (7.2) запрещает файлы ресурсов растровым текстурам и моделям.
 * На звук запрет не распространялся никогда: раздел о нём молчит.
 *
 * Что обязан сделать загрузчик
 * ────────────────────────────
 * Записи обрезаны по границам кадров MP3 — иначе пришлось бы
 * перекодировать, а перекодирование портит то, ради чего запись
 * и берут. Из этого следуют три обязанности, которых у посчитанных
 * звуков нет.
 *
 * 1. СРЕЗАТЬ ТИШИНУ В НАЧАЛЕ. Кадр MP3 длится 26 миллисекунд,
 *    а кодировщик добавляет к записи свою задержку. Вместе это даёт
 *    от тридцати до сорока миллисекунд молчания перед звуком —
 *    ровно столько выстрел и опаздывал бы за вспышкой.
 * 2. ПРИВЕСТИ ГРОМКОСТЬ к общей таблице. Записи приходят с пиками
 *    от 0,17 до 1,01, и без приведения соотношение громкостей в игре
 *    зависело бы от того, кто и как сводил исходник.
 * 3. СГЛАДИТЬ КРАЯ. Обрезка попадает в произвольную точку волны,
 *    и без короткого ската на концах это щелчок.
 */

export interface SoundFile {
  readonly url: string;
  /**
   * Множители скорости для вариантов.
   *
   * Из одной записи получается несколько разных: тот же звук,
   * сыгранный чуть выше и чуть ниже. Для редких событий хватает
   * одного варианта, для частых — нескольких.
   *
   * Варианты пекутся заранее, а не задаются скоростью на лету, потому
   * что скорость всё равно разбрасывается сверху по ключу события:
   * два разброса поверх друг друга дают больше разнообразия, чем один.
   */
  readonly rates: readonly number[];

  /**
   * С какой секунды звук уводится в тишину.
   *
   * Записи кончаются длинными естественными хвостами, и не всякий хвост
   * игре нужен: восемь секунд ядерного гула держат внимание дольше,
   * чем длится само событие. Обрезать хвост «по живому» нельзя — это
   * щелчок; увести его затуханием можно.
   *
   * В самом файле затухания нет и быть не может: записи режутся
   * по границам кадров MP3, а изменить громкость внутри кадра, не
   * перекодировав, невозможно. Накладывает загрузчик, уже после
   * декодирования.
   */
  readonly fadeFrom?: number;

  /**
   * Ниже какой частоты срезать.
   *
   * Заведено для ротора и по жалобе: запись двигателя гудела на полсотне
   * герц непрерывно, и вместе со свёрткой это давало не простор, а хрип.
   */
  readonly highPass?: number;

  /**
   * Вторая запись, накладываемая поверх этой.
   *
   * Не вариант и не замена, а слой: обе звучат одновременно и вместе
   * составляют одно событие.
   */
  readonly layer?: { readonly url: string; readonly gain: number };
}

const one: readonly number[] = [1];

/**
 * Что берётся записью.
 *
 * Громкость здесь не задаётся: записи приходят с самым разным уровнем
 * (у одной пик 0,17, у другой 1,01), и выравнивать их вручную —
 * занятие без конца. Уровень назначает та же таблица, что и для
 * посчитанных звуков, уже после загрузки. Так соотношение громкостей
 * в игре не зависит от того, откуда звук взялся.
 */
export const SOUND_FILES: Partial<Record<Sound, readonly SoundFile[]>> = {
  // Единственное частое событие, взятое записью. Четыре варианта из одной
  // записи — не полноценная замена четырём посчитанным, и если в бою
  // проступит строчка вместо стрельбы, лечить это придётся возвратом
  // к выкладке.
  [Sound.BoltUnit]: [{ url: boltUnitUrl, rates: [1, 1.07, 0.94, 1.13] }],

  // Машина и генерал — одна и та же запись, обрезанная по-разному.
  // У машины полторы секунды: их гибнут десятки, и длинный хвост
  // у каждой превратил бы бой в сплошной гул (замысел, 7.2). У генерала
  // та же запись во всю длину — он один, и его гибель событие.
  //
  // Скорости у машины разведены шире обычного: это самое частое
  // из событий гибели, и одинаковый хлопок полсотни раз подряд слышен
  // не боем, а неисправностью.
  [Sound.BlastUnit]: [{ url: blastUnitUrl, rates: [1, 1.09, 0.92, 1.17, 0.86], fadeFrom: 0.7 }],
  [Sound.BlastGeneral]: [{ url: blastGeneralUrl, rates: [1, 0.96], fadeFrom: 1.4 }],

  // В исходной записи два дубля с тишиной между ними — это и есть
  // два готовых варианта, они разрезаны по файлам.
  [Sound.BlastStructure]: [
    { url: blastStructureOneUrl, rates: [1, 0.95], fadeFrom: 2 },
    { url: blastStructureTwoUrl, rates: [1], fadeFrom: 2 },
  ],

  // Луч снайпера и снайперской башни — одна запись, разведённая
  // скоростью. Башня получает 0,78: это и ниже примерно на кварту,
  // и на четверть длиннее — ровно то, чем выстрел крупного неподвижного
  // сооружения отличается от выстрела машины. Отдельной записи ради
  // этого не нужно: оружие у них одно и то же, и звучать оно должно
  // родственно.
  [Sound.BeamUnit]: [{ url: beamUrl, rates: [1, 1.05, 0.95], fadeFrom: 0.32 }],
  [Sound.BeamTower]: [{ url: beamUrl, rates: [0.78, 0.74], fadeFrom: 0.42 }],

  // Разряд собран из двух записей, и ни одна поодиночке не годится.
  //
  // Молния даёт тело и раскат, но трещит невнятно. Искры трещат
  // отменно — и не имеют низа вовсе: их яркость держится на трёх
  // килогерцах от начала до конца, то есть это чистый верх. Сложенные,
  // они дают то самое «птыщщщ» и гром вдогонку.
  //
  // Вариантов три, и различаются они не скоростью, а дублем искр:
  // в исходной записи их было десять, и три самых внятных разведены
  // по файлам. Разряд бьёт раз в пару секунд, для записи это часто,
  // и повторяющийся рисунок треска слышен раньше всего.
  [Sound.Arc]: [
    { url: arcUrl, rates: [1], fadeFrom: 1.8, layer: { url: sparksOneUrl, gain: 0.8 } },
    { url: arcUrl, rates: [1.06], fadeFrom: 1.8, layer: { url: sparksTwoUrl, gain: 0.8 } },
    { url: arcUrl, rates: [0.95], fadeFrom: 1.8, layer: { url: sparksThreeUrl, gain: 0.8 } },
  ],

  // Семь секунд, из них последние три — затухание. Дальше гул держал бы
  // внимание дольше, чем длится само событие: картинка ядерного удара
  // живёт пять секунд, и звук вправе её пережить, но не вдвое.
  [Sound.NukeBlast]: [{ url: nukeBlastUrl, rates: one, fadeFrom: 4 }],

  // Зацикленный. Стык сшивается перекрёстным затуханием при загрузке:
  // в записи двигателя нет ни малейшего повода сойтись концу с началом.
  [Sound.Rotor]: [{ url: rotorUrl, rates: one, highPass: 150 }],
};

/** Сколько вариантов даст запись, если она есть. */
export const fileVariantCount = (sound: Sound): number => {
  const files = SOUND_FILES[sound];
  if (files === undefined) return 0;

  let total = 0;
  for (const file of files) total += file.rates.length;
  return total;
};
