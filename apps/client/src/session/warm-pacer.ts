/**
 * Распорядок прогрева кеша спрайтов.
 *
 * Вынесен из `session.ts` не ради стройности, а ради проверяемости:
 * само правило («греться в простое, но не дольше отпущенного») сломалось
 * уже дважды и оба раза обнаружилось не тестом, а красным CI. В сессии
 * оно было неотделимо от глобального состояния и браузерных вызовов,
 * и написать на него проверку было не за что взяться.
 *
 * Здесь же от браузера не осталось ничего: простой, часы и признак
 * идущего матча приходят снаружи.
 */

/**
 * Сколько РАБОТЫ прогрев вправе потратить за один заход в меню, мс.
 *
 * Ограничение стоит на потраченном времени, а не на числе запеканий,
 * и это единственный вид ограничения, который переносится с машины
 * на машину. Двести комбинаций на быстрой машине стоят пары секунд,
 * а на слабой — полуминуты; время же говорит одно и то же везде.
 *
 * Три секунды — это ровно один полный базовый набор по проектной цене:
 * около двухсот комбинаций по тринадцать миллисекунд. Машина,
 * укладывающаяся в замысел, прогревается целиком и правки не замечает
 * вовсе; машина, которой набор обходится дороже, останавливается
 * на середине. Это верно, а не досадно: недостающее допечётся
 * по надобности, а меню, отдавшее прогреву полминуты, нарушает главное
 * требование проекта — отзывчивость.
 *
 * Мерка взята не с потолка. Замер 31.08.2026 на своей машине
 * с шестикратным дросселем процессора — так выглядит runner GitHub,
 * где программная отрисовка делит четыре ядра с пятью процессами:
 *
 * | Прогрев | Занятый главный поток за 40 с |
 * | ------- | ----------------------------- |
 * | как был | 16,9 с, очередь не кончилась |
 * | с бюджетом | 12,5 с, из них 3,1 с прогрева |
 * | выключен вовсе | 8,6 с |
 *
 * На runner'е эти же восемь лишних секунд на браузер роняли
 * `lobby.spec.ts:159` по сроку в 120 с и вздёрнули вчетверо весь сквозной
 * набор — включая проверки, которые матч вовсе не начинают.
 */
export const WARM_BUDGET_MS = 3000;

export interface WarmPacerDeps {
  /**
   * Испечь очередной кусок, уложившись в отпущенное.
   *
   * Возвращает `true`, если очередь не кончилась. Уложиться точно
   * запекатель не обязан и не может: одно запекание неделимо.
   */
  readonly warm: (budgetMs: number) => boolean;
  /** Отложить работу до простоя страницы. */
  readonly whenIdle: (run: (deadline?: IdleDeadline) => void) => void;
  /** Часы. Отдельно от `performance.now` — чтобы проверка могла их вести. */
  readonly now: () => number;
  /** Идёт ли матч. Пока идёт, кадр нужен бою, а не заготовкам. */
  readonly matchRunning: () => boolean;
  /** Бюджет работы. По умолчанию `WARM_BUDGET_MS`. */
  readonly budgetMs?: number;
  /** Бюджет одного шага, когда браузер своего срока не сообщил. */
  readonly frameBudgetMs: number;
  /** Прогрев кончился — и по очереди, и по бюджету. */
  readonly onDone: () => void;
}

/**
 * Завести цикл прогрева.
 *
 * Цикл сам себя переназначает на следующий простой и заканчивается
 * ровно двумя способами: очередь кончилась либо бюджет исчерпан.
 * Идущий матч не заканчивает его, а откладывает: игрок вернётся в меню,
 * и заготовки пригодятся.
 */
export const startWarmPacer = (deps: WarmPacerDeps): void => {
  const budgetMs = deps.budgetMs ?? WARM_BUDGET_MS;

  // Считается именно работа, а не время с начала прогрева: между шагами
  // страница занята вводом и сетью, и ставить это в счёт прогреву значило
  // бы обрывать его тем раньше, чем деятельнее игрок в меню.
  let spentMs = 0;

  const step = (deadline?: IdleDeadline): void => {
    if (deps.matchRunning()) {
      deps.whenIdle(step);

      return;
    }

    // Браузер сам говорит, сколько времени у него есть. Запасной путь
    // такого не знает, и ему остаётся кадровый бюджет.
    const stepBudget = deadline === undefined ? deps.frameBudgetMs : deadline.timeRemaining();

    const started = deps.now();
    const more = deps.warm(stepBudget);
    spentMs += deps.now() - started;

    // Бюджет проверяется ПОСЛЕ шага, а не до: запекание неделимо,
    // и остановиться посреди него всё равно нельзя. Проверка до шага
    // означала бы только то, что последний шаг не сделан вовсе.
    if (more && spentMs < budgetMs) deps.whenIdle(step);
    else deps.onDone();
  };

  deps.whenIdle(step);
};
