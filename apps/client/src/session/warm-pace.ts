/**
 * Мерка вреда от прогрева: во что он обходится МЕНЮ.
 *
 * Зачем. Прогрев кеша спрайтов проходит очередь из двух с лишним сотен
 * запеканий и до появления этой мерки проходил её всегда до конца.
 * На машине с проектной ценой запекания это пара секунд незаметной
 * работы; на слабой — секунды дёрганого меню, то есть прямое нарушение
 * главного требования проекта. Останавливаться прогрев не умел, потому
 * что не знал, во что обходится.
 *
 * Почему меряются КАДРЫ, а не время работы. Двумя замерами подряд
 * 31.08.2026 показано, что время работы о цене запекания не говорит
 * ничего:
 *
 * 1. Часы вокруг вызова (`performance.now()` в обе стороны от
 *    `renderer.warm`) показывают отпущенный им срок, а цена не падает:
 *    заказ уходит в текстуру и продолжается вне этих часов.
 * 2. Промежуток между порциями прогрева — тоже мимо. Внутри одного
 *    простоя браузер зовёт нас повторно, порции идут вплотную,
 *    и промежуток выходит около миллисекунды, тогда как работа драйвера
 *    к этой минуте ещё не легла.
 *
 * А кадры показывают беду прямо, потому что беда и ЕСТЬ кадры. Замер
 * в режиме runner'а (программная отрисовка, два работника):
 *
 * | секунда | кадров | худший кадр |
 * | ------- | ------ | ----------- |
 * | 1 | 24 | 300 мс |
 * | 2 | 12 | 250 мс |
 * | 3 | 35 | 133 мс |
 * | 6 (прогрев кончился) | 60 | 17 мс |
 *
 * На здоровой машине те же секунды прогрева дают ровные шестьдесят
 * кадров при худшем в 17 мс. Разделить эти два случая нетрудно —
 * достаточно смотреть на среднюю длину кадра.
 */

/**
 * Средняя длина кадра, выше которой меню считается дёрганым, мс.
 *
 * Сорок миллисекунд — это двадцать пять кадров в секунду. Проектная
 * плавность — шестьдесят (17 мс), и порог оставляет до неё запас
 * в два с лишним раза: обычная работа меню — перерисовка списка комнат,
 * ввод имени — за него не выходит.
 *
 * Сверху порог держит замер больной машины: в худшие секунды прогрева
 * средний кадр там 42 и 83 мс. Между 17 и 42 сорок стоит с запасом
 * в обе стороны.
 *
 * Порог абсолютный, а не доля от частоты экрана, и это намеренно.
 * Доля потребовала бы знать, на что экран способен, — а узнать это
 * можно только в спокойную минуту, которой во время прогрева нет
 * по определению. Двадцать пять кадров же плохи на любом экране.
 */
export const WARM_FRAME_LIMIT_MS = 40;

/**
 * Окно наблюдения, мс.
 *
 * Полсекунды — это тридцать кадров при шестидесяти в секунду:
 * достаточно, чтобы средняя длина кадра не скакала от одной случайной
 * заминки, и достаточно мало, чтобы приговор поспел вовремя. На больной
 * машине он выносится примерно на первой секунде прогрева, а не на
 * пятой, когда меню уже отдёргалось своё.
 */
export const WARM_WINDOW_MS = 500;

/**
 * Сколько кадров в окне нужно, чтобы судить.
 *
 * Окно закрывается по времени, а не по кадрам, и на совсем уж вставшей
 * странице в него попадёт один кадр. Средняя длина кадра по одному
 * кадру — это не средняя длина, а сам этот кадр.
 */
export const WARM_WINDOW_FRAMES_MIN = 4;

export interface WarmPace {
  /**
   * Учесть показанный кадр и рассудить, продолжать ли прогрев.
   *
   * @param timestamp метка кадра, та самая, что даёт `requestAnimationFrame`
   * @returns `false`, если меню дёргается и прогрев пора прекратить
   */
  frame(timestamp: number): boolean;
  /**
   * Средняя длина кадра в последнем закрытом окне, мс. `undefined`,
   * пока ни одно окно не закрылось.
   *
   * Нужна для объяснения в консоли: без цифры сообщение «прогрев
   * прекращён» не сообщает ничего.
   */
  frameMs(): number | undefined;
  /**
   * Забыть незакрытое окно.
   *
   * Нужно на время матча: кадры там принадлежат бою, прогрев в это время
   * молчит, и судить его по ним не за что. Без сброса первый же кадр
   * после матча дал бы «длину кадра» во весь матч.
   */
  pause(): void;
}

export const createWarmPace = (): WarmPace => {
  let previous: number | undefined;

  /** Копится окно: сколько времени прошло и сколько кадров пришло. */
  let windowMs = 0;
  let windowFrames = 0;

  /**
   * Первое окно не судит.
   *
   * В него попадает загрузка страницы вместе с компиляцией шейдера
   * (746–830 мс на первое запекание сессии, одно на всю сессию). Судить
   * по ней значило бы признать негодной любую машину; к тому же это
   * единственная часть прогрева, которую нельзя ни отложить,
   * ни разделить.
   */
  let judging = false;

  let lastFrameMs: number | undefined;

  return {
    frame(timestamp) {
      const since = previous;
      previous = timestamp;

      // Первый кадр окна задаёт точку отсчёта: длина кадра — это
      // разность двух меток, а не одна из них.
      if (since === undefined) return true;

      const delta = timestamp - since;
      // Метки времени приходят от браузера, и одинаковые среди них
      // встречаются: несколько подписчиков на один кадр. Нулевую длину
      // в среднее пускать нельзя — она занижает его молча.
      if (delta <= 0) return true;

      windowMs += delta;
      windowFrames += 1;

      if (windowMs < WARM_WINDOW_MS || windowFrames < WARM_WINDOW_FRAMES_MIN) return true;

      const frameMs = windowMs / windowFrames;
      windowMs = 0;
      windowFrames = 0;

      if (!judging) {
        judging = true;

        return true;
      }

      lastFrameMs = frameMs;

      return frameMs <= WARM_FRAME_LIMIT_MS;
    },
    frameMs: () => lastFrameMs,
    pause() {
      previous = undefined;
      windowMs = 0;
      windowFrames = 0;
    },
  };
};
