/**
 * Мерка скорости прогрева: во что запекание обходится НА САМОМ ДЕЛЕ.
 *
 * Зачем отдельная мерка. Прогрев кеша спрайтов проходит очередь
 * из двух с лишним сотен запеканий и до появления этой мерки проходил
 * её всегда до конца. На машине с проектной ценой запекания (13 мс)
 * это 2,7 с незаметной работы; на медленной — десятки секунд
 * дёргающегося меню, то есть прямое нарушение главного требования
 * проекта. Останавливаться прогрев не умел, потому что не знал,
 * во что обходится.
 *
 * Почему замер снаружи, а не вокруг вызова. Часами JavaScript цену
 * запекания снять НЕЛЬЗЯ, и это проверено делом 31.08.2026: бюджет
 * времени вокруг `renderer.warm()` показывал ровно отпущенные ему
 * три секунды, а цена не падала. Заказ на запекание уходит в текстуру
 * и продолжается вне этих часов — измерялось оформление заказа,
 * а не работа.
 *
 * Поэтому меряется промежуток МЕЖДУ порциями. В него попадает всё, чем
 * прогрев вредит меню: и работа драйвера, ушедшая за пределы вызова,
 * и задержка кадров, и нежелание браузера давать простой занятой
 * странице. И почти ничего сверх: между порциями прогрев не делает
 * ничего.
 */

/**
 * Сколько прогреву отпущено на весь остаток очереди, мс.
 *
 * Шесть секунд разделяют два измеренных случая с запасом в обе стороны.
 * Здоровая машина: 208 запеканий по 13 мс — 2,7 с, запас до порога
 * вдвое. Больная (runner GitHub, программная отрисовка, замер
 * 31.08.2026): 72 мс на запекание, то есть 15 с, — перебор в два
 * с половиной раза.
 *
 * Это не «столько меню терпит дёрганье». Настоящее дёрганье кончается
 * на четырёх порциях: ровно столько нужно, чтобы вынести приговор.
 * Срок отвечает на другой вопрос — сколько прогрев вправе занимать
 * очередь, оставаясь ускорением, а не помехой.
 */
export const WARM_HORIZON_MS = 6_000;

/**
 * Сколько промежутков нужно, прежде чем судить.
 *
 * Один ничего не значит: браузер мог отдать простой позже по своей
 * причине — сборка мусора, чужая вкладка на том же ядре, переключение
 * окна. Четыре, а не десять: на больной машине каждый замер стоит
 * игроку дёрганого меню, и растягивать приговор незачем.
 */
export const WARM_SAMPLE_MIN = 4;

export interface WarmPace {
  /**
   * Учесть порцию и рассудить, продолжать ли прогрев.
   *
   * @param baked сколько запеканий сделала порция, не меньше одного
   * @param rest сколько запеканий в очереди ещё не тронуто
   * @param at момент окончания порции, `performance.now()`
   * @returns `false`, если по замерам остаток в срок не укладывается
   */
  afford(baked: number, rest: number, at: number): boolean;
  /**
   * Цена одного запекания по замерам, мс. `undefined`, пока замеров нет.
   *
   * Нужна для объяснения в консоли: без цифры сообщение «прогрев
   * прекращён» ничего не сообщает.
   */
  costMs(): number | undefined;
}

export const createWarmPace = (): WarmPace => {
  /**
   * Момент окончания прошлой порции. Пока его нет, мерить нечего:
   * промежуток — это разность двух моментов, а не один из них.
   *
   * Отсюда же и бесплатное избавление от компиляции шейдера. Она входит
   * в ПЕРВОЕ запекание сессии (746–830 мс по замеру) и от машины зависит
   * слабо; попади она в среднее — негодной оказалась бы любая машина,
   * 800 мс на 208 запеканий дают два с половиной часа прогноза. Первая
   * порция промежутка не образует и в замер не входит вовсе.
   */
  let previousAt: number | undefined;

  /**
   * Лучший из промежутков в пересчёте на одно запекание.
   *
   * Именно лучший, а не средний, и причина в том, что портит замеры.
   * Промежуток можно только РАСТЯНУТЬ посторонним делом: свёрнутая
   * вкладка, сборка мусора, чужой процесс на том же ядре. Укоротить
   * его нечем — быстрее собственной работы прогрев не пойдёт.
   *
   * Значит, среднее говорит о машине вместе со всем, что на ней
   * случилось, а минимум — о машине. Приговор по минимуму означает
   * «не укладываемся даже в лучшем случае», и ошибиться он может лишь
   * в сторону сохранения прогрева, а не отказа от него.
   */
  let best: number | undefined;
  let samples = 0;

  return {
    afford(baked, rest, at) {
      const since = previousAt;
      previousAt = at;

      if (since !== undefined && baked > 0) {
        const perBake = (at - since) / baked;

        if (best === undefined || perBake < best) best = perBake;
        samples += 1;
      }

      // Замеров мало — судить рано. Продолжаем: прогрев полезен,
      // и отказываться от него по одной случайности не за что.
      if (best === undefined || samples < WARM_SAMPLE_MIN) return true;

      return best * rest <= WARM_HORIZON_MS;
    },
    costMs: () => best,
  };
};
