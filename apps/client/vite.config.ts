import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import process from 'node:process';

// Приёмника записи матчей здесь больше нет. Запись ведёт игровой сервер:
// он один знает и состав сторон, и профиль компьютерного участника,
// и все идущие матчи разом. См. apps/server/src/recording.ts.

// Порт берётся из среды, потому что рабочих деревьев у репозитория теперь
// несколько и каждое поднимает свой клиент. Значение по умолчанию прежнее,
// поэтому запуск из основного дерева ничего не замечает.
//
// Имя без приставки VITE_ намеренно: такие переменные Vite вшивает
// в браузерный бандл, а этот порт нужен только процессу сборщика.
//
// `process` импортирован явно, а не взят из глобальных: в tsconfig клиента
// стоит `types: ["vite/client"]`, то есть глобальных типов Node здесь нет,
// и на голом `process` падал бы `pnpm typecheck`.
const CLIENT_PORT = Number(process.env['CLIENT_PORT'] ?? 5173);

export default defineConfig({
  plugins: [react()],
  server: {
    // Хост задан явно, а не оставлен по умолчанию: 'localhost' на Windows
    // разрешается в IPv6-адрес ::1, и тогда обращение на 127.0.0.1
    // не доходит — на это спотыкается Playwright и любой внешний инструмент.
    host: '127.0.0.1',
    port: CLIENT_PORT,
    // strictPort остаётся и при настраиваемом порте. Молчаливый переезд
    // на соседний свободный порт означал бы, что Playwright и браузер
    // стучатся туда, где клиента нет, — и это выглядело бы как «игра
    // не открывается», без единой ошибки в логах.
    strictPort: true,
  },
  build: {
    target: 'es2022',
    sourcemap: true,
  },
});
