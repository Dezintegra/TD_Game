import { appendFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { gzipSync } from 'node:zlib';
import type { LogRecord } from './records.js';

/**
 * Писатель JSONL, сжатого gzip.
 *
 * Устроен нарочито тупо: копит строки в памяти и сбрасывает порциями.
 * Никакой умной буферизации, никаких асинхронных очередей — писатель,
 * который может что-то потерять или переупорядочить, обесценивает весь
 * разбор, а выигрыш от сложности здесь измеряется миллисекундами
 * на матч, идущий минуты.
 *
 * Дописывание, а не перезапись целиком: прерванный прогон должен
 * оставлять годные первые строки. Последняя строка при этом может
 * оказаться обрезанной — сборка базы такую пропускает с предупреждением.
 *
 * ## Почему сжато и почему многочленным архивом
 *
 * Лог одного матча весит мегабайты, и 87 % веса — записи решений:
 * все оценённые рубежи и все несостоявшиеся траты. Урезать их нельзя,
 * ради них разбор и существует, — значит надо ужать хранение. Замерено
 * на пяти настоящих логах этой самой нарезкой: 26,25 МБ против 1,41 МБ,
 * в 18,6 раза.
 *
 * Единый архив на файл отменил бы дописывание: чтобы дописать в поток
 * сжатия, его надо держать открытым, и обрыв процесса оставил бы файл
 * без концевика. Поэтому каждая порция сжимается отдельно и ложится
 * в конец — файл выходит многочленным архивом. Это не самоделка:
 * склейка членов разрешена самим форматом gzip, её понимают и `zcat`,
 * и `zlib` в Node.
 *
 * Цена — степень сжатия чуть ниже, чем у единого архива: словарь
 * начинается заново на каждой порции. При 512 строках он успевает
 * набраться, и потеря замерена: 6,7 % против единого архива.
 *
 * Формат записей не меняется: внутри архива тот же JSONL, строка
 * на запись. Греп по логу остаётся, только через `zcat`.
 */

/** Сколько записей копится до сброса на диск. */
const FLUSH_EVERY = 512;

/**
 * Расширение файла лога.
 *
 * Объявлено у писателя, потому что формат определяет он. Читатель
 * его импортирует, а не повторяет: расхождение этих двух знаний
 * означало бы, что логи пишутся, но не находятся при сборке базы, —
 * и заметить это можно было бы только по пустому отчёту.
 */
export const LOG_SUFFIX = '.jsonl.gz';

/** Куда лечь логу этого матча. Расширение подставляется здесь, а не у зовущего. */
export const logPathFor = (dir: string, matchId: string): string =>
  join(dir, `${matchId}${LOG_SUFFIX}`);

export interface LogWriter {
  write(record: LogRecord): void;
  /** Дописать остаток. Обязателен в конце — иначе хвост не доедет. */
  close(): void;
}

export const createLogWriter = (path: string): LogWriter => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, '');

  let pending: string[] = [];

  const flush = (): void => {
    if (pending.length === 0) return;

    appendFileSync(path, gzipSync(Buffer.from(`${pending.join('\n')}\n`, 'utf8')));
    pending = [];
  };

  return {
    write(record) {
      pending.push(JSON.stringify(record));
      if (pending.length >= FLUSH_EVERY) flush();
    },
    close: flush,
  };
};

/** Писатель, который ничего не пишет. Нужен прогонам без лога. */
export const NO_LOG: LogWriter = {
  write: () => undefined,
  close: () => undefined,
};
