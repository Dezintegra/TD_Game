/**
 * Настройки службы компьютерных дежурных.
 *
 * Служба ходит к игровому серверу по сети — ровно так же, как браузер
 * человека, — поэтому знать ей нужно только адрес и общий секрет.
 * Ни одного значения из внутренностей сервера здесь нет и быть не может:
 * пакет `@td/bot` про `@td/server` не знает вовсе, и за этим следит линт.
 */

/**
 * Где живёт игровой сервер.
 *
 * Адрес можно задать целиком (`COMPUTER_API_URL`), а можно не задавать
 * вовсе: тогда он собирается из `HOST` и `PORT` — тех же имён, которыми
 * настраивают сам сервер. Так рабочее дерево, поднявшее сервер на своём
 * порту, получает службу на том же порту без второй настройки.
 *
 * `0.0.0.0` в адресе назначения превращается в `127.0.0.1`: слушать
 * на всех адресах осмысленно, стучаться на них — нет.
 */
const host = (): string => {
  const value = process.env['HOST'] ?? '127.0.0.1';
  return value === '0.0.0.0' || value === '::' ? '127.0.0.1' : value;
};

const port = (): string => process.env['PORT'] ?? '3001';

export const API_URL = process.env['COMPUTER_API_URL'] ?? `http://${host()}:${port()}`;

export const WS_URL = process.env['COMPUTER_WS_URL'] ?? `ws://${host()}:${port()}/game`;

/**
 * Общий секрет, которым служба заверяет свои личности перед сервером.
 *
 * Умолчание пустое, и это то же осознанное умолчание, что у сервера
 * (`apps/server/src/config.ts`). Пустой секрет означает закрытую
 * регистрацию: служба не поднимает ни одного дежурного и говорит почему.
 *
 * Поднять дежурных, не объявившись, было бы хуже недоступности: их
 * комнаты встали бы в списке непомеченными, то есть человеческими
 * на вид, и игрок сел бы играть с компьютером, думая, что играет
 * с человеком.
 */
export const COMPUTER_SECRET = process.env['COMPUTER_SECRET'] ?? '';

/**
 * На каком порту служба отдаёт свои показания.
 *
 * По умолчанию не отдаёт вовсе — ноль означает «прибор молчит».
 * Умолчание выбрано не из скромности: рабочих деревьев на машине
 * несколько, и порт, занятый по умолчанию, дерётся с соседним деревом
 * ровно так же, как дерутся игровые порты. Кому показания нужны —
 * называет порт явно.
 *
 * Наружу этот порт не публикуется никогда: показания снимает тот, кто
 * уже внутри сети развёртывания.
 */
export const METRICS_PORT = Number(process.env['COMPUTER_METRICS_PORT'] ?? 0);

export const METRICS_HOST = process.env['COMPUTER_METRICS_HOST'] ?? '127.0.0.1';
