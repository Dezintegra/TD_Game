import { defineConfig } from 'vitest/config';

/**
 * Тесты служебных сценариев.
 *
 * Отдельным корнем, а не проектом внутри общего прогона, и причина
 * механическая: в корне репозитория лежит `vitest.workspace.ts`, и Vitest
 * подхватывает его раньше любого `--config`. Прогон, запущенный отсюда
 * (`vitest run --root scripts`), рабочего пространства над собой не видит
 * и гоняет ровно эти файлы.
 *
 * Пакетом `scripts/` не является намеренно: файлы здесь запускаются
 * напрямую в Node, без сборки, и в `pnpm-workspace.yaml` не значатся.
 * Заводить ради трёх функций пакет со своим `package.json` и своей
 * сборкой было бы дороже всего предмета проверки.
 *
 * Проверяется только счёт: годность записи, выбор «было», сводка
 * по нагрузке. Всё, что трогает машину, — замок, порты, сам прогон
 * Playwright — не проверяется намеренно: такая проверка занимала бы
 * машину ровно тем, от чего замер и страхует.
 */
export default defineConfig({
  test: {
    name: 'scripts',
    environment: 'node',
    include: ['**/*.test.mjs'],
  },
});
