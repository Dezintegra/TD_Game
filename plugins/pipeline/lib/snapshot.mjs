/**
 * Снимок сессий: превращение ответа средства в картину, понятную сканеру.
 *
 * Снимок нужен оркестратору каждый цикл — почти триста раз в сутки. Пока
 * его собирали строкой кода в `node -e`, он был и самым частым запросом
 * подтверждения: разрешить выполнение произвольного кода заранее нельзя
 * никак, а неотвеченный запрос в автономной сессии запирает её задачу
 * планировщика насмерть. Отсюда отдельный сценарий: у него есть имя,
 * и на имя выписывается разрешение.
 *
 * Своя польза сверх этого: превращение стало проверяемым. Раньше оно
 * писалось заново каждым пробуждением оркестратора и каждый раз могло
 * выйти чуть иначе — а сканер по этой картине решает, жива сессия или
 * пора слать продолжателя.
 */

/** Поля, которые сканеру нужны от сессии. Прочее отбрасывается. */
function one(session) {
  return {
    title: String(session?.title ?? ''),
    isRunning: session?.isRunning === true,
    lastActivityAt: session?.lastActivityAt ?? null,
  };
}

/**
 * Достать перечень сессий из чего угодно, чем ответило средство.
 *
 * Форм несколько, и зависят они от того, как ответ доехал: голым массивом,
 * обёрнутым в `sessions` или в `result`. Гадать при разборе дешевле, чем
 * однажды получить пустой снимок и не заметить: пустой снимок означает
 * «о живости исполнителей ничего не известно», и продолжателей тогда
 * не назначают вовсе — конвейер молча перестаёт восстанавливаться.
 */
export function extractSessions(raw) {
  if (Array.isArray(raw)) return raw;
  if (Array.isArray(raw?.sessions)) return raw.sessions;
  if (Array.isArray(raw?.result)) return raw.result;
  return null;
}

/**
 * Собрать снимок.
 *
 * @param {unknown} raw разобранный ответ средства
 * @returns {{ snapshot: object|null, problem: string|null }}
 */
export function buildSnapshot(raw) {
  const list = extractSessions(raw);
  if (!list) {
    return {
      snapshot: null,
      problem: 'в ответе средства нет перечня сессий: ни массивом, ни в полях sessions и result',
    };
  }

  const sessions = list.filter((item) => item && item.title).map(one);
  if (sessions.length === 0) {
    // Пустой перечень — это не «сессий нет», а почти наверняка разбор
    // не того файла: сама читающая сессия в списке есть всегда.
    return { snapshot: null, problem: 'перечень сессий пуст — похоже, разобран не тот ответ' };
  }

  return { snapshot: { sessions }, problem: null };
}
