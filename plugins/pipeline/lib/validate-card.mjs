import { STATES } from '../config/transitions.mjs';

/**
 * Проверка карточки взамен схемы задачи.
 *
 * Прежний бэклог защищала JSON Schema: файл, не удовлетворивший ей,
 * в работу не брался, а причина называлась поимённо. Над карточкой схемы
 * нет — её правит человек мышью, и проверять приходится при чтении.
 *
 * Требуется немного, и это намеренно. Всё, что конвейер может проставить
 * сам, он проставляет сам: идентификатор, отметки времени, счётчики.
 * У человека спрашивается только то, чего за него не решить, — чем эта
 * задача является и чего от неё ждут.
 *
 * Претензия называет недостающее поимённо и годится в комментарий как есть:
 * читать её будет человек, а не разработчик конвейера.
 */

/** Типы задач и виды прогона — те же, что и в прежней схеме. */
const TYPES = ['feature', 'run', 'note'];
const RUN_KINDS = ['arena', 'perf', 'bench-tick'];

/**
 * Что мешает взять карточку в работу.
 *
 * Пустой ответ означает, что карточка годна. Порядок претензий — от той,
 * что мешает больше: без типа задачи разговаривать не о чем вовсе,
 * а без ожидания от прогона беда только у прогонов.
 *
 * @param {object} parsed результат разбора карточки: `{ task, card }`
 * @returns {string[]} претензии, годные в комментарий человеку
 */
export function checkCard({ task, card }) {
  const problems = [];

  if (card.metaBroken) {
    problems.push(
      'служебный блок в конце описания не разобрался. ' +
        'Если правили описание руками — проще всего удалить блок целиком: ' +
        'конвейер соберёт его заново',
    );
  }

  if (!task.title) {
    problems.push('у карточки нет названия');
  }

  if (task.status === null) {
    problems.push(
      // Число состояний в подсказке не называем: оно уже дважды разошлось
      // с действительностью — их было четырнадцать, стало семнадцать, —
      // а сам перечень рядом и говорит правду всегда.
      'карточка лежит в колонке, которая не отвечает ни одному состоянию задачи. ' +
        `Состояния: ${STATES.join(', ')}`,
    );
  }

  if (card.types.length === 0) {
    problems.push(`нет метки типа задачи — поставьте одну из: ${TYPES.join(', ')}`);
  } else if (card.types.length > 1) {
    problems.push(
      `меток типа задачи больше одной (${card.types.join(', ')}), ` +
        'а маршрут задачи от типа зависит однозначно — оставьте одну',
    );
  }

  if (task.type === 'run') {
    if (card.runKinds.length === 0) {
      problems.push(`нет метки вида прогона — поставьте одну из: ${RUN_KINDS.join(', ')}`);
    } else if (card.runKinds.length > 1) {
      problems.push(
        `меток вида прогона больше одной (${card.runKinds.join(', ')}) — оставьте одну`,
      );
    }

    if (!task.run?.expectation) {
      problems.push(
        'в описании нет раздела «## Ожидаемый результат». ' +
          'Без него прогон нечем истолковать: цифра сама по себе не говорит ни о чём',
      );
    }
  }

  return problems;
}

/**
 * Что сделать с меткой «не разобрано» по итогам проверки.
 *
 * Метка снимается сама, как только карточку исправили: требовать от
 * человека ещё и снять её значило бы оставлять на доске красноту, которую
 * никто не уберёт. Комментарий с причиной при этом остаётся — он часть
 * истории карточки.
 */
export function unparsedLabelChange(problems, flags) {
  const marked = flags.includes('unparsed');
  if (problems.length > 0) return marked ? 'keep' : 'add';
  return marked ? 'remove' : 'keep';
}
