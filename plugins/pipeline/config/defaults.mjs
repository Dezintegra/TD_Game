/**
 * Настройка конвейера: всё, что зависит от проекта и от машины.
 *
 * Значения отсюда — умолчания. Настоящий проект кладёт рядом
 * `pipeline.config.json` и переопределяет то, что у него иначе. Скрипты
 * читают только результат слияния и зашитых имён путей, команд и порогов
 * не содержат: иначе плагин перестал бы переноситься копированием каталога.
 *
 * Обязательные для проекта значения перечислены в REQUIRED. Отсутствие
 * любого из них останавливает конвейер с внятным сообщением, а не
 * подставляет умолчание наугад: угаданная команда выкладки хуже
 * несделанной выкладки.
 */

/** Умолчания, годные для любого проекта. */
export const DEFAULTS = {
  /** Как часто просыпается оркестратор, минут. */
  cycleMinutes: 5,

  /** Сколько задач разом вправе занимать ресурсные состояния. */
  maxResource: 2,

  /** Сколько ревью идёт одновременно. Одно: замечания к чужому коду не делятся. */
  maxReview: 1,

  /** Сколько минут молчания сессии считать смертью. */
  deadAfterMinutes: 30,

  /** Сколько раз продолжать один этап после уснувшей сессии, прежде чем сдаться. */
  maxContinuations: 2,

  /** Сколько неуспешных циклов подряд взводят рубильник паузы. */
  pauseAfterFailedCycles: 3,

  /** Сколько секунд отпущено на отправку с повторами. Меньше интервала цикла. */
  pushBudgetSeconds: 120,

  /** Через сколько минут замок цикла считается брошенным. Больше интервала. */
  lockStaleMinutes: 30,

  /** Имя удалённого репозитория и главной ветки. */
  remote: 'origin',
  mainBranch: 'main',

  /**
   * Кем конвейер подписывает свои коммиты.
   *
   * Своё имя ему нужно не для красоты. Досылка хвоста отправляет только
   * свои коммиты и наотрез отказывается публиковать чужой черновик; узнаёт
   * она их по имени автора, сверяя со списком `ourAuthors`. Пока конвейер
   * коммитил под именем хозяина машины, он объявлял чужим собственный хвост
   * и переставал писать вовсе — до вмешательства человека.
   *
   * Почта выдуманная нарочно: это подпись машины, а не человека, и
   * привязывать её к чьему-то живому ящику незачем.
   */
  author: {
    name: 'Конвейер',
    email: 'pipeline@localhost',
  },

  /** Каталоги. Пути относительно корня репозитория. */
  paths: {
    tasks: 'manage/tasks',
    journal: 'manage/journal',
    questions: 'manage/questions.md',
    schema: 'manage/schema.json',
    local: '.pipeline',
  },

  /** Ведётся ли проработка через OpenSpec. Без него маршрут короче на два этапа. */
  useOpenSpec: true,
};

/**
 * Значения, которые обязан назвать проект. Угадывать их нельзя: команда
 * выкладки, придуманная конвейером, выложит не то и не туда.
 */
export const REQUIRED = ['commands.verify', 'commands.deploy', 'commands.perf', 'worktreeDir'];

/** Достать значение по пути вида `commands.deploy`. */
export function pick(config, path) {
  return path.split('.').reduce((node, key) => (node == null ? undefined : node[key]), config);
}

/**
 * Что нужно каждому этапу.
 *
 * Нехватка настройки не останавливает конвейер целиком: без команды выкладки
 * он прекрасно работает, пока ни одна задача до выкладки не дошла. А вот
 * начинать этап, которого нельзя закончить, нельзя — сессия проснётся,
 * дойдёт до последнего шага и встанет, оставив задачу в состоянии, из
 * которого её будет доставать человек.
 */
export const STAGE_NEEDS = {
  design: ['worktreeDir'],
  audit: ['worktreeDir'],
  implement: ['worktreeDir'],
  revise: ['worktreeDir'],
  review: ['worktreeDir'],
  deploy: ['worktreeDir', 'commands.deploy', 'commands.perf'],
  benchmark: [],
  triage: [],
};

/**
 * Чего не хватает, чтобы начать этап.
 *
 * Прогон разбирается отдельно: арену считает чужое железо, а замер кадров
 * требует местной команды. Требовать её у задачи, которая идёт в Actions,
 * значило бы запретить прогон там, где он и так возможен.
 */
export function missingForStage(config, stage, task) {
  const needs = [...(STAGE_NEEDS[stage] ?? [])];
  if (stage === 'benchmark' && task?.run?.kind === 'perf') needs.push('commands.perf');
  return needs.filter((path) => pick(config, path) === undefined);
}

/**
 * Слить умолчания с настройкой проекта и убедиться, что обязательное названо.
 *
 * Возвращает `{ config, missing }`. Разбираться с нехваткой — дело
 * вызывающего: сканер вправе работать и без команды выкладки, пока ни одна
 * задача до выкладки не дошла.
 */
export function resolveConfig(projectConfig = {}) {
  const author = { ...DEFAULTS.author, ...(projectConfig.author ?? {}) };
  const config = {
    ...DEFAULTS,
    ...projectConfig,
    author,
    paths: { ...DEFAULTS.paths, ...(projectConfig.paths ?? {}) },
    // Список своих авторов выводится из подписи, а не задаётся отдельно.
    // Разъедься эти два значения — и конвейер объявит чужим собственный
    // хвост, после чего перестанет писать до вмешательства человека.
    // Проект вправе дописать имена, под которыми конвейер коммитил раньше,
    // но своя подпись входит в список всегда.
    ourAuthors: [...new Set([author.name, ...(projectConfig.ourAuthors ?? [])])],
  };
  const missing = REQUIRED.filter((path) => pick(config, path) === undefined);
  return { config, missing };
}
