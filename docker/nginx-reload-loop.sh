#!/bin/sh
# Периодический перечит конфигурации nginx — ради обновлённых сертификатов.
#
# Certbot продлевает сертификат в своём контейнере и кладёт новые файлы
# в общий том. Но nginx читает их один раз, при старте: без перечита он
# продолжит показывать старый сертификат до самого истечения, а потом
# игра просто покраснеет.
#
# Почему скрипт лежит в /docker-entrypoint.d, а не подменяет команду
# контейнера: точка входа официального образа выполняет всё из этого
# каталога, а потом запускает nginx — но подстановку переменных в шаблоны
# она делает ТОЛЬКО если команда начинается со слова nginx. Подменив
# команду ради этого цикла, мы молча потеряли бы подстановку домена
# в пути к сертификату, и контейнер не поднялся бы вовсе.
#
# Шесть часов — с запасом. Certbot продлевает за месяц до истечения,
# так что даже пропущенный цикл ничем не грозит.
( while :; do
    sleep 6h
    nginx -s reload 2>/dev/null || true
  done ) &
