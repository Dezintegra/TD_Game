// Ядерный удар
// ─────────────────────────────────────────────────────────────────────────

/**
 * Цена пуска без единого купленного уровня: шестнадцать базовых
 * стоимостей юнита.
 *
 * Прежде цена была пятьюдесятью и не зависела ни от чего. Шестнадцать,
 * а не восемь: по чистой площади вышло бы восемь, и удар оказался бы
 * слишком доступен — четырнадцать секунд дохода. Удвоение возвращает
 * ему цену решения, а не расходника.
 */
export const NUKE_COST = BASE_UNIT_COST * 16;

/**
 * На сколько процентов дорожает пуск за каждый купленный уровень
 * радиуса и мощности.
 *
 * Прежде цена считалась по накрытой площади — квадратом радиуса, —
 * и это оказалось прямой ошибкой. Уровень радиуса даёт двадцать
 * процентов радиуса, то есть сорок четыре процента цены КАЖДОГО
 * последующего пуска. Ветка выходила такая: заплати за уровень, потом
 * заплати за подорожавший уровень, потом плати в полтора раза больше
 * за каждый выстрел до конца матча. Покупать такое незачем, и никто
 * не покупал.
 *
 * Теперь платят за УРОВНИ, а не за площадь, и платят немного: пять
 * процентов за уровень радиуса. Круг при этом по-прежнему растёт
 * на двадцать процентов, то есть накрытая площадь — на сорок четыре.
 * Площадь обгоняет цену почти в девять раз, и прокачка радиуса
 * впервые окупается.
 *
 * Мощность двигает цену вдвое сильнее — на десять процентов, — и это
 * разводит две ветки по смыслу. Радиус дёшев в эксплуатации и дорог
 * в покупке: он накрывает больше целей, но каждую бьёт тем же зарядом.
 * Мощность наоборот. Прежде мощность цену не двигала вовсе, и это
 * делало её бесплатной навсегда: заплатил однажды — бьёшь сильнее
 * весь матч.
 *
 * Откат цену пуска не двигает: он меняет, КАК ЧАСТО бьют, а не сколько
 * стоит удар. Учащение уже оплачено ценой самой ветки.
 *
 * От радиуса цена больше не считается вовсе, и обратный ход
 * («какой это уровень при таком радиусе») сознательно не заводится:
 * он потребовал бы логарифма, а логарифм в детерминированном ядре
 * зависит от библиотеки математики платформы.
 */
export const NUKE_PRICE_PER_RADIUS_LEVEL = 5;
export const NUKE_PRICE_PER_DAMAGE_LEVEL = 10;

/**
 * Цена пуска по купленным уровням радиуса и мощности.
 *
 * Множители перемножаются `combinePpm`, а не применяются по очереди:
 * два применения подряд округлили бы вниз дважды, и цена зависела бы
 * от порядка строк. Обоснование целиком — при самой `combinePpm`.
 */
export const nukeLaunchCost = (radiusLevel: number, damageLevel: number): number =>
  applyPpm(
    NUKE_COST,
    combinePpm(
      compoundPpm(NUKE_PRICE_PER_RADIUS_LEVEL, radiusLevel),
      compoundPpm(NUKE_PRICE_PER_DAMAGE_LEVEL, damageLevel),
    ),
  );

/**
 * Базовый радиус поражения: четыре клетки.
 *
 * Прежде их было десять — две базовые дальности выстрела башни. Это
 * четверть ширины карты и заведомо больше любого построенного узла
 * обороны: удар не требовалось наводить, его достаточно было указать
 * примерно. Четыре клетки требуют попасть.
 *
 * Радиус прокачивается веткой `NukeRadius`, поэтому это именно базовое
 * значение, а не радиус конкретного удара. Радиус удара лежит в записи
 * о нём и замораживается в момент пуска.
 */
export const NUKE_RADIUS_CELLS = 4;
export const NUKE_RADIUS = cellsToUnits(NUKE_RADIUS_CELLS);

/**
 * Базовая мощность заряда: полторы прочности штурмовика.
 *
 * Взрыв не стирает всё в круге, а вычитает прочность, и по этой шкале
 * цели сами собой делятся на два разряда. Штурмовик (100), снайпер (75)
 * и снайперская башня (150) гибнут сразу; Тесла, обычная башня
 * и генерал (по 200) выходят из взрыва с четвертью прочности; стена
 * (1000) держится. Чтобы снести оборону, надо либо вложиться в мощность,
 * либо прийти следом войсками.
 */
export const NUKE_DAMAGE = Math.round(BASE_HEALTH * 1.5);

/**
 * Задержка между командой и взрывом.
 *
 * Мгновенный удар не оставляет противнику хода: полсотни юнитов исчезают
 * без единого шанса среагировать. Три секунды и видимая метка на карте
 * превращают удар из наказания в угрозу, на которую можно ответить.
 */
export const NUKE_DELAY_TICKS = TICKS_PER_SECOND * 3;

/**
 * Откат пусковой установки: минута между пусками одного игрока.
 *
 * Прежде отката не было вовсе, и темп ударов ограничивался одной лишь
 * ценой. Накопивший энергию бил подряд, а ответ на ядерный удар —
 * успеть увести войска: от трёх ударов подряд уводить некуда.
 *
 * Отсчитывается от ПУСКА, а не от взрыва. Задержка в три секунды —
 * свойство летящей ракеты, откат — свойство установки; сложив их,
 * мы наказали бы дважды за одно.
 *
 * Первый в матче удар откатом не задержан: тик готовности у нового
 * игрока нулевой.
 */
export const NUKE_COOLDOWN_TICKS = TICKS_PER_SECOND * 60;

/**
 * Предел, ниже которого откат не опускается никакой прокачкой.
 *
 * Тридцать секунд — это вдвое чаще базового, и дальше удар перестал бы
 * быть событием. Удар в круге четыре клетки успевает нанести урон,
 * а войско — отойти; при откате в пятнадцать секунд отходить было бы
 * некогда, и оружие превратилось бы в постоянный фон.
 */
export const NUKE_COOLDOWN_MIN_TICKS = TICKS_PER_SECOND * 30;

/** Сколько снимает один купленный уровень отката. */
export const NUKE_COOLDOWN_STEP_TICKS = TICKS_PER_SECOND * 10;

/**
 * Сколько уровней отката вообще существует.
 *
 * Выводится из трёх чисел выше, а не записан четвёртым: три числа,
 * из которых любое можно поправить, и четвёртое, которое при этом надо
 * не забыть, — это ровно та связь, которую забывают.
 */
export const NUKE_COOLDOWN_MAX_LEVEL =
  (NUKE_COOLDOWN_TICKS - NUKE_COOLDOWN_MIN_TICKS) / NUKE_COOLDOWN_STEP_TICKS;

/**
 * Откат при данном числе купленных уровней.
 *
 * Ступенями, а не процентами, и это единственная ветка, устроенная так.
 * Требование — ровно минус десять секунд за уровень; в процентах это
 * −16,7 %, потом −20 %, потом −25 %, то есть три разных числа. Ни одно
 * постоянным множителем не выражается, поэтому у ветки нет прибавки
 * за уровень вовсе, а значение выводится из самого уровня.
 *
 * Нижняя граница стоит здесь ВТОРЫМ рубежом, хотя покупку сверх потолка
 * отклоняет ядро. Первый рубеж защищает энергию игрока, второй —
 * состояние мира: расчёт, отвечающий отрицательным откатом на уровень,
 * которого «не может быть», — это авария, ждущая своего часа.
 */
export const nukeCooldownTicks = (level: number): number =>
  Math.max(NUKE_COOLDOWN_MIN_TICKS, NUKE_COOLDOWN_TICKS - level * NUKE_COOLDOWN_STEP_TICKS);

/**
 * Запретная зона вокруг каждой базы: базы всегда остаются вне радиуса
 * поражения. Радиус взрыва плюс основание базы плюс клетка запаса.
 *
 * Была константой, стала функцией: радиус прокачивается, и у каждого
 * игрока он свой. Зона считается в трёх местах — в ядре при пуске,
 * в подсветке недопустимых клеток у клиента и при переборе целей
 * у противника под управлением компьютера, — и все три обязаны считать
 * одинаково. Разойтись им негде ровно потому, что формула здесь одна.
 *
 * Следствие, которое стоит знать заранее: прокачавший радиус расширяет
 * себе и запретную зону. Это не побочный ущерб, а размен — за широкий
 * круг платят правом бить у баз.
 */
export const nukeBaseExclusion = (radius: number): number => radius + cellsToUnits(2);

