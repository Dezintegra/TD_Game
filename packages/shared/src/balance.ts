/**
 * Сколько тиков живёт запись о выстреле. Нужна только рендеру.
 *
 * Срок разный, потому что разные выстрелы означают разное. Трассеров
 * в бою десятки в секунду, и живи каждый дольше — экран залило бы сеткой
 * линий. Снайперский выстрел редок и весом, и вдвое больший срок делает
 * из него событие, которое игрок успевает заметить.
 *
 * На правила срок не влияет ничем: след не наносит урона, не перекрывает
 * линию огня и в контрольную сумму не входит.
 */
export const SHOT_LIFETIME_TICKS: Readonly<Record<ShotWeapon, number>> = {
  [ShotWeapon.Bolt]: BOLT_LIFETIME_TICKS,
  [ShotWeapon.Beam]: BOLT_LIFETIME_TICKS * 2,
  // Разряд живёт столько же, сколько луч, и по той же причине: это редкое
  // и весомое событие, которое игрок должен успеть заметить. Прежние
  // четыре тика — восьмая доля секунды, за которую растекание разряда
  // по площади в две клетки разглядеть невозможно.
  [ShotWeapon.Arc]: BOLT_LIFETIME_TICKS * 2,
  // Ракете срок нужен на две вещи подряд: долететь и дать дыму
  // рассеяться. Продлить показ за пределы записи нечем — записи
  // к этому моменту в мире уже нет, — поэтому дым укладывается
  // внутрь срока, а не после него. Полёт занимает первую половину,
  // вторая уходит на дым.
  //
  // Вчетверо против трассера — это шестнадцать тиков, чуть больше
  // полусекунды.
  //
  // Здесь стояло «упереться в перезарядку генерала (секунда) след
  // не успевает: два следа одной машины никогда не висят одновременно».
  // Перезарядка стала восемью тиками, и теперь их висит ровно два —
  // след прошлой ракеты доживает свой срок, пока летит следующая.
  //
  // Утверждение снято, а не число: два следа одной машины — это и есть
  // залп, ради которого перезарядка сокращена. Ракеты при этом уходят
  // с разных бортов (`ShotSide`), поэтому пара читается парой,
  // а не двоением одного пуска.
  [ShotWeapon.Missile]: BOLT_LIFETIME_TICKS * 4,
};

