export interface UpgradeBranch {
  readonly target: UpgradeTarget;
  readonly stat: UpgradeStat;
  readonly label: string;
  readonly baseCost: number;
  /** На сколько процентов дорожает следующий уровень этой же ветки. */
  readonly costGrowthPercent: number;
  /**
   * На сколько процентов меняется характеристика за уровень.
   * Отрицательное значение означает уменьшение — так устроены
   * перезарядка и время возрождения, где меньше значит лучше.
   */
  readonly effectPercent: number;
  /**
   * Потолок уровня. Отсутствует у всех веток, кроме отката ядерки.
   *
   * Поле, а не проверка по имени ветки. Проверка вида «если это откат —
   * не выше трёх» была бы правилом, спрятанным в ветвлении: следующая
   * ветка с потолком либо заведёт второе такое ветвление, либо
   * не заведёт вовсе — и станет продаваться сверх предела молча,
   * списывая энергию ни за что.
   *
   * Знать о потолке обязаны трое: ядро (отклонить покупку), интерфейс
   * (не предлагать кнопку, которая гарантированно получит отказ)
   * и противник под управлением компьютера (не выбирать предельную
   * ветку, иначе он повторит отклонённую команду на следующем тике —
   * и так до конца матча).
   */
  readonly maxLevel?: number;
}

/** Достигнут ли потолок ветки. Ветка без потолка не достигает его никогда. */
export const isUpgradeMaxed = (branch: UpgradeBranch, level: number): boolean =>
  branch.maxLevel !== undefined && level >= branch.maxLevel;

/**
 * Прибавка за уровень для «чем больше, тем лучше».
 * Единая для всех веток: разные шаги у похожих улучшений игрок не считывает,
 * зато они порождают неочевидные перекосы баланса.
 */
const GAIN = 10;

/**
 * Прибавка за уровень у двух ядерных веток — вдвое против общей.
 *
 * Это ЕДИНСТВЕННОЕ исключение из правила выше, и заводится оно
 * не потому, что правило перестало действовать, а потому, что ядерные
 * ветки устроены иначе всех прочих.
 *
 * Три отличия, и вместе они делают обычный шаг слишком слабым.
 *
 * Ветка юнита или башни действует на ДЕСЯТКИ объектов сразу и работает
 * весь матч. Ядерная действует на одно событие, которое случается раз
 * или два за игру: десять процентов к заряду, применённые дважды, —
 * это пятнадцать единиц урона, не меняющие вообще ничего.
 *
 * За обе ядерные ветки платят ДВАЖДЫ: сперва ценой уровня, растущей
 * на двадцать процентов, а потом ценой каждого пуска — пять процентов
 * за уровень радиуса, десять за уровень мощности. Двойная плата обязана
 * покупать и двойной шаг.
 *
 * Ветка отката платы за пуск не несёт и прибавки за уровень не имеет
 * вовсе: она считается ступенями, а не процентами, и `NUCLEAR_GAIN`
 * к ней не относится.
 *
 * И перекоса, которым опасно разное у похожих веток, здесь нет: ядерные
 * ветки не соседствуют ни с чем и ни с чем не сравниваются. Обогнать
 * соседа по дальности они не могут — соседа у них нет.
 *
 * Игрок эту разницу как раз СЧИТЫВАЕТ: у радиуса она видна кольцом
 * на земле, у мощности — тем, переживает ли башня удар.
 */
const NUCLEAR_GAIN = GAIN * 2;

/**
 * Уменьшение за уровень для «чем меньше, тем лучше».
 *
 * Шесть процентов, а не десять. Уменьшение на десять процентов
 * сложным процентом за тридцать уровней даёт коэффициент 0,04 —
 * перезарядка практически исчезает. Шесть процентов оставляют 0,16,
 * что уже ощутимо, но не ломает игру.
 */
const REDUCE = -6;

/** Обычный рост цены уровня. У экономики он свой, вдвое с половиной больше. */
