export const BASE_HEALTH = 100;

/** Базовый урон одного выстрела. */
export const BASE_ATTACK = 10;

/** Базовая перезарядка: один выстрел в секунду. */
export const BASE_COOLDOWN_TICKS = TICKS_PER_SECOND;

/** Базовая дальность стрельбы юнита, в клетках. */
export const BASE_UNIT_RANGE_CELLS = 2;

/** Базовая дальность стрельбы башни, в клетках. */
export const BASE_TOWER_RANGE_CELLS = 5;

/**
 * Дальность стрельбы Теслы, в клетках.
 *
 * Задана не множителем, а относительно базовой башни: ровно на клетку
 * больше. В этом весь смысл Теслы — она расстреливает башню, стоя вне
 * её досягаемости.
 *
 * Живёт здесь, а не в таблице юнитов, потому что от неё считается
 * дальность снайперской башни. Пока число стояло в таблице, связь
 * «башня обязана крыть Теслу» держалась на честном слове двух
 * комментариев в разных концах файла.
 */
export const TESLA_RANGE_CELLS = BASE_TOWER_RANGE_CELLS + 1;

/**
 * На сколько клеток снайперская башня перекрывает дальнобойного юнита.
 *
 * Величина одна на обоих — и на Теслу, и на снайпера, — и в этом её
 * смысл: снайперская башня заведена как ответ дальнобойным, и отвечать
 * она должна одинаково, а не по-разному в зависимости от того, кто
 * подошёл.
 *
 * Ровно две клетки, и число выведено, а не подобрано. Тесла ползёт
 * 0,6 клетки в секунду, поэтому две клетки проходит за 3,3 секунды —
 * ровно одна перезарядка снайперской башни, то есть ОДНО бесплатное
 * попадание на подходе. Дальше счёт равный, по пять попаданий друг
 * в друга, и дуэль решает тот, кто открыл огонь.
 *
 * Прежде перекрытие Теслы составляло четыре клетки: 6,7 секунды
 * безнаказанной стрельбы и два-три бесплатных попадания. Дуэль решала
 * фора, а не то, кто выстрелил первым.
 */
export const SNIPER_TOWER_OVERREACH_CELLS = 2;

/**
 * Дальность стрельбы снайперской башни, в клетках.
 *
 * Выражена через Теслу, и это не оборот речи: башня заведена ради
 * контрбатарейной работы, то есть её число ОБЯЗАНО быть больше дальности
 * Теслы, иначе у осадной машины нет ответа вовсе. Запись через
 * `TESLA_RANGE_CELLS` не даёт нарушить это молча.
 *
 * Прежде здесь стояла двойная базовая дальность башни, то есть десять
 * клеток, и перекрытие выходило вчетверо больше нужного. Сближали
 * снижением башни, а не подъёмом Теслы: дальность Теслы участвует
 * в трёх связках сразу, и, подняв её, мы дали бы осадной машине
 * перестреливать заодно снайпера и генерала, которых она крыть
 * не должна. Дальность этой башни участвует ровно в одной связке —
 * контрбатарейной, — и снижение трогает только её.
 *
 * Втрое (пятнадцать клеток) не рассматривается по-прежнему: это половина
 * видимого экрана, и башня простреливала бы поле раньше, чем игрок успел
 * бы её заметить.
 */
export const SNIPER_TOWER_RANGE_CELLS = TESLA_RANGE_CELLS + SNIPER_TOWER_OVERREACH_CELLS;

/**
 * Базовая скорость: примерно две клетки в секунду.
 *
 * Хранится сразу в «внутренних единицах за тик», потому что именно в таком
 * виде она нужна каждый тик. Две клетки в секунду при тридцати тиках дают
 * 66,67 единицы за тик — дробное число, которого в мире быть не должно,
 * поэтому округляем до 67 и получаем 2,01 клетки в секунду. Расхождение
 * в полпроцента незаметно, зато арифметика остаётся целой.
 *
 * Множитель `speed` из `rules.ts` двигает это число на время замера,
 * и вместе с ним едут Тесла и генерал: их скорости выведены отсюда,
 * а не записаны своими числами.
 */
const BASE_SPEED_BY_DESIGN = 67;
export let BASE_SPEED_UNITS_PER_TICK = BASE_SPEED_BY_DESIGN;

/** Базовая стоимость юнита. От неё считаются цена ядерного удара и награды. */
export const BASE_UNIT_COST = energy(25);

