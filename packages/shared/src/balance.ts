export const GENERAL_KILL_REWARD = BASE_UNIT_COST * 20;

/**
 * Доля добычи, достающаяся ПОСТРОЙКЕ за добивающий удар, в миллионных долях.
 *
 * Двадцать процентов от той же самой `bounty`, по которой платят генералу.
 * На штурмовике это ровно пять единиц — число, названное владельцем
 * продукта, сохранено там, где он его и представлял.
 *
 * Почему доля, а не плоская пятёрка. В игре уже есть один ответ на вопрос
 * «сколько стоит убитый», и второй с ним неминуемо разъедется: подорожает
 * Тесла — награда генерала поедет за ценой, а награда башни останется
 * прежней. Плоская пятёрка вдобавок неверна по смыслу: убийство Теслы
 * за 250 приносило бы столько же, сколько убийство штурмовика за 25,
 * то есть выгоднее всего было бы расстреливать дешёвое мясо.
 *
 * Почему пятая часть, а не полная цена, как у генерала. Полная цена
 * превращает башню в источник дохода, сравнимый с базой: штурмовик
 * снимается базовой башней за семь секунд, и 25 единиц за семь секунд —
 * это треть базового дохода С ОДНОЙ БАШНИ. Три башни на направлении
 * удвоили бы экономику того, кто и так выигрывает бой. Пятая часть даёт
 * 0,71 в секунду, то есть семь процентов базового дохода: башня окупает
 * свои 60 за двенадцать убийств, а экономика матча сдвигается на один-
 * четыре процента и остаётся собой.
 *
 * Асимметрия с генералом намеренна: за генерала надо стоять в пяти
 * клетках от боя под ответным огнём, а башня стои́т в безопасности.
 * Это плата за риск, и стирать её нельзя — стережёт `balance.test.ts`.
 *
 * Величина подвижна множителем `killBounty` из `rules.ts`: число выбрано
 * рассуждением, а рассуждение может ошибиться, и развёртка 1/2/4 отвечает
 * на вопрос «может, стоит и больше» замером, а не спором.
 */
const TOWER_KILL_BOUNTY_PPM_BY_DESIGN = PPM_ONE / 5;
export let TOWER_KILL_BOUNTY_PPM = TOWER_KILL_BOUNTY_PPM_BY_DESIGN;

