/**
 * Как войско ведёт себя при встрече с противником по дороге.
 *
 * До сих пор правило было одно и жёсткое: юнит останавливается перед
 * встречным врагом. Оно осмысленно — две армии, прошедшие друг сквозь
 * друга и разошедшиеся по своим делам, это не тактика, а отсутствие
 * события, — но оно же означало, что осадная волна вязнет в любом
 * заслоне, и решать за игрока тут не за что.
 *
 * Режим — свойство ИГРОКА, а не отдельного юнита: приказ отдаётся всему
 * войску сразу, как и выбор цели. Управление ротами — совсем другая игра,
 * и вводить его под видом режима атаки нельзя.
 *
 * Преследования здесь пока нет намеренно. Оно требует памяти у юнита —
 * за кем гонимся и откуда начали, — то есть двух новых полей в состоянии
 * мира и предела погони; это отдельный раздел работы, и половинчатое
 * преследование хуже, чем его отсутствие.
 */
export const AttackStance = {
  /** Прорыв: идти к цели, ведя огонь на ходу и не останавливаясь. */
  Breakthrough: 0,
  /** Бой: остановиться перед встречным противником и драться. */
  Engage: 1,
} as const;

export type AttackStance = (typeof AttackStance)[keyof typeof AttackStance];

export const ATTACK_STANCES: readonly AttackStance[] = [
  AttackStance.Breakthrough,
  AttackStance.Engage,
];

/** Подписи режимов. Живут рядом с прочими подписями баланса. */
export const ATTACK_STANCE_LABEL: Readonly<Record<AttackStance, string>> = {
  [AttackStance.Breakthrough]: 'Прорыв',
  [AttackStance.Engage]: 'Бой',
};

export const isValidStance = (value: number): value is AttackStance =>
  Number.isInteger(value) && value >= 0 && value < ATTACK_STANCES.length;

export interface UnitStats {
  readonly label: string;
  readonly health: number;
  readonly attack: number;
  readonly cooldownTicks: number;
  /** Дальность стрельбы во внутренних единицах. */
  readonly range: number;
  readonly speed: number;
  /** Доля урона по постройкам, в процентах от обычного урона. */
  readonly structureDamagePercent: number;
  readonly cost: number;
}

/**
 * Характеристики юнитов.
 *
 * Множители относительно базовых величин записаны в комментариях —
 * это прямая расшифровка игрового замысла, и сверять её нужно с ним,
 * а не с этими числами.
 */
const buildUnitStats = (): Readonly<Record<UnitType, UnitStats>> => ({
  [UnitType.Assault]: {
    label: 'Штурмовик',
    health: BASE_HEALTH, // ×1
    attack: BASE_ATTACK, // ×1
    cooldownTicks: BASE_COOLDOWN_TICKS, // ×1
    range: cellsToUnits(BASE_UNIT_RANGE_CELLS), // ×1
    speed: BASE_SPEED_UNITS_PER_TICK, // ×1
    structureDamagePercent: 100, // ×1
    cost: BASE_UNIT_COST, // ×1
  },
  [UnitType.Sniper]: {
    label: 'Снайпер',
    health: Math.round(BASE_HEALTH * 0.75), // ×0,75
    attack: BASE_ATTACK * 3, // ×3
    // Скорострельность ×0,3 — значит перезарядка делится на 0,3.
    cooldownTicks: Math.round(BASE_COOLDOWN_TICKS / 0.3),
    // Дальность задана не множителем, а относительно своей башни: ровно
    // настолько, насколько снайперская башня перекрывает дальнобойных.
    // Прежде здесь стояло «×3 от базовой дальности юнита», и это число
    // совпадало с нужным по случайности — правка башни не тянула за собой
    // снайпера, и пара «снайпер против снайперской башни» разъезжалась бы
    // молча.
    //
    // Получившиеся шесть клеток совпадают с дальностью Теслы, и совпадение
    // это намеренное: обе дальнобойные машины стоят ровно на одно
    // бесплатное попадание ниже той башни, которая их кроет. Записывать
    // снайпера через `TESLA_RANGE_CELLS` при этом нельзя — снайпер
    // определяется своей башней, а не осадной машиной, и общее число
    // у них следствие, а не причина.
    range: cellsToUnits(SNIPER_TOWER_RANGE_CELLS - SNIPER_TOWER_OVERREACH_CELLS),
    speed: BASE_SPEED_UNITS_PER_TICK, // ×1
    structureDamagePercent: 10, // ×0,1
    cost: BASE_UNIT_COST * 2, // ×2
  },
  [UnitType.Tesla]: {
    label: 'Тесла',
    // ×2 — ровно столько же, сколько у базовой башни, и это не совпадение.
    //
    // Число выведено, а не подобрано. Тесла проходит треть базовой
    // скорости, то есть пересекает карту за восемьдесят секунд — один раз
    // за матч. По подвижности это не машина, а сооружение, и прочность
    // она получает сооружения.
    //
    // Прежде здесь стояло базовое здоровье, то же самое, что у штурмовика
    // за одну десятую цены. Самый дорогой юнит в игре был и самым дешёвым
    // по прочности за энергию — 0,4 очка на единицу против четырёх
    // у штурмовика.
    //
    // Боевой машиной её это не делает: десять штурмовиков стоят столько же,
    // снимают двести очков за две секунды и успевают получить один-два
    // ответа. Размен по-прежнему не в её пользу, и так и задумано —
    // это оружие позиции, а не драки.
    health: BASE_HEALTH * 2,
    attack: BASE_ATTACK * 3, // ×3
    cooldownTicks: Math.round(BASE_COOLDOWN_TICKS / 0.3), // скорострельность ×0,3
    // Дальность задана не множителем, а относительно базовой башни:
    // ровно на клетку больше. В этом весь смысл Теслы — она расстреливает
    // башню, стоя вне её досягаемости. Само число и вывод к нему лежат
    // выше, рядом с базовыми величинами: от него считается дальность
    // снайперской башни, и держать связь через комментарий было нельзя.
    range: cellsToUnits(TESLA_RANGE_CELLS),
    speed: Math.round(BASE_SPEED_UNITS_PER_TICK * 0.3), // ×0,3
    structureDamagePercent: 100, // ×1
    cost: BASE_UNIT_COST * 10, // ×10
  },
});

export let UNIT_STATS: Readonly<Record<UnitType, UnitStats>> = buildUnitStats();

