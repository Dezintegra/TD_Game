// Ветеранские ранги за убийства
// ─────────────────────────────────────────────────────────────────────────

/**
 * Сколько убийств нужно набрать для каждого ранга.
 *
 * Это треугольные числа: следующий ранг дороже предыдущего ровно
 * на одно убийство — 1, 2, 3, 4, 5. Правило целиком укладывается
 * в одну фразу, и запоминать таблицу игроку не нужно.
 *
 * Первый ранг даётся за первое же убийство намеренно: связь «сделал —
 * увидел» обязана устанавливаться с первого раза, иначе механику
 * опознают не сразу, а к середине матча.
 *
 * Пятнадцать убийств — это осада: три волны по пять машин, прошедшие
 * через один объект. При расчётном матче в 10–15 минут потолок берут
 * единицы, и так и задумано — закрашенная звезда должна быть событием.
 */
export const VETERAN_RANK_KILLS: readonly number[] = [1, 3, 6, 10, 15];

/**
 * Множитель силы БАШНИ на каждом ранге, в миллионных долях.
 *
 * Шаг прибавки растёт: +10, +15, +20, +25, +30 процентных пунктов —
 * вслед за ценой ранга, которая тоже растёт на одно убийство. Обе
 * прогрессии арифметические, поэтому награда не отстаёт от цены,
 * и последние ранги имеет смысл брать осознанно.
 *
 * Вершина ровная — ровно вдвое. Круглое число проговаривается вслух
 * («закрашенная звезда — вдвое сильнее») и потому запоминается;
 * при 195 или 210 процентах пришлось бы говорить «примерно вдвое»,
 * а это то же самое, только хуже.
 *
 * Прежде рост был непрерывным: +5 процентов сложным процентом
 * за каждое убийство, без игрового потолка. До пятнадцатого убийства
 * новая таблица ЩЕДРЕЕ прежнего правила (×1,10 против ×1,05
 * за первое), на пятнадцатом они сходятся (×2,00 против ×2,08),
 * и дальше вступает потолок. Менялось не «сколько дают», а «когда
 * перестают давать».
 */
export const VETERAN_STRUCTURE_PPM: readonly number[] = [
  1_100_000, 1_250_000, 1_450_000, 1_700_000, 2_000_000,
];

/**
 * Множитель силы МАШИНЫ на тех же рангах. Заметно мягче башенного.
 *
 * Таблицы две, а пороги и знаки различия одни — и это не половинчатость,
 * а следствие замера. При общей таблице (юниты тоже до ×2) матч
 * укорачивался с 7,5 до 5,7 минуты, а на одном из seed — с «больше
 * пятнадцати» до 5,6, то есть уходил ВНИЗ из проектной вилки 10–15
 * минут. Причина известна и записана заранее: исход матча решают живые
 * юниты, а не оборона. Удвоив самое сильное, мы удвоили и перекос.
 *
 * Проверено отдельно: с рангами у одних только башен, по той же
 * таблице, матч на том же seed снова не кончается за пятнадцать минут,
 * а лучшая башня набирает сотню убийств. То есть виноват был не потолок
 * башни, а именно сила ветеранских машин.
 *
 * Поэтому машине потолок — полтора, а не два. Ветеран остаётся заметно
 * крепче и злее пополнения, но перестаёт в одиночку решать исход:
 * прибавка за первый ранг впятеро скромнее башенной (+5 против +10
 * процентных пунктов), а высший ранг даёт полторы силы вместо двух.
 *
 * Башне при этом оставлено вдвое намеренно. Башня неподвижна, стоит
 * там, где её поставили, и погибает вместе со своим рангом; машина
 * ходит по всей карте и приносит накопленное туда, где оно решает.
 * За подвижность и платится разницей таблиц.
 */
export const VETERAN_UNIT_PPM: readonly number[] = [
  1_050_000, 1_120_000, 1_200_000, 1_300_000, 1_500_000,
];

/** Выше этого ранга не поднимаются, сколько бы убийств ни набрали. */
export const VETERAN_MAX_RANK = VETERAN_RANK_KILLS.length;

/**
 * Ранг по числу убийств. Пороги общие для башни и машины.
 *
 * Перебор, а не двоичный поиск: рангов пять, и цикл из пяти сравнений
 * короче, чем подготовка к поиску.
 */
export const veteranRank = (kills: number): number => {
  let rank = 0;
  for (const threshold of VETERAN_RANK_KILLS) {
    if (kills < threshold) break;
    rank += 1;
  }
  return rank;
};

const ppmAt = (table: readonly number[], rank: number): number =>
  rank <= 0 ? PPM_ONE : (table[Math.min(rank, VETERAN_MAX_RANK) - 1] ?? PPM_ONE);

/** Множитель силы башни для ранга. Нулевой ранг не усиливает. */
export const veteranStructurePpm = (rank: number): number => ppmAt(VETERAN_STRUCTURE_PPM, rank);

/** Множитель силы машины для ранга. */
export const veteranUnitPpm = (rank: number): number => ppmAt(VETERAN_UNIT_PPM, rank);

/** Множители прямо по числу убийств — самый частый способ спросить. */
export const veteranStructurePpmOf = (kills: number): number =>
  veteranStructurePpm(veteranRank(kills));

export const veteranUnitPpmOf = (kills: number): number => veteranUnitPpm(veteranRank(kills));

/**
 * Сколько убийств осталось до следующего ранга. Ноль — ранг высший.
 *
 * Нужна окну сведений: пороги неравномерны, и без хода к следующему
 * рангу игрок не может решить, стоит ли держаться за башню, которой
 * до звезды осталось одно убийство.
 */
export const killsToNextRank = (kills: number): number => {
  const next = VETERAN_RANK_KILLS[veteranRank(kills)];
  return next === undefined ? 0 : next - kills;
};

