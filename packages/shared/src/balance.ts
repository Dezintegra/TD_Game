/**
 * Кольцо вокруг базы, в котором строить нельзя, в клетках.
 *
 * Величина выведена, а не подобрана. Кольцо защищает ровно две вещи:
 * появление юнита (свободная клетка ищется от центра базы) и возвращение
 * генерала (точка появления отстоит от центра на две клетки). Защищать
 * весь радиус поиска не нужно и вредно: это кольцо в треть ширины карты,
 * и укреплять собственную базу стало бы нельзя вовсе. Достаточно
 * гарантировать, что **часть** клеток останется свободной.
 *
 * Отсюда тройка: основание базы занимает радиус в одну клетку, остаётся
 * кольцо шириной в две — то самое, в котором юнит появляется в обычном
 * случае.
 *
 * Правило действует у ОБЕИХ баз. Асимметричный вариант «у чужой нельзя,
 * у своей можно» не спасал бы от случайного запирания собственного
 * производства, читался бы с поля хуже и вносил бы асимметрию туда,
 * где карта симметрична по прямому требованию замысла.
 */
