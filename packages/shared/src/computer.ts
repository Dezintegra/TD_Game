import type { ComputerSide } from './matchlog.js';

/**
 * Как выводится компьютерная сторона матча.
 *
 * Лежит в общем пакете, а не у компьютера, потому что вывод нужен
 * двоим сразу. Сервер собирает состав сторон для записи матча — он
 * знает, кто за какой стороной и кто из игроков компьютер. Сам
 * компьютер собирает противника — ему нужны те же profile и seed.
 * Разойдись эти два вывода, запись матча получила бы манеру, которой
 * никто не играл, а воспроизведение собрало бы не того противника
 * и разошлось бы не сразу, а через десятки решений.
 *
 * Прежде вывод жил в `packages/bot`, и сервер ходил за ним туда. Пока
 * служба дежурных поднималась внутри сервера, это ничего не стоило;
 * теперь она уезжает в свой процесс, и зависимость сервера от пакета
 * компьютера остаться не может — иначе переезд был бы переездом
 * на словах.
 */

/**
 * Seed решений выводится из seed мира и стороны.
 *
 * Те же числа, что в арене, и это не совпадение: матч компьютера против
 * компьютера должен воспроизводиться одинаково независимо от того, где
 * он идёт — в безголовом прогоне или через сервер. Разные слагаемые
 * у сторон нужны, чтобы два компьютера в одном матче не играли зеркально
 * одно и то же.
 */
export const aiSeedOf = (seed: number, side: number): number =>
  side === 0 ? (seed ^ 0x5bf03635) >>> 0 : (seed ^ 0x2f6e1a77) >>> 0;

/**
 * Чем компьютер думает на этой стороне.
 *
 * Манера приходит снаружи и обязательна. Умолчания здесь нет намеренно:
 * пока манера была одна, постоянная совпадала с правдой; со второй
 * манерой совпадать перестаёт — и молча. Кто зовёт, тот и знает, чем
 * играет; библиотечное умолчание живёт в `@td/ai` и значит там другое.
 */
export const computerMindOf = (worldSeed: number, side: number, profile: string): ComputerSide => ({
  who: 'computer',
  profile,
  seed: aiSeedOf(worldSeed, side),
});
