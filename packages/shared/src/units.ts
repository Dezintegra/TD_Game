import { FIXED_POINT_SCALE } from './constants.js';

/**
 * Координаты и расстояния в игровом мире.
 *
 * Почему целые числа, а не привычные дробные?
 *
 * Числа с плавающей точкой считаются с крошечной погрешностью, и результат
 * может отличаться между браузерами и платформами. В обычной игре это
 * незаметно, но у нас клиент и сервер прогоняют одну и ту же симуляцию
 * независимо друг от друга и сверяют результат. Расхождение в последнем
 * знаке через тысячу тиков превращается в разное положение врага —
 * то есть в рассинхрон и испорченный матч.
 *
 * Поэтому весь мир живёт в целых числах. Одна клетка поля равна
 * FIXED_POINT_SCALE внутренних единиц, то есть значение 1500 при масштабе
 * 1000 означает "полторы клетки". Это называется арифметикой
 * с фиксированной точкой.
 */
export interface Vec2 {
  /** Координата X во внутренних единицах. */
  readonly x: number;
  /** Координата Y во внутренних единицах. */
  readonly y: number;
}

export const vec2 = (x: number, y: number): Vec2 => ({ x, y });

/** Переводит координату в клетках во внутренние единицы. */
export const cellsToUnits = (cells: number): number => Math.round(cells * FIXED_POINT_SCALE);

/** Переводит внутренние единицы обратно в клетки. Используется только для отрисовки. */
export const unitsToCells = (units: number): number => units / FIXED_POINT_SCALE;

/** Квадрат расстояния между точками. Квадрат — чтобы не извлекать корень. */
export const distanceSquared = (a: Vec2, b: Vec2): number => {
  const dx = a.x - b.x;
  const dy = a.y - b.y;
  return dx * dx + dy * dy;
};

/**
 * Проверка попадания в радиус без извлечения корня.
 *
 * Корень — дорогая операция, и вдобавок дробная, а нам нужны только целые.
 * Сравнение квадратов даёт тот же ответ дешевле и точнее.
 */
export const isWithinRadius = (a: Vec2, b: Vec2, radiusUnits: number): boolean =>
  distanceSquared(a, b) <= radiusUnits * radiusUnits;
