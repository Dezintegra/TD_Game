/**
 * Игрок как человек за экраном: его имя и правила, которым оно обязано
 * соответствовать.
 *
 * Правило живёт здесь, а не в клиенте, потому что проверять имя обязаны
 * оба: клиент — чтобы дать отклик в том же кадре, не спрашивая сеть,
 * сервер — потому что клиенту верить нельзя, и в комнату может прийти
 * запрос из чего угодно, а не только из нашей формы.
 *
 * Две копии одного правила разошлись бы: кто-нибудь поднял бы предел
 * длины в форме и забыл про сервер, и игрок получил бы отказ уже после
 * нажатия. Одна копия на двоих — единственный способ этого избежать.
 *
 * Обратите внимание: к состоянию мира это отношения не имеет. Ядро
 * симуляции про имена не знает и знать не должно — там игрок это номер
 * стороны.
 */
export const NAME_MIN_LENGTH = 2;
export const NAME_MAX_LENGTH = 20;

/**
 * Почему имя не принято.
 *
 * Перечисление, а не готовая строка, по той же причине, что
 * и `RejectReason`: сообщение переводится и переписывается, причина —
 * нет. Пустое поле и слишком короткое имя разведены намеренно: игрок,
 * не набравший ничего, и игрок, набравший одну букву, должны прочитать
 * разное.
 */
export const NameError = {
  Empty: 'empty',
  TooShort: 'too-short',
  TooLong: 'too-long',
} as const;

export type NameError = (typeof NameError)[keyof typeof NameError];

export type NameCheck =
  { readonly ok: true; readonly name: string } | { readonly ok: false; readonly error: NameError };

/**
 * Проверка имени игрока или названия комнаты.
 *
 * Пробелы по краям отсекаются, внутренние сохраняются: «Иван Петров» —
 * законное имя. Ни приведения регистра, ни транслитерации, ни замены
 * символов: игрок написал своё имя так, как хотел.
 *
 * Уникальность здесь не проверяется и нигде не требуется. Двое
 * одноимённых различаются идентификаторами, а запрет на повтор
 * потребовал бы хранить все когда-либо занятые имена.
 */
export const checkName = (raw: string): NameCheck => {
  const name = raw.trim();

  if (name.length === 0) return { ok: false, error: NameError.Empty };
  if (name.length < NAME_MIN_LENGTH) return { ok: false, error: NameError.TooShort };
  if (name.length > NAME_MAX_LENGTH) return { ok: false, error: NameError.TooLong };

  return { ok: true, name };
};
