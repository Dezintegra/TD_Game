/**
 * Арифметика сложных процентов на целых числах.
 *
 * В игре два места, где величина растёт геометрически: цена покупки
 * (+2 процента за каждое улучшение типа) и цена самого улучшения
 * (+10 процентов за уровень, +25 у экономики). Состояние мира
 * целочисленное, а проценты по своей природе дробные, поэтому нужен
 * аккуратный способ их считать.
 *
 * Третьим здесь была сила башни за убийство (+5 процентов сложным
 * процентом). Она ушла к ветеранским рангам в `balance.ts`: рост стал
 * ступенчатым и конечным, и множитель теперь не наращивается, а берётся
 * из таблицы по рангу.
 *
 * Наивная реализация ломается сразу же:
 *
 * ```
 * цена = Math.floor(цена * 102 / 100)   // 10 -> floor(10.2) -> 10
 * ```
 *
 * На малых числах шаг округляется в ноль, и прогрессия замирает навсегда.
 *
 * Приём здесь такой: растёт не сама величина, а множитель, выраженный
 * в миллионных долях. Множитель всегда велик, поэтому округление вниз
 * съедает пренебрежимо малую часть шага, и прогрессия работает сколько
 * угодно долго.
 */

/** Множитель «умножить на единицу», выраженный в миллионных долях. */
export const PPM_ONE = 1_000_000;

/**
 * Применяет множитель к базовой величине.
 *
 * Округление вниз, а не к ближайшему: направление округления должно быть
 * одинаковым на всех платформах, а `Math.round` на ровно половине
 * округляет вверх и оттого чувствителен к тому, как именно получилось
 * дробное значение.
 */
export const applyPpm = (base: number, multiplierPpm: number): number =>
  Math.floor((base * multiplierPpm) / PPM_ONE);

/**
 * Увеличивает множитель на заданное число процентов.
 *
 * Процент целый и может быть отрицательным: так описывается уменьшение
 * перезарядки и времени возрождения, где «улучшение» означает «меньше».
 */
export const growPpm = (multiplierPpm: number, percent: number): number =>
  Math.floor((multiplierPpm * (100 + percent)) / 100);

/**
 * Множитель после нескольких одинаковых шагов.
 *
 * Нужна только там, где уровень известен сразу целиком: в тестах и при
 * восстановлении состояния. В горячем пути множители хранятся в состоянии
 * игрока и наращиваются по одному шагу за покупку — иначе каждый запрос
 * характеристики стоил бы цикла длиной в число купленных уровней.
 */
export const compoundPpm = (percent: number, steps: number): number => {
  let multiplier = PPM_ONE;
  for (let index = 0; index < steps; index += 1) {
    multiplier = growPpm(multiplier, percent);
  }
  return multiplier;
};

/**
 * Произведение двух множителей.
 *
 * Нужна там, где к одной величине применяются два НЕЗАВИСИМЫХ множителя.
 * Такое место в игре одно — цена пуска ядерной ракеты, которую двигают
 * сразу две ветки прокачки, радиус и мощность.
 *
 * Соблазн обойтись без неё выглядит так:
 *
 * ```
 * цена = applyPpm(applyPpm(NUKE_COST, множительРадиуса), множительМощности)
 * ```
 *
 * И это ошибка, хотя выглядит безобидно. `applyPpm` округляет вниз,
 * поэтому здесь округление происходит ДВАЖДЫ — сперва промежуточная
 * цена, потом окончательная. Итог зависит от того, какой множитель
 * применён первым, то есть от порядка строк в коде. В детерминированном
 * ядре такая зависимость означает, что два одинаковых мира могут
 * разойтись после невинного переставления строк местами.
 *
 * Здесь округление одно: множители перемножаются между собой, и только
 * готовый результат применяется к величине. Переполнения не будет —
 * произведение двух множителей порядка миллиона это порядка триллиона,
 * что вчетверо тысяч раз меньше предела точности целых.
 */
export const combinePpm = (first: number, second: number): number =>
  Math.floor((first * second) / PPM_ONE);

/**
 * Ограничение множителя сверху.
 *
 * Защита не игровая, а арифметическая. Все вычисления идут в числах
 * с плавающей точкой двойной точности, где целые представимы точно
 * только до 2^53. Множитель растёт экспоненциально, и произведение
 * «базовое значение × множитель» рано или поздно вышло бы за этот предел.
 * Дальше начались бы потери младших разрядов, то есть расхождение
 * результата в зависимости от порядка операций — ровно то, что
 * детерминированное ядро себе позволить не может.
 */
export const clampPpm = (multiplierPpm: number, maxPpm: number): number =>
  multiplierPpm > maxPpm ? maxPpm : multiplierPpm;
