/**
 * Настройка правил игры на время запуска.
 *
 * Зачем это есть. Величины вроде базового дохода или размера карты — это
 * `export const`, и подобрать их можно было только правкой исходника
 * с последующей пересборкой. Для одиночной правки баланса так и надо:
 * число живёт в одном месте, рядом с обоснованием, и попадает в историю.
 * Но замер, перебирающий десятки сочетаний, упирался в эту же стену —
 * каждое сочетание требовало своей сборки, и перебор становился дороже
 * самого счёта.
 *
 * Что здесь заведено. Величины, применяемые ОДИН раз при запуске, до того
 * как создан первый мир. Не настройки игры и не режимы: в бою эти числа
 * неизменны, ровно как раньше. Умолчание каждого ключа — задуманное
 * значение: единица у множителя, задуманный процент у процента,
 * сложный процент у модели роста. Без вызова `applyRuleTuning` игра
 * ведёт себя в точности так же, как до появления этого модуля.
 *
 * Чего здесь намеренно НЕТ.
 *
 * Чтения среды. `process.env` в этом пакете запрещён: `shared` уезжает
 * в браузер вместе с клиентом. Откуда брать множители — дело приложения:
 * арена читает их из ключей командной строки и зовёт `applyRuleTuning`
 * сама. Граница пакетов при этом остаётся нетронутой.
 *
 * Изменения на ходу. После создания первого мира настройка запирается
 * и попытка сменить её падает с ошибкой. Иначе правила разъехались бы
 * посреди партии, а воспроизведение по записи молча дало бы другой мир —
 * то есть ровно та беда, ради которой ядро сделано детерминированным.
 */

import type { GrowthModel } from './percent.js';

/**
 * Настройка правил. Умолчание каждого ключа означает «как задумано».
 *
 * Ключи трёх родов, и проверяются они по-разному (см. `KIND_OF_KEY`):
 * множители, где единица нейтральна и ноль бессмыслен; проценты, где
 * нейтрально задуманное число, а ноль законен; и модели роста, где
 * значение вовсе не число.
 */
export interface RuleTuning {
  /** Базовый доход в секунду. Только вверх имеет смысл: см. `balance.ts`. */
  income: number;
  /**
   * Прибавка к добыче энергии за уровень, в процентах. Задумано десять.
   *
   * Вместе с `incomeEffectModel` задаёт кривую дохода целиком: при
   * геометрической модели это сложный процент, при линейной — доля базы
   * за уровень.
   */
  incomeEffectPercent: number;
  /** Как растёт добыча энергии с уровнем. Задумано сложным процентом. */
  incomeEffectModel: GrowthModel;
  /**
   * Рост цены уровня добычи энергии, в процентах. Задумано двадцать пять.
   *
   * Ноль законен и означает неизменную цену: это предельный случай
   * перебора, а не ошибка ввода.
   */
  incomeCostPercent: number;
  /** Как растёт цена уровня добычи энергии. Задумано сложным процентом. */
  incomeCostModel: GrowthModel;
  /** Множитель базовой цены первого уровня добычи энергии. */
  incomeBaseCost: number;
  /** Скорость машин. Тянет за собой Теслу и генерала — они выведены от базы. */
  speed: number;
  /** Прочность СТРЕЛЯЮЩИХ построек. Стены и базы не касается. */
  towerHealth: number;
  /**
   * Прочность базы — главный регулятор длительности матча.
   *
   * Отдельно от `towerHealth` намеренно. Почти всё остальное в балансе
   * задано соотношениями замысла, а это число свободно (см. обоснование
   * рядом с самой величиной), и двигают его именно ради длины матча.
   * Слитый с прочностью башен, он отвечал бы сразу за две разные вещи,
   * и замер получил бы сумму двух правок вместо одной.
   */
  baseHealth: number;
  /** Личный радиус машины, то есть плотность строя. Тянет зазор до стены. */
  unitRadius: number;
  /** Сторона карты. Отступ базы от угла едет вместе с ней, подобно. */
  map: number;
}

const NEUTRAL: RuleTuning = {
  income: 1,
  incomeEffectPercent: 10,
  incomeEffectModel: 'geometric',
  incomeCostPercent: 25,
  incomeCostModel: 'geometric',
  incomeBaseCost: 1,
  speed: 1,
  towerHealth: 1,
  baseHealth: 1,
  unitRadius: 1,
  map: 1,
};

/** Род ключа. От него зависит, что считать допустимым значением. */
type TuningKind = 'multiplier' | 'percent' | 'model';

/**
 * Род каждого ключа — таблицей, а не цепочкой условий.
 *
 * Таблица и есть то место, которое придётся дополнять следующей ручкой:
 * одна строка на ключ, и проверка подхватывает его сама. Цепочка условий
 * потребовала бы дописывать ещё и ветку, а забытая ветка означала бы
 * ключ, который не проверяется вовсе.
 */
const KIND_OF_KEY: Readonly<Record<keyof RuleTuning, TuningKind>> = {
  income: 'multiplier',
  incomeEffectPercent: 'percent',
  incomeEffectModel: 'model',
  incomeCostPercent: 'percent',
  incomeCostModel: 'model',
  incomeBaseCost: 'multiplier',
  speed: 'multiplier',
  towerHealth: 'multiplier',
  baseHealth: 'multiplier',
  unitRadius: 'multiplier',
  map: 'multiplier',
};

/** Допустимые модели роста. Список один на проверку и на сообщение об ошибке. */
export const GROWTH_MODELS: readonly GrowthModel[] = ['geometric', 'linear'];

let current: RuleTuning = { ...NEUTRAL };
let locked = false;

/** Пересчёт производной величины. Регистрируется модулем, который её держит. */
type Recompute = () => void;

const recomputes: Recompute[] = [];

/**
 * Заявить пересчёт производных величин модуля.
 *
 * Зовётся на загрузке модуля, а не при настройке, — и порядок вызовов
 * совпадает с порядком импортов, то есть зависимости пересчитываются
 * раньше зависимого. `constants.ts` грузится прежде `balance.ts`,
 * значит размер карты обновится раньше всего, что от него считается.
 */
export const onRuleTuningApplied = (recompute: Recompute): void => {
  recomputes.push(recompute);
};

/** Действующие множители. Только для чтения и для записи в отчёт замера. */
export const ruleTuning = (): Readonly<RuleTuning> => current;

/** Отличается ли настройка от задуманной. Пишется в шапку журнала матча. */
export const ruleTuningIsNeutral = (): boolean =>
  (Object.keys(NEUTRAL) as (keyof RuleTuning)[]).every((key) => current[key] === NEUTRAL[key]);

/**
 * Запереть настройку. Зовётся созданием мира: дальше правила неизменны.
 *
 * Идемпотентно — миров за запуск создаётся много, а запирание одно.
 */
export const lockRuleTuning = (): void => {
  locked = true;
};

/**
 * Проверка одного заказанного значения по роду его ключа.
 *
 * Множитель обязан быть строго положительным: ноль означал бы мир без
 * дохода, без скорости или без карты — не замер, а опечатка. Процент
 * ноль принимает: плоская цена уровня это предельный случай перебора,
 * ровно тот, ради которого перебор и затевается.
 */
const validate = (key: keyof RuleTuning, value: number | string): void => {
  const kind = KIND_OF_KEY[key];

  if (kind === 'model') {
    if (!GROWTH_MODELS.includes(value as GrowthModel)) {
      throw new Error(
        `модель «${key}» должна быть одной из: ${GROWTH_MODELS.join(', ')}; ` +
          `получено «${String(value)}»`,
      );
    }
    return;
  }

  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`«${key}» должен быть числом, получено «${String(value)}»`);
  }

  if (kind === 'multiplier' && value <= 0) {
    throw new Error(`множитель «${key}» должен быть положительным, получено «${String(value)}»`);
  }

  if (kind === 'percent' && value < 0) {
    throw new Error(`процент «${key}» не может быть отрицательным, получено «${String(value)}»`);
  }
};

/**
 * Применить множители и пересчитать всё, что от них выведено.
 *
 * Падает, а не молчит, если мир уже создан: молчаливое применение
 * «наполовину» дало бы мир, часть правил которого новая, а часть старая,
 * и заметить это по поведению почти невозможно.
 */
export const applyRuleTuning = (tuning: Partial<RuleTuning>): void => {
  if (locked) {
    throw new Error('настройка правил заперта: мир уже создан, менять правила поздно');
  }

  for (const [key, value] of Object.entries(tuning)) {
    if (value === undefined) continue;
    validate(key as keyof RuleTuning, value);
  }

  current = { ...current, ...tuning };

  for (const recompute of recomputes) recompute();
};

/** Вернуть задуманные правила. Нужен тестам, чтобы не течь между файлами. */
export const resetRuleTuning = (): void => {
  locked = false;
  current = { ...NEUTRAL };
  for (const recompute of recomputes) recompute();
};
