export const BASE_INSET_CELLS = 6;

/**
 * Параметры проекции поля.
 *
 * Проекция аксонометрическая: мир поворачивается вокруг вертикальной оси
 * на PROJECTION_YAW_DEG, а камера смотрит сверху под углом
 * PROJECTION_PITCH_DEG к горизонту. Оба угла зафиксированы и не меняются
 * ни игроком, ни по ходу матча.
 *
 * Поворот НЕ равен 45 градусам, и это принципиально.
 *
 * При 45 градусах проекция становится честной изометрией: обе оси мира
 * ложатся на экран симметрично, все рёбра выстраиваются в одни и те же
 * две диагонали, и грани соседних объектов сливаются в сплошное поле
 * параллельных линий. Силуэты перестают читаться.
 *
 * При 40 градусах оси расходятся: правая грань объекта заметно шире левой,
 * рёбра соседей уже не совпадают по направлению, и каждый объект получает
 * собственный различимый контур.
 *
 * Наклон камеры в 35 градусов вместо привычных 30 усиливает эффект: сверху
 * видно чуть больше верхних граней, и объекты меньше загораживают друг друга.
 */
export const PROJECTION_YAW_DEG = 40;
export const PROJECTION_PITCH_DEG = 35;

/**
 * Масштаб: сколько экранных пикселей приходится на одну клетку мира
 * до проекции.
 *
 * Площадь клетки на экране равна `масштаб² × sin(наклон)` и от угла поворота
 * не зависит вовсе. При масштабе 63 и наклоне 35 градусов это около 2277
 * пикселей на клетку, то есть при окне 1920 × 1080 видно примерно 911 клеток
 * из 2304 — около 40 процентов карты.
 *
 * Масштаб намеренно оставлен прежним при вчетверо уменьшенной карте.
 * Уменьшать вместе с картой было бы бессмысленно: поле стало меньше
 * затем, чтобы события происходили ближе друг к другу, а не затем,
 * чтобы разглядывать его с той же дистанции.
 */
export const CELL_SCALE_PX = 63;

/** Количество игроков в PvP-матче. */
export const PLAYERS_PER_MATCH = 2;

/** Сколько секунд сервер держит слот отключившегося игрока перед техническим поражением. */
export const RECONNECT_GRACE_SECONDS = 30;

/**
 * Задержка ввода: через сколько тиков после отправки исполняется команда.
 *
 * Величина одна на весь матч и назначается сервером по худшему из каналов.
 * Не «каждому по его пингу», и это принципиально: при задержке по своему
 * каналу игрок с коротким проводом исполнял бы задуманное на несколько
 * тиков раньше соперника при одинаковой скорости реакции, а компьютер,
 * живущий рядом с сервером, обыгрывал бы обоих на разнице каналов,
 * а не решений.
 *
 * Нижняя граница нужна даже на localhost: сеть не бывает ровной, а команда,
 * опоздавшая к своему тику, обходится дороже, чем команда, подождавшая
 * лишний тик. Верхняя — предел, за которым игра перестаёт быть игрой.
 */
export const INPUT_DELAY_MIN_TICKS = 2;
export const INPUT_DELAY_MAX_TICKS = 9;

/**
 * Запас на дрожание канала, прибавляемый к половине времени кругового
 * обхода при расчёте задержки ввода.
 *
 * Один тик — начальное значение, взятое из рассуждения, а не из замера:
 * правильную величину покажут матчи между живыми людьми.
 */
export const INPUT_DELAY_JITTER_TICKS = 1;

/**
 * Как часто сервер шлёт контрольную сумму своего состояния.
 *
 * Раз в секунду. Чаще — лишний трафик и лишний счёт на ровном месте:
 * расхождение не исчезает само, и лишняя секунда до его обнаружения
 * ничего не меняет. Реже — и матч успеет уйти далеко от места ошибки.
 */
export const CHECKSUM_INTERVAL_TICKS = TICKS_PER_SECOND;

/**
 * Предохранитель на глубину переигрывания при пересборке предсказания.
 *
 * В норме переигрывается ровно задержка ввода, то есть не больше
 * INPUT_DELAY_MAX_TICKS шагов. Вдвое больший предел оставляет запас
 * на случай, когда кадры пришли пачкой после короткой заминки, и при этом
 * не даёт клиенту молча уйти в многосекундный пересчёт внутри кадра.
 */
export const PREDICTION_REPLAY_LIMIT_TICKS = INPUT_DELAY_MAX_TICKS * 2;

/**
 * Сколько тиков клиент вправе нести свою неподтверждённую команду.
 *
 * Своя команда, не пришедшая обратно кадром своего тика, считается
 * не потерянной, а перенесённой: сервер отдать её назад не умеет,
 * он умеет только двигать вперёд. Поэтому клиент переставляет её
 * в предсказании на ближайший неподтверждённый тик, и картинка
 * не проседает. Но нести её вечно нельзя: единственный неизвестный
 * путь потери обернулся бы действием, которого не будет, показанным
 * навсегда.
 *
 * Две секунды зажаты двумя границами. Снизу — время обхода на плохом
 * канале: в прогоне 32783516359 оно было 756 мс, то есть около
 * двадцати трёх тиков на весь путь «отдали — увидели в кадре».
 * Сверху — сколько терпимо жить фантому; на фоне
 * RECONNECT_GRACE_SECONDS видно масштаб: канал, не доставивший
 * команду за две секунды, скорее всего уже разорван.
 *
 * Ошибка в меньшую сторону деградирует мягко — возвращает поведение
 * к прежнему, с одной просадкой. В большую врёт дольше. Поэтому запас
 * взят умеренный, а не «с потолка вверх».
 */
export const COMMAND_CARRY_LIMIT_TICKS = TICKS_PER_SECOND * 2;

/**
 * Запас показа над полом, в тиках.
 *
 * Часы показа двигают картинку своим ходом, но целятся не в пол
 * (подтверждённый тик плюс задержка ввода плюс один), а на тик выше.
 * Иначе пол пробивался бы примерно на половине кадров, и каждое
 * пробитие было бы рывком на два тика за один кадр отрисовки — ровно
 * тем, что часы и заводились чинить.
 *
 * Откуда берётся половина. Пол — это лестница, которую строят приходы
 * кадров: он поднимается на ступеньку, когда кадр доехал. Часы — прямая
 * с тем же средним наклоном. Всякий кадр, пришедший раньше расписания,
 * по которому ставили якорь, оказывается ступенькой выше прямой,
 * а приходят раньше примерно половина.
 *
 * Один тик, а не два и не три. Запас — это 33 мс догадки о сопернике
 * сверх сегодняшних, и покупается на них устойчивость к дрожанию
 * канала в тик. Дрожание вдвое большее случается заметно реже, а цена
 * догадки растёт с каждым тиком: соперник в ней продолжает прежнее
 * намерение, и чем дальше, тем чаще это неправда.
 */
export const DISPLAY_LEAD_TICKS = 1;

/**
 * Сколько секунд сервер ждёт подключения участника к начавшемуся матчу.
 *
 * Между «оба нажали готов» и первым тиком клиенту нужно создать сцену,
 * а компьютеру — открыть соединение. Ждать бесконечно нельзя: не пришедший
 * заблокировал бы соперника навсегда, поэтому невыход равносилен невозврату
 * после разрыва и кончается техническим поражением.
 */
export const MATCH_JOIN_TIMEOUT_SECONDS = 20;
