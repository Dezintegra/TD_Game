/**
 * Сколько тиков клиент вправе нести свою неподтверждённую команду.
 *
 * Своя команда, не пришедшая обратно кадром своего тика, считается
 * не потерянной, а перенесённой: сервер отдать её назад не умеет,
 * он умеет только двигать вперёд. Поэтому клиент переставляет её
 * в предсказании на ближайший неподтверждённый тик, и картинка
 * не проседает. Но нести её вечно нельзя: единственный неизвестный
 * путь потери обернулся бы действием, которого не будет, показанным
 * навсегда.
 *
 * Две секунды зажаты двумя границами. Снизу — время обхода на плохом
 * канале: в прогоне 32783516359 оно было 756 мс, то есть около
 * двадцати трёх тиков на весь путь «отдали — увидели в кадре».
 * Сверху — сколько терпимо жить фантому; на фоне
 * RECONNECT_GRACE_SECONDS видно масштаб: канал, не доставивший
 * команду за две секунды, скорее всего уже разорван.
 *
 * Ошибка в меньшую сторону деградирует мягко — возвращает поведение
 * к прежнему, с одной просадкой. В большую врёт дольше. Поэтому запас
 * взят умеренный, а не «с потолка вверх».
 */
export const COMMAND_CARRY_LIMIT_TICKS = TICKS_PER_SECOND * 2;

/**
 * Запас показа над полом, в тиках.
 *
 * Часы показа двигают картинку своим ходом, но целятся не в пол
 * (подтверждённый тик плюс задержка ввода плюс один), а на тик выше.
 * Иначе пол пробивался бы примерно на половине кадров, и каждое
 * пробитие было бы рывком на два тика за один кадр отрисовки — ровно
 * тем, что часы и заводились чинить.
 *
 * Откуда берётся половина. Пол — это лестница, которую строят приходы
 * кадров: он поднимается на ступеньку, когда кадр доехал. Часы — прямая
 * с тем же средним наклоном. Всякий кадр, пришедший раньше расписания,
 * по которому ставили якорь, оказывается ступенькой выше прямой,
 * а приходят раньше примерно половина.
 *
 * Один тик, а не два и не три. Запас — это 33 мс догадки о сопернике
 * сверх сегодняшних, и покупается на них устойчивость к дрожанию
 * канала в тик. Дрожание вдвое большее случается заметно реже, а цена
 * догадки растёт с каждым тиком: соперник в ней продолжает прежнее
 * намерение, и чем дальше, тем чаще это неправда.
 */
export const DISPLAY_LEAD_TICKS = 1;

/**
 * Сколько времени за кадр отдаётся ВСЕЙ отложенной работе.
 *
 * Отложенных работ на клиенте две: запекание скал и догон матча
 * по истории команд. Встречаются они не в теории — перезагрузка
 * страницы посреди матча, самый обычный способ вернуться, заводит обе
 * разом: печь надо всю карту, а матч тем временем ушёл вперёд.
 * Два отдельных бюджета в этом случае складываются, и кадр оказывается
 * съеден целиком, только двумя работами вместо одной, — то есть ровно
 * в том случае, ради которого нарезка и заводилась. Поэтому бюджет
 * один на всех и тратится по порядку: сперва скалы, потом догон.
 *
 * **Восемь миллисекунд, и вот откуда.** Догон обязан проигрывать тики
 * быстрее, чем сервер их считает, иначе он превращается в вечную
 * погоню: клиент растягивает проигрывание, сервер за это время уходит
 * дальше, клиент просит историю снова. Условие сходимости с трёхкратным
 * запасом:
 *
 * ```
 * бюджет × кадров в секунду ÷ цена тика  ≥  3 × TICKS_PER_SECOND
 * ```
 *
 * Цена тика замерена (`pnpm bench:tick`, 25.08.2026, тихая машина):
 * медиана 203 мкс, худший из пяти прогонов 215 мкс. Замер идёт
 * с запасом в нашу сторону: стенд считает шаг мира вместе с решениями
 * обеих компьютерных сторон, а догон зовёт только `step`. На занятой
 * машине тот же замер давал 1,1 мс — это и берётся за худший случай.
 *
 * ```
 * 30 к/с, тик 1,1 мс:  8 × 30 ÷ 1,1  =  218 тиков в секунду  (запас 7,3×)
 * 30 к/с, тик 0,2 мс:  8 × 30 ÷ 0,2  = 1200 тиков в секунду  (запас 40×)
 * ```
 *
 * Нижняя граница по неравенству — 3,3 мс; восемь взяты потому, что
 * ровно столько уже жило запекание скал, и общий бюджет наследует его
 * число, а не заводит рядом второе, которое пришлось бы сводить
 * с первым. Смысл восьмёрки там был тот же, что здесь: «одна диагональ,
 * и хватит» — между единицами работы главный поток освобождается,
 * и браузер успевает разобрать пришедшие кадры матча.
 *
 * Худший кадр — тот, где обе работы взяли по своей неделимой единице:
 * диагональ скал (около двадцати миллисекунд, разрезать её нельзя —
 * останется шов) плюс один тик мира. Это ровно сегодняшняя цена
 * запекания, к которой добавился один шаг.
 */
export const FRAME_WORK_BUDGET_MS = 8;

/**
 * Сколько секунд сервер ждёт подключения участника к начавшемуся матчу.
 *
 * Между «оба нажали готов» и первым тиком клиенту нужно создать сцену,
 * а компьютеру — открыть соединение. Ждать бесконечно нельзя: не пришедший
 * заблокировал бы соперника навсегда, поэтому невыход равносилен невозврату
 * после разрыва и кончается техническим поражением.
 */
export const MATCH_JOIN_TIMEOUT_SECONDS = 20;
