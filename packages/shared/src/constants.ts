/**
 * Сколько внутренних целочисленных единиц приходится на одну клетку поля.
 * Подробнее о том, зачем это нужно, — в units.ts.
 */
export const FIXED_POINT_SCALE = 1000;

/**
 * Частота симуляции: сколько тиков мира просчитывается за секунду.
 *
 * Это не то же самое, что частота кадров. Рендер идёт со скоростью монитора
 * (обычно 60 кадров в секунду), а мир пересчитывается 30 раз в секунду,
 * и между тиками картинка интерполируется. Так мы вдвое экономим и трафик,
 * и процессорное время, не теряя плавности.
 */
export const TICKS_PER_SECOND = 30;

/** Длительность одного тика в миллисекундах. */
export const MS_PER_TICK = 1000 / TICKS_PER_SECOND;

/**
 * Размер игровой карты в клетках. Квадрат — чтобы поворотная симметрия
 * не требовала оговорок про разные измерения.
 *
 * Было 96, стало 48: вчетверо меньшая площадь. На большом поле армии
 * расходились, не встречаясь, а генерал тратил на дорогу до фронта
 * больше времени, чем на игру. Меньшее поле делает каждый шаг заметным.
 */
export const MAP_WIDTH_CELLS = 48;
export const MAP_HEIGHT_CELLS = 48;
export const MAP_CELL_COUNT = MAP_WIDTH_CELLS * MAP_HEIGHT_CELLS;

/**
 * Целевая доля непроходимых клеток на карте, в процентах.
 *
 * Середина допустимого диапазона 8–25. Ниже карта вырождается в пустое поле
 * без укрытий, выше — в лабиринт, по которому невозможно маневрировать.
 */
export const MAP_TARGET_ROCK_PERCENT = 15;

/** Длина случайного блуждания при разрастании одного скального массива. */
export const ROCK_BLOB_STEPS = 40;

/**
 * Предохранитель на число массивов. Генерация останавливается по достижении
 * целевой плотности, но цикл без верхней границы — приглашение к зависанию,
 * если условие остановки однажды окажется недостижимым.
 */
export const ROCK_BLOB_LIMIT = 4096;

/** Радиус расчищаемой площадки вокруг базы, в клетках. */
export const BASE_CLEARANCE_CELLS = 2;

/** Отступ базы от угла карты, в клетках. */
export const BASE_INSET_CELLS = 6;

/**
 * Параметры проекции поля.
 *
 * Проекция аксонометрическая: мир поворачивается вокруг вертикальной оси
 * на PROJECTION_YAW_DEG, а камера смотрит сверху под углом
 * PROJECTION_PITCH_DEG к горизонту. Оба угла зафиксированы и не меняются
 * ни игроком, ни по ходу матча.
 *
 * Поворот НЕ равен 45 градусам, и это принципиально.
 *
 * При 45 градусах проекция становится честной изометрией: обе оси мира
 * ложатся на экран симметрично, все рёбра выстраиваются в одни и те же
 * две диагонали, и грани соседних объектов сливаются в сплошное поле
 * параллельных линий. Силуэты перестают читаться.
 *
 * При 40 градусах оси расходятся: правая грань объекта заметно шире левой,
 * рёбра соседей уже не совпадают по направлению, и каждый объект получает
 * собственный различимый контур.
 *
 * Наклон камеры в 35 градусов вместо привычных 30 усиливает эффект: сверху
 * видно чуть больше верхних граней, и объекты меньше загораживают друг друга.
 */
export const PROJECTION_YAW_DEG = 40;
export const PROJECTION_PITCH_DEG = 35;

/**
 * Масштаб: сколько экранных пикселей приходится на одну клетку мира
 * до проекции.
 *
 * Площадь клетки на экране равна `масштаб² × sin(наклон)` и от угла поворота
 * не зависит вовсе. При масштабе 63 и наклоне 35 градусов это около 2277
 * пикселей на клетку, то есть при окне 1920 × 1080 видно примерно 911 клеток
 * из 2304 — около 40 процентов карты.
 *
 * Масштаб намеренно оставлен прежним при вчетверо уменьшенной карте.
 * Уменьшать вместе с картой было бы бессмысленно: поле стало меньше
 * затем, чтобы события происходили ближе друг к другу, а не затем,
 * чтобы разглядывать его с той же дистанции.
 */
export const CELL_SCALE_PX = 63;

/** Количество игроков в PvP-матче. */
export const PLAYERS_PER_MATCH = 2;

/** Сколько секунд сервер держит слот отключившегося игрока перед техническим поражением. */
export const RECONNECT_GRACE_SECONDS = 30;
