/**
 * Сколько внутренних целочисленных единиц приходится на одну клетку поля.
 * Подробнее о том, зачем это нужно, — в units.ts.
 */
export const FIXED_POINT_SCALE = 1000;

/**
 * Частота симуляции: сколько тиков мира просчитывается за секунду.
 *
 * Это не то же самое, что частота кадров. Рендер идёт со скоростью монитора
 * (обычно 60 кадров в секунду), а мир пересчитывается 30 раз в секунду,
 * и между тиками картинка интерполируется. Так мы вдвое экономим и трафик,
 * и процессорное время, не теряя плавности.
 */
export const TICKS_PER_SECOND = 30;

/** Длительность одного тика в миллисекундах. */
export const MS_PER_TICK = 1000 / TICKS_PER_SECOND;

/** Размер игровой карты в клетках. Квадрат — чтобы поворотная симметрия
 *  не требовала оговорок про разные измерения. */
export const MAP_WIDTH_CELLS = 96;
export const MAP_HEIGHT_CELLS = 96;
export const MAP_CELL_COUNT = MAP_WIDTH_CELLS * MAP_HEIGHT_CELLS;

/**
 * Целевая доля непроходимых клеток на карте, в процентах.
 *
 * Середина допустимого диапазона 8–25. Ниже карта вырождается в пустое поле
 * без укрытий, выше — в лабиринт, по которому невозможно маневрировать.
 */
export const MAP_TARGET_ROCK_PERCENT = 15;

/** Длина случайного блуждания при разрастании одного скального массива. */
export const ROCK_BLOB_STEPS = 40;

/**
 * Предохранитель на число массивов. Генерация останавливается по достижении
 * целевой плотности, но цикл без верхней границы — приглашение к зависанию,
 * если условие остановки однажды окажется недостижимым.
 */
export const ROCK_BLOB_LIMIT = 4096;

/** Радиус расчищаемой площадки вокруг базы, в клетках. */
export const BASE_CLEARANCE_CELLS = 2;

/** Отступ базы от угла карты, в клетках. */
export const BASE_INSET_CELLS = 6;

/**
 * Размер клетки на экране в изометрической проекции.
 *
 * Числа не подобраны на глаз, а выведены из требования «игрок видит примерно
 * десятую часть карты».
 *
 * В изометрии 2:1 одна клетка занимает на экране площадь
 * `ширина × высота / 2` пикселей. При окне 1920 × 1080 и клетке 96 × 48
 * это 2304 пикселя на клетку, то есть видно 2073600 / 2304 = 900 клеток
 * из 9216 — ровно 9,8 процента карты.
 *
 * Приятный побочный эффект: 96 пикселей ширины — достаточно крупный холст,
 * чтобы юниты на нём были действительно детализированными.
 */
export const TILE_WIDTH_PX = 96;
export const TILE_HEIGHT_PX = 48;

/** Количество игроков в PvP-матче. */
export const PLAYERS_PER_MATCH = 2;

/** Сколько секунд сервер держит слот отключившегося игрока перед техническим поражением. */
export const RECONNECT_GRACE_SECONDS = 30;
