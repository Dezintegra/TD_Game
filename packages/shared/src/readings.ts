import type { HistogramSnapshot } from './histogram.js';

/**
 * Формат показаний клиента — общий для того, кто их шлёт, и того,
 * кто их принимает и хранит.
 *
 * Живёт здесь по той же причине, что и формат записи матча: шлёт
 * показания браузер, принимает сервер, а приложения друг друга
 * не импортируют. Значит допустимое место ровно одно — `@td/shared`.
 *
 * ## Почему это отдельно от записи матча
 *
 * Запись матча — правда сервера: seed, стороны, команды, контрольные
 * суммы, из которых матч воспроизводится. Показания — заявление
 * недоверенной стороны о том, как ему рисовалось. Проверить их
 * невозможно в принципе: снимаются они на чужой машине.
 *
 * Один формат на двоих уравнял бы их в доверии, и через месяц никто
 * не вспомнил бы, какие числа проверяемы, а какие приняты на слово.
 *
 * ## Почему снимок накопительный
 *
 * Копилки на клиенте копятся с начала матча, и снимок несёт их целиком,
 * а не приращение с прошлой отправки. Канал у игрока рваный — это
 * замерено, — и снимки будут теряться. Накопительному это безразлично:
 * следующий через пять секунд принесёт и своё, и потерянное.
 *
 * Платит за это сервер: в общие ряды он обязан вливать разность,
 * а не снимок целиком.
 */

/**
 * Имена рядов, одним списком.
 *
 * Список именно здесь, а не по копии у отправителя и у приёмника.
 * Два списка в двух файлах однажды разъехались бы молча: клиент начал
 * бы слать ряд, которого приёмник не ждёт, и ряд пропадал бы без следа
 * и без ошибки.
 */
export const READING_ROWS = [
  'frame',
  'netGap',
  'displayGap',
  'shift',
  'jump',
  'pendingOnJump',
] as const;

export type ReadingRow = (typeof READING_ROWS)[number];

/**
 * Ряды снимка.
 *
 * Каждый необязателен, и это не послабление к порядку. Страница живёт
 * у игрока в открытой вкладке дольше, чем выкладка: снимок от прежнего
 * бандла обязан приниматься, иначе счётчик отвергнутых покраснеет
 * от нашей же выкладки. Пришедший, но порченый ряд — отвергается
 * наравне с остальными.
 */
export type ReadingRows = {
  readonly [Row in ReadingRow]?: HistogramSnapshot;
};

/** Мгновенные величины: не распределения, а «что было в эту минуту». */
export interface ReadingMoment {
  /** Показываемый тик. По его скачку виден догон истории. */
  readonly tick: number;
  /** Задержка ввода на этот момент. */
  readonly delayTicks: number;
  /** Сколько своих команд в пути. */
  readonly pending: number;
}

/**
 * Что клиент отправляет.
 *
 * Билет едет затем, чтобы сервер опознал матч и сторону сам. Ни того
 * ни другого клиент не сообщает вовсе: точка приёма смотрит в интернет,
 * и всё, что клиент о себе говорит, проверке не подлежит.
 */
export type ReadingsReport = ReadingRows &
  ReadingMoment & {
    /** Билет матча — тот же, которым участник входил в игру. */
    readonly ticket: string;
    /**
     * Порядковый номер снимка, с единицы.
     *
     * Нужен не приёмнику, а читателю: по разрыву в нумерации видно,
     * что снимок потерялся по дороге, а по возврату к единице — что
     * игрок перезагрузил страницу посреди матча.
     */
    readonly seq: number;
  };

/**
 * Что сервер пишет в файл.
 *
 * Билета здесь нет: он опознаёт человека. Матч и сторона опознают
 * партию, но не игрока, и этого разбору достаточно — требование
 * «показания отдаются без сведений об игроках» действует и для
 * хранимых показаний.
 */
export type ReadingsRecord = ReadingRows &
  ReadingMoment & {
    readonly t: 'readings';
    readonly matchId: string;
    readonly side: number;
    readonly seq: number;
    /** Время сервера, а не клиента: чужим часам верить незачем. */
    readonly atMs: number;
  };
