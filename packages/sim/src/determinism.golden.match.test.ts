/**
 * Golden-тест детерминизма — главный страж честного PvP.
 *
 * Идея простая: прогоняем симуляцию строго заданное число тиков с
 * фиксированным seed и фиксированной записью команд, а итоговую
 * контрольную сумму сравниваем с эталоном, записанным в этом файле.
 *
 * Что он ловит:
 *   - случайно просочившийся Math.random или Date.now в ядре;
 *   - зависимость от порядка перебора ключей объекта;
 *   - незаявленное изменение игровых правил.
 *
 * Если тест упал, а поведение менялось намеренно — эталон нужно обновить
 * тем же коммитом, что и правку правил. Тогда история изменений баланса
 * видна в diff, а не теряется.
 */

const GOLDEN_SEED = 1337;
const GOLDEN_TICKS = 1200;

/** Базы стоят в противоположных углах; клетки рядом с ними известны заранее. */
const BASE_INSET = 6;

/**
 * Воспроизводимая запись команд.
 *
 * Сценарий задействует все механики сразу: движение генерала,
 * строительство, производство юнитов всех типов, прокачку и ядерный удар.
 * Чем шире охват, тем больше шансов, что случайно просочившийся источник
 * недетерминизма изменит итоговую сумму.
 */
const scriptedCommands = (tick: number): Command[] => {
  const commands: Command[] = [];

  for (const player of [0, 1]) {
    // Смещение в три клетки, а не в две: вокруг базы появилось защищённое
    // кольцо, и с прежним смещением ближайшая постройка сценария — стена —
    // отклонялась всегда. Сценарий продолжал бы «проходить», охраняя
    // при этом мир без единой стены.
    const near = player === 0 ? BASE_INSET + 3 : MAP_WIDTH_CELLS - 1 - BASE_INSET - 3;
    const side = player === 0 ? 1 : -1;

    // Генерал меняет направление раз в пару секунд: движение обязано
    // быть воспроизводимым, включая упоры в препятствия.
    //
    // Деление здесь и ниже обязательно целочисленное. Обычное `tick / 60`
    // даёт дробь, а дробный индекс направления или типа юнита ядро молча
    // отклоняет — и сценарий незаметно превращается в пустой прогон.
    if (tick % 60 === player * 10) {
      commands.push({
        kind: CommandKind.MoveGeneral,
        player: asPlayerId(player),
        tick: asTickNumber(tick),
        direction: (Math.floor(tick / 60) % 8) + 1,
      });
    }

    // Постройки вокруг базы: стены и башни вперемешку.
    //
    // Место выбирается веером из нескольких клеток, а не одной. Вокруг базы
    // есть и скалы, и защищённое кольцо, и одна фиксированная клетка легко
    // оказывается негодной — тогда сценарий молча перестаёт ставить
    // постройки этого вида, продолжая при этом «проходить». Лишние команды
    // ядро отклонит, а отказы в контрольную сумму не входят.
    if (tick % 90 === 30 + player * 5) {
      const shift = Math.floor(tick / 90) % 3;

      for (let dx = 0; dx < 3; dx += 1) {
        for (let dy = 0; dy < 3; dy += 1) {
          commands.push({
            kind: CommandKind.Build,
            player: asPlayerId(player),
            tick: asTickNumber(tick),
            cell: cellIndex(near + side * dx, near + side * dy),
            // Виды чередуются в шахматном порядке, а сдвиг меняет её от раза
            // к разу. Прежняя схема ставила один вид за раз в одну клетку,
            // и стоило клетке оказаться скалой — постройки этого вида
            // исчезали из сценария целиком.
            structure: (dx + dy + shift) % 2 === 0 ? StructureKind.Wall : StructureKind.TowerBasic,
          });
        }
      }
    }

    // Снос: раз в шесть секунд разбирается угол веера.
    //
    // Сценарий существует ради охвата всех механик сразу, и снос — такая же
    // механика, как стройка. Команды по пустым клеткам ядро отклонит,
    // а отказы в контрольную сумму не входят.
    if (tick % 180 === 100 + player * 5) {
      // Тот же веер, что и у стройки, и по той же причине: угадать
      // заранее, какая клетка окажется землёй, а какая скалой, нельзя.
      for (let dx = 0; dx < 3; dx += 1) {
        for (let dy = 0; dy < 3; dy += 1) {
          commands.push({
            kind: CommandKind.Demolish,
            player: asPlayerId(player),
            tick: asTickNumber(tick),
            cell: cellIndex(near + side * dx, near + side * dy),
          });
        }
      }
    }

    // Производство: три типа по кругу.
    if (tick % 40 === 10 + player * 3) {
      const type = (Math.floor(tick / 40) % 3) as UnitType;
      commands.push({
        kind: CommandKind.TrainUnit,
        player: asPlayerId(player),
        tick: asTickNumber(tick),
        unitType: type,
      });
    }

    // Прокачка: перебираем ветки по кругу.
    if (tick % 70 === 20 + player * 7) {
      commands.push({
        kind: CommandKind.BuyUpgrade,
        player: asPlayerId(player),
        tick: asTickNumber(tick),
        branch: Math.floor(tick / 70) % UPGRADE_BRANCHES.length,
      });
    }

    // Ядерный удар в середину карты — единственная точка, гарантированно
    // лежащая вне запретной зоны обеих баз. Координаты считаются от размера
    // карты, а не вписаны числом: карта уже однажды меняла размер, и тогда
    // вписанная точка молча уехала за её край, а удар — в никуда.
    //
    // Одних команд для удара НЕ ХВАТАЕТ, и это выяснилось не сразу.
    // За сорок секунд сценария игрок зарабатывает около четырёх сотен
    // единиц и почти всё тратит на стройку, войско и прокачку: к тику 900
    // у него оставалось тридцать семь. Обе команды удара отклонялись
    // по нехватке энергии — молча, потому что отказы в контрольную сумму
    // не входят, — и сценарий «задействовал все механики сразу» без
    // единого взрыва. Ни одно правило ядерного удара эталон при этом
    // не охранял: ни радиус, ни мощность, ни то, что запись об ударе
    // входит в сумму.
    //
    // Лечится доводкой энергии ровно перед пуском, см. `affordNuke`.
    if (tick === NUKE_TICKS[player]) {
      commands.push({
        kind: CommandKind.LaunchNuke,
        player: asPlayerId(player),
        tick: asTickNumber(tick),
        cell: cellIndex(MAP_WIDTH_CELLS / 2, MAP_HEIGHT_CELLS / 2),
      });
    }
  }

  return commands;
};

/** На каком тике каждый игрок бьёт ядеркой. */
const NUKE_TICKS = [900, 930];

/**
 * Доводка энергии ровно перед пуском: игроку добавляется цена удара.
 *
 * Единственное место, где сценарий трогает состояние мира, а не отдаёт
 * команду, — и потому объяснить его надо целиком.
 *
 * Дохода на удар не хватает (см. разбор у команды пуска), а поднять
 * стартовую энергию нельзя: она гейтит и стройку, и войско, и прокачку,
 * и щедрый старт переписал бы весь сценарий, а не добавил бы к нему
 * взрыв. Прибавка ровно в цену удара и ровно перед ним меняет одно
 * событие и не трогает ни одного другого.
 *
 * Цена берётся у характеристик игрока, а не из константы: она выводится
 * из радиуса, а радиус прокачивается. Прибавка `+ 1` — на доход того
 * тика, в котором пуск и случится: без неё игрок оказывается должен
 * ровно единицу.
 */
const affordNuke = (world: WorldState, tick: number): WorldState => {
  const player = NUKE_TICKS.indexOf(tick + 1);
  if (player < 0) return world;

  return {
    ...world,
    players: world.players.map((entry, index) =>
      index === player
        ? { ...entry, energy: entry.energy + playerStats(entry).nuke.cost + 1 }
        : entry,
    ),
  };
};

const runGolden = (): number => {
  let world = createWorld(GOLDEN_SEED);
  for (let tick = 0; tick < GOLDEN_TICKS; tick += 1) {
    world = step(affordNuke(world, tick), scriptedCommands(tick));
  }
  return checksum(world);
};

describe('детерминизм симуляции', () => {
  it('два прогона в одном процессе дают одинаковую контрольную сумму', () => {
    expect(runGolden()).toBe(runGolden());
  });

  it('совпадает с эталонной контрольной суммой', () => {
    // Эталон вычислен на правилах из двух изменений сразу.
    //
    // slow-down-construction: время возведения выросло у всех трёх построек,
    // а прочность набирается по расписанию, а не прибавкой с округлением
    // вверх. protect-base-surroundings: вокруг каждой базы появилось кольцо,
    // в котором строить нельзя, и сценарий пришлось отодвинуть от базы —
    // с прежним смещением все его стены отклонялись.
    //
    // Следом добавились ещё три правила: дальность генерала выросла
    // до пяти клеток, а у снайпера и Теслы появились ветки
    // прокачки дальности — от них поехал и состав покупок сценария,
    // который перебирает ветки по кругу.
    //
    // И наконец добавился снос: у постройки появился тик исчезновения,
    // а сценарий научился разбирать собственный веер.
    //
    // И режимы атаки: поведение по умолчанию сменилось с «остановись
    // перед встречным» на «прорывайся, ведя огонь на ходу».
    //
    // Затем добавился разворот постройки. Правила боя он не трогает:
    // сектора обстрела нет, разворот мгновенный, стрелять можно назад.
    // Но это величина состояния мира, и в сумму она входит наравне
    // с разворотом юнита — иначе рассинхрон по ней остался бы незамеченным.
    // Поэтому сумма сдвинулась, хотя ни одно правило не изменилось.
    //
    // Последним сократилась вчетверо перезарядка генерала: с тридцати
    // тиков до восьми. Здесь правило изменилось прямо, и сумма обязана
    // была сдвинуться — генерал стреляет в сценарии, и с четырёхкратной
    // скорострельностью ход боя расходится с прежним уже на первых
    // выстрелах. Борт ракеты, заведённый тем же изменением, на сумму
    // не влияет: он в неё намеренно не входит (см. `checksum.ts`).
    //
    // В этом слиянии правила изменились ДВАЖДЫ, и разбор нужен на оба.
    //
    // Ветеранские ранги: вместо непрерывных пяти процентов сложным
    // процентом — пять ступеней с общими порогами 1/3/6/10/15 и двумя
    // таблицами силы (башне до удвоения, машине до полутора), и ранги
    // теперь набирают ещё и юниты. Правило боя изменилось прямо, но сумма
    // сдвинулась бы и без единого выстрела: поле `kills` входит в неё
    // у каждой постройки и каждого юнита, а базы есть в любом сценарии.
    //
    // Расталкивание: у машины завёлся личный радиус, и после движения строй
    // разводится, чтобы войско не слипалось в точку. Правило меняет
    // положения юнитов, а положения входят в сумму. Полей в состоянии мира
    // при этом не прибавилось: смещение выводится из положений каждый тик.
    //
    // Эталон посчитан на обоих правилах сразу — порознь их числа
    // 3815411508 (только ранги) и 871233069 (только расталкивание)
    // и в истории остаются как промежуточные.
    //
    // И наконец прокачался сам ядерный удар — и здесь сумма двигалась
    // дважды, причём разбор первого раза оказался НЕВЕРЕН, и это стоит
    // прочесть целиком.
    //
    // В первый раз (1152514732) сумму сдвинуло единственное: массив
    // уровней прокачки удлинился на две ветки, а он входит в сумму
    // у каждого игрока. Тогда было записано, что сдвиг вызван ещё
    // и новыми полями записи об ударе, — неправда. Проверилось это
    // случайно: цену удара удвоили, а сумма не дрогнула. Не дрогнула
    // потому, что удара в сценарии НЕ БЫЛО: обе команды пуска
    // отклонялись по нехватке энергии, а отказы в сумму не входят.
    //
    // Второй раз (2067497138) — от той самой доводки энергии, которой
    // это вылечено, плюс от удвоенной цены пуска и удвоенного шага
    // ядерных веток. Теперь удар в сценарии действительно гремит,
    // и радиус с мощностью в сумму действительно входят. Стережёт
    // это отдельная проверка «оба удара дошли до взрыва»: без неё дыра
    // затянулась бы обратно так же молча, как открылась.
    //
    // И наконец сюда же пришло расталкивание юнитов (`push-units-apart`,
    // эталон 1340422107) — правка того же тика, но чужая. Сумма поэтому
    // пересчитана на СЛИЯНИИ двух правок, а не выведена из одной из них:
    // расталкивание двигает положения, ядерный удар — прочность
    // и запись об ударе, и обе величины входят в сумму.
    //
    // Сюда пришла новая генерация мира (`compact-map-and-island-rocks`) —
    // тремя шагами, и каждый двигал сумму: поле 38 × 38 вместо 48 × 48
    // (4136712671), посадка скальных массивов островками вместо
    // случайного блуждания (1694083486) и раскрытие проходов до трёх
    // клеток (2258099750).
    //
    // Правил игры не трогал ни один из шагов — менялось поле, на котором
    // они разыгрываются, а этого хватает: другие клетки под ногами, другие
    // пути, другие места встречи. Сумма при таком изменении обязана
    // сдвинуться, и не сдвинься она — это был бы повод искать ошибку
    // в самой сумме.
    //
    // И последней — настройка ядерки (`tune-the-nuke`), которая двигает
    // сумму по трём различимым причинам. Первая: таблица веток удлинилась
    // на ветку отката, а массив уровней входит в сумму у каждого игрока —
    // то есть сумма сдвинулась бы и в матче, где ядерка не применялась
    // вовсе. Вторая: в сумму добавлен тик готовности пусковой установки.
    // Третья: цена пуска считается от уровней прокачки, а не от площади
    // круга, и энергия после удара у обоих игроков выходит другой.
    //
    // Число ПЕРЕСНЯТО на слиянии, а не выбрано из двух: карта и правила
    // ядерки меняют разные слагаемые одной суммы, и ни одно из двух
    // чисел по отдельности после слияния не верно.
    //
    // Предыдущие эталоны: 2258099750 — новая генерация мира;
    // 1694083486 — островки без раскрытия проходов;
    // 4136712671 — поле 38 × 38 со старой генерацией;
    // 3303966452 — настройка ядерки на карте 48 × 48;
    // 3129409696 — прокачка мощности и радиуса;
    // 1340422107 — расталкивание юнитов;
    // 2067497138 — ядерный удар с уроном и прокачкой;
    // 1152514732 — ядерные ветки прокачки;
    // 1820139674 — ветеранские ранги;
    // 4262254141 — залп генерала;
    // 1549904538 — разворот постройки;
    // 2055560148 — режимы атаки; 1886512028 — снос;
    // 1724205168 — дальность
    // генерала и ветки
    // дальности; 3833150104 — стройка и кольцо базы;
    // 3677035819 — только slow-down-construction;
    // 519025619 — refine-targeting-and-ai-posture и add-detailed-models.
    //
    // Меняйте его ТОЛЬКО вместе с намеренным изменением игровых правил,
    // и тем же коммитом — тогда история баланса видна в diff.
    const GOLDEN_CHECKSUM = 513359514;

    expect(runGolden()).toBe(GOLDEN_CHECKSUM);
  });

  it('сценарий действительно доводит дело до боя', () => {
    // Страховка от вырождения: если сценарий перестанет что-либо делать,
    // сумма всё равно будет стабильной, и тест начнёт охранять пустоту.
    let world = createWorld(GOLDEN_SEED);

    // Виды собираются за весь прогон, а не снимаются в конце. Башня
    // у базы вполне может не дожить до последнего тика — это законный ход
    // матча, а не вырождение сценария. Вырождение — это когда башню
    // ни разу не поставили.
    const seen = new Set<StructureKind>();
    let demolished = false;
    let launched = 0;
    let detonated = 0;

    for (let tick = 0; tick < GOLDEN_TICKS; tick += 1) {
      const before = world.nukes.length;
      world = step(affordNuke(world, tick), scriptedCommands(tick));

      launched += Math.max(0, world.nukes.length - before);
      detonated += Math.max(0, before - world.nukes.length);

      for (const structure of world.structures) {
        seen.add(structure.kind);
        if (structure.demolishAtTick > 0) demolished = true;
      }
    }

    // Снос задействован хотя бы раз: без этой проверки команда сноса
    // могла бы отклоняться всегда, а сценарий продолжал бы «проходить».
    expect(demolished).toBe(true);

    // Оба удара дошли до взрыва.
    //
    // Проверка заведена по следам молчаливой дыры: команды пуска
    // отклонялись по нехватке энергии, отказы в сумму не входят,
    // и эталон годами «охранял» ядерный удар, которого в сценарии
    // не случалось ни разу. Считать нужно ИМЕННО пуски и взрывы:
    // в конце прогона записей об ударе нет в обоих случаях — и когда
    // удар отгремел, и когда его не было вовсе.
    expect(launched).toBe(2);
    expect(detonated).toBe(2);

    expect(world.structures.length).toBeGreaterThan(2);
    expect(world.units.length).toBeGreaterThan(0);

    // Виды названы поимённо. Общего счётчика мало: правило, отсекающее
    // ровно один вид построек, оставило бы счётчик прежним, и охват
    // сценария сузился бы молча.
    expect(seen.has(StructureKind.Wall)).toBe(true);
    expect(seen.has(StructureKind.TowerBasic)).toBe(true);
  });

  it('сценарий доводит дело до ветеранских рангов', () => {
    // Проверка того же рода, что «доводит дело до боя», и заведена
    // по той же причине. Зелёный эталон НЕ доказывает, что правило рангов
    // цело: сумма сдвинется от одного поля `kills` в состоянии базы,
    // даже если ранга не возьмёт никто.
    //
    // Проверяется ПЕРВЫЙ ранг из пяти: сценарий доводит лучший объект
    // до одного-двух убийств, не больше. Значит, со второго по пятый ранг
    // и потолок множителя здесь не проверяются вовсе — их закрывают
    // точечные тесты в `combat.test.ts`, и снимать их нельзя.
    //
    // Охват просел вместе с уменьшением карты, и просел он честно.
    // Раньше сценарий доводил лучший объект до трёх убийств; на поле
    // 38 × 38 бой не пропал (за прогон гибнет пять машин, вдвое больше
    // прежнего), но растёкся: стычки идут в нескольких местах сразу,
    // убийцы гибнут сами, и накопителя больше не образуется. Удлинение
    // прогона в полтора раза не помогает — смертей девять, накопитель
    // тот же.
    //
    // Порог поэтому сформулирован не числом убийств, а взятым рангом:
    // число было снимком прошлой карты и устаревало при каждой правке
    // поля, а правило «есть убийство — есть ранг» не устаревает.
    //
    // Просядет охват — тест упадёт, и это станет видно, а не останется
    // молчаливой дырой.
    let world = createWorld(GOLDEN_SEED);
    let topKills = 0;

    for (let tick = 0; tick < GOLDEN_TICKS; tick += 1) {
      world = step(world, scriptedCommands(tick));

      for (const structure of world.structures) topKills = Math.max(topKills, structure.kills);
      for (const unit of world.units) topKills = Math.max(topKills, unit.kills);
    }

    // Проверяем не число убийств, а взятый ранг: охраняется здесь именно
    // связь «убил — получил ранг», и порог у неё свой, записанный
    // в `VETERAN_RANK_KILLS`. Сравнение с вписанным числом сравнивало
    // сценарий с прошлой картой, а не правило — с самим собой.
    expect(veteranRank(topKills)).toBeGreaterThanOrEqual(1);
  });

  it('различает состояния, отличающиеся одним полем', () => {
    const world = createWorld(GOLDEN_SEED);
    const modified = { ...world, tick: asTickNumber(1) };

    expect(checksum(world)).not.toBe(checksum(modified));
  });
});
