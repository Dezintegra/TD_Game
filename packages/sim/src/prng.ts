/**
 * Детерминированный генератор псевдослучайных чисел (алгоритм xorshift32).
 *
 * Math.random() нам не подходит принципиально: он даёт разные числа при
 * каждом запуске, а значит клиент и сервер, прогоняя одну и ту же симуляцию,
 * получат разные результаты. Здесь же всё наоборот — одинаковое начальное
 * состояние (seed) всегда даёт одну и ту же последовательность чисел.
 *
 * Состояние генератора хранится прямо в состоянии мира, поэтому оно
 * откатывается вместе с ним при rollback и попадает в контрольную сумму.
 */
export interface RngState {
  readonly value: number;
}

export const createRng = (seed: number): RngState => ({
  // Ноль — вырожденное состояние xorshift: из него генератор не выберется,
  // поэтому подменяем его на произвольную ненулевую константу.
  value: (seed | 0) === 0 ? 0x9e3779b9 : seed | 0,
});

/**
 * Возвращает следующее состояние генератора и очередное 32-битное число.
 *
 * Функция чистая: она ничего не мутирует, а отдаёт новое состояние.
 * Вызывающий код обязан сохранить его — иначе последовательность
 * не сдвинется и вы получите одно и то же число снова.
 */
export const nextRng = (state: RngState): readonly [RngState, number] => {
  let x = state.value;
  x ^= x << 13;
  x |= 0;
  x ^= x >>> 17;
  x ^= x << 5;
  x |= 0;
  // Приводим к беззнаковому виду: удобнее брать остаток от деления.
  return [{ value: x }, x >>> 0];
};

/** Случайное целое в диапазоне [0, bound). */
export const nextRngInt = (state: RngState, bound: number): readonly [RngState, number] => {
  const [next, raw] = nextRng(state);
  return [next, raw % bound];
};
