import type { PlayerId } from '@td/shared';
import type { Spending } from './profile.js';

/**
 * Наблюдение за решениями противника.
 *
 * Зачем это здесь, а не в инструменте разбора. Мир показывает, что
 * случилось. Он не показывает, чего противник ХОТЕЛ: что места под башню
 * не нашлось, что он копил на дорогое, что терпение кончилось, что
 * положительной выгоды не было ни у одного рубежа. Снаружи все эти случаи
 * выглядят одинаково — «он просто стоит», — и восстановить их по потоку
 * команд невозможно, потому что команд в этих случаях как раз и нет.
 *
 * ## Главное правило: наблюдение не меняет игру
 *
 * Наблюдатель только принимает уже посчитанное. Ему запрещено обращаться
 * к генератору случайных чисел, менять порядок обхода чего бы то ни было
 * и заставлять противника считать что-либо дополнительно.
 *
 * Правило не формальность. Случайность живёт в замыкании противника,
 * и одно лишнее обращение к ней сдвинуло бы всю последующую
 * последовательность решений — разбирать мы стали бы не тот матч,
 * который играли. Свойство закреплено тестом: прогон с наблюдателем
 * и без него обязан дать одинаковую контрольную сумму.
 *
 * Оценки всех рубежей достаются бесплатно: противник считает их все
 * на каждом решении и до сих пор просто оставлял себе победителя.
 */

/**
 * Что помешало покупке.
 *
 * Ради этого перечисления вся затея с наблюдателем во многом и нужна.
 * «Не построил башню» может означать четыре совершенно разные вещи,
 * и лечатся они по-разному: нет денег — вопрос к экономике, нет места —
 * к выбору рубежа, не дошла очередь трат — к порядку фазы.
 *
 * Причина называет **помеху**, а не исход. Помеха «не хватает энергии»
 * одна и та же и когда противник копит, и когда махнул рукой; что
 * из двух — говорит `AttemptResult`. Заводить на это две причины значило
 * бы описывать одно и то же дважды и в разных местах.
 */
export const AttemptNote = {
  /** Очередь производства и так заполнена до целевой глубины. */
  QueueFull: 'queue-full',
  /** В составе фазы все веса нулевые: заказывать нечего. */
  MixEmpty: 'mix-empty',
  /** На юнита не хватает энергии. */
  UnitUnaffordable: 'unit-unaffordable',
  /** Генерал мёртв — строить некому. */
  GeneralDead: 'general-dead',
  /** Выбранный вид постройки не возводится. */
  NotBuildable: 'not-buildable',
  /** На постройку не хватает энергии. */
  StructureUnaffordable: 'structure-unaffordable',
  /** Места под башню, накрывающую ненакрытый путь, не нашлось. */
  NoTowerSite: 'no-tower-site',
  /** Места под прикрывающую стену не нашлось. */
  NoShieldSite: 'no-shield-site',
  /** В ветках фазы покупать нечего. */
  NothingToUpgrade: 'nothing-to-upgrade',
  /** На улучшение не хватает энергии. */
  UpgradeUnaffordable: 'upgrade-unaffordable',
} as const;

export type AttemptNote = (typeof AttemptNote)[keyof typeof AttemptNote];

/**
 * Чем кончилась попытка.
 *
 * `wait` — самое важное здесь и самое незаметное снаружи. Оно означает
 * «хочу, но пока не по карману, и мелочь вместо этого покупать не буду».
 * Именно оно однажды загнало противника в ступор на весь матч, и без
 * записи о нём разобраться в таком было бы нечем.
 */
export type AttemptResult = 'bought' | 'wait' | 'pass';

/** Чем закончилась одна попытка потратить энергию. */
export interface AttemptRecord {
  readonly spending: Spending;
  readonly result: AttemptResult;
  /** Причина, по которой не купил. У `bought` отсутствует. */
  readonly note?: AttemptNote;
  /**
   * Цена того, что попытка хотела купить.
   *
   * Без неё запись «коплю» не отвечает на главный вопрос — на что именно
   * и сколько ещё. А ответ на него нужен: копить на улучшение за четыре
   * тысячи разумно, а на удар за тридцать семь — нет, и снаружи эти два
   * случая выглядят одинаково.
   */
  readonly price?: number;
}

/** Оценка одного рубежа, как её увидел противник. */
export interface FrontierRecord {
  readonly fraction: number;
  readonly cell: number;
  readonly coverage: number;
  readonly gain: number;
  readonly risk: number;
  readonly score: number;
  readonly deathChance: number;
  /** Этот рубеж и выбран. Ровно один в записи, либо ни одного. */
  readonly chosen: boolean;
}

export interface DecisionRecord {
  readonly tick: number;
  readonly player: PlayerId;
  /** Номер фазы в профиле. Имя фазы не хранится: фазы безымянны. */
  readonly phaseIndex: number;
  readonly waitStreak: number;
  /** Терпение кончилось: желание «подождать» на этом решении игнорируется. */
  readonly impatient: boolean;
  /**
   * Генерал ушёл вперёд без прикрытия и потому набирает войско.
   *
   * Без этого признака «купил юнита вместо улучшения» выглядит
   * необъяснимым отклонением от порядка фазы.
   */
  readonly escorting: boolean;
  readonly liveUnits: number;
  /**
   * Сколько своих юнитов рядом с генералом.
   *
   * Пишется рядом с общей численностью, а не вместо неё, и это важно:
   * именно расхождение двух величин показало, что «прикрыт» означало
   * «юниты есть где-то на карте». Из одной только численности этого
   * не увидеть.
   */
  readonly nearbyUnits: number;
  readonly spendOrder: readonly Spending[];
  readonly attempts: readonly AttemptRecord[];
  /** Оценки ВСЕХ рубежей, а не только выбранного. */
  readonly frontiers: readonly FrontierRecord[];
  readonly generalCell: number;
  /** Расстояние генерала от своей базы по проходимым клеткам. */
  readonly generalFromHome: number;
  /** Длина кратчайшего маршрута между базами: знаменатель доли пути. */
  readonly approachShortest: number;
  readonly energy: number;
  /** Нанесён ядерный удар: остальные траты на этом решении пропущены. */
  readonly struck: boolean;
  readonly commandCount: number;
}

/**
 * Приёмник записей о решениях.
 *
 * Функция, а не объект с методом: приёмник ровно один, и обставлять
 * его интерфейсом значило бы усложнять на ровном месте.
 */
export type DecisionObserver = (record: DecisionRecord) => void;
