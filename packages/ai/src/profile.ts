import { NUKE_COST, PRODUCTION_QUEUE_CAP, TICKS_PER_SECOND, UnitType, UpgradeTarget } from '@td/shared';

/**
 * Профиль поведения — все числа, задающие манеру игры противника.
 *
 * Зачем он нужен. Пока эти числа были константами модуля, невозможны были
 * три вещи: честно сравнить два варианта настройки (оставалось «поиграл,
 * вроде стало лучше»), откатить неудачную настройку иначе, чем откатом
 * кода, и записать в разбор матча, какой именно настройкой он сыгран.
 *
 * ## Числа хранятся в человеческих единицах
 *
 * Секунды, клетки, доли — а не тики и не единицы с фиксированной точкой.
 * Перевод во внутренние выполняется при чтении, вспомогательными
 * функциями внизу файла.
 *
 * Это сознательный отход от того, как устроен `balance.ts`, и вот почему.
 * Профиль правит руками человек, сравнивая варианты: `horizonSeconds: 60`
 * он поймёт сразу, `horizonTicks: 1800` — нет. Ядро такой вольности себе
 * позволить не может, потому что переводы внутри тика стоили бы дорого
 * и накапливали бы ошибку округления. Здесь перевод случается дважды
 * в секунду, и его цена неизмерима.
 *
 * ## Что профиль умеет и чего не умеет
 *
 * Профиль меняет **настройку**, но не **устройство**: числа в формулах,
 * порядок перебора уже существующих возможностей — да; сами формулы,
 * состав этапов решения, новые возможности — нет. Откат неудачной
 * настройки делается сменой профиля, откат неудачного устройства —
 * откатом кода. Держать в репозитории мёртвые ветки ради «отката
 * поведения» мы не будем: разбор матчей хранит версию кода, и этого
 * достаточно, чтобы сравнить устройство до и после.
 *
 * ## Профиль неизменяем
 *
 * Заморожен вглубь, и не из чистоплюйства. Профиль читается на каждом
 * решении; случайная запись в него посреди матча дала бы поведение,
 * невоспроизводимое по seed, — то есть уничтожила бы главное свойство,
 * ради которого всё и затевалось.
 */

/** На что можно потратить энергию за одно решение. */
export type Spending = 'upgrade' | 'build' | 'train';

/**
 * Неприкосновенный запас энергии фазы.
 *
 * Не число, а одно из двух состояний. Причина в том, что запас существует
 * ради вполне конкретной вещи — накопить на ядерный удар, — и записывать
 * его отдельным числом значило бы завести второй источник истины о цене
 * удара. Поменяется цена в балансе, а профиль останется со старой,
 * и противник начнёт копить не то, что нужно.
 */
export type Reserve = 'none' | 'nuke';

export interface PhaseProfile {
  /** До какой секунды матча действует фаза. */
  readonly untilSecond: number;
  /** Ветки прокачки, интересные в этой фазе, в порядке предпочтения. */
  readonly upgrades: readonly UpgradeTarget[];
  /** Доля юнитов каждого типа: сумма весов задаёт вероятности. */
  readonly mix: Readonly<Record<UnitType, number>>;
  /**
   * Порядок трат. Первое, что удалось купить, останавливает перебор:
   * за одно решение противник совершает не более одной покупки.
   */
  readonly spend: readonly Spending[];
  readonly reserve: Reserve;
}

export interface AiProfile {
  /**
   * Устойчивое имя. Попадает в разбор матча и в командную строку
   * инструментов, поэтому меняться у существующего профиля не должно:
   * переименование разрывает связь с уже сыгранными матчами.
   */
  readonly id: string;

  readonly movement: {
    /** На сколько клеток вперёд по маршруту берётся прицел движения. */
    readonly lookaheadCells: number;
    /** Дальше этой доли пути рубеж считается наступательным. */
    readonly advanceFraction: number;
  };

  readonly building: {
    /** Каждая N-я постройка — стена, прикрывающая уже стоящие башни. */
    readonly wallEvery: number;
    /** В каком радиусе от генерала ищутся свои башни, которые стоит прикрыть. */
    readonly cellsAroundGeneral: number;
    /** В скольких клетках от своей башни имеет смысл ставить стену. */
    readonly shieldRadiusCells: number;
  };

  readonly spending: {
    /** Насколько далёкую покупку имеет смысл ждать, в секундах дохода. */
    readonly savingHorizonSeconds: number;
    /** Сколько решений подряд разрешено копить, ничего не покупая. */
    readonly maxWaitDecisions: number;
    /** Сколько заказов держать в очереди производства. */
    readonly queueTarget: number;
  };

  readonly escort: {
    /** Сколько своих юнитов делают генерала прикрытым на наступлении. */
    readonly units: number;
    /** Порядок трат, пока сопровождения не набралось. */
    readonly spend: readonly Spending[];
  };

  readonly nuke: {
    /** Сколько вражеских юнитов оправдывают удар. */
    readonly worthUnits: number;
    /** Шаг сетки при поиске места для удара, в клетках. */
    readonly scanStep: number;
  };

  readonly posture: {
    /** Доли вероятного пути, на которых генерал готов встать. */
    readonly frontierFractions: readonly number[];
    /** Насколько клетка может отстоять от желаемого расстояния. */
    readonly bandCells: number;
    /** Радиус, в котором вражеские юниты считаются угрозой базе, в клетках. */
    readonly threatRadiusCells: number;
    /** Горизонт планирования, в секундах. */
    readonly horizonSeconds: number;
  };

  readonly phases: readonly PhaseProfile[];
}

// ─────────────────────────────────────────────────────────────────────────
// Перевод в единицы ядра
// ─────────────────────────────────────────────────────────────────────────

/** Горизонт планирования в тиках. */
export const horizonTicks = (profile: AiProfile): number =>
  profile.posture.horizonSeconds * TICKS_PER_SECOND;

/** Неприкосновенный запас фазы в единицах энергии ядра. */
export const reserveOf = (phase: PhaseProfile): number =>
  phase.reserve === 'nuke' ? NUKE_COST : 0;

/**
 * Фаза, действующая на этом тике.
 *
 * Последняя фаза замыкает список с бесконечным порогом, поэтому поиск
 * всегда что-нибудь находит и запасной вариант нужен лишь формально.
 */
export const phaseAt = (profile: AiProfile, tick: number): PhaseProfile => {
  const seconds = tick / TICKS_PER_SECOND;
  const found = profile.phases.find((phase) => seconds < phase.untilSecond);
  const last = profile.phases[profile.phases.length - 1];

  if (found !== undefined) return found;
  if (last === undefined) throw new Error('профиль без фаз');

  return last;
};

