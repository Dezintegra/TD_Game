/** Горизонт планирования в тиках. */
export const horizonTicks = (profile: AiProfile): number =>
  profile.posture.horizonSeconds * TICKS_PER_SECOND;

/**
 * Предел терпения: сколько решений подряд разрешено копить.
 *
 * Вычисляется, а не хранится. Ждать разрешено только тогда, когда цена
 * укладывается в горизонт при нынешнем доходе, а во время накопления
 * деньги не тратятся — значит, энергия растёт монотонно и цена достигается
 * за время не длиннее горизонта. Отсюда: предел, равный горизонту,
 * не обрывает ни одного законного накопления, а всё, что он обрывает,
 * законным не было.
 *
 * Прежние восемь решений при горизонте в сорок пять секунд означали
 * четыре секунды против сорока пяти. В предел упиралось каждое
 * накопление, и «копить» на деле означало «потерять четыре секунды
 * и купить что подвернулось».
 */
export const patienceDecisions = (profile: AiProfile, guarded = false): number =>
  (horizonSecondsOf(profile, guarded) * TICKS_PER_SECOND) / AI_DECISION_INTERVAL_TICKS;

/**
 * Сколько секунд противник согласен копить в этой обстановке.
 *
 * Обстановок две, и различает их одно: стоят ли на пути вражеские
 * башни. Против нападающего копить вредно — накопленное не стоит
 * на поле, а исход решает войско на поле. Против обороны копить
 * необходимо: волна, посланная по частям, гибнет по частям.
 *
 * Профиль, назвавший одно число, ведёт себя как прежде в обеих.
 */
const horizonSecondsOf = (profile: AiProfile, guarded: boolean): number =>
  guarded
    ? (profile.spending.guardedHorizonSeconds ?? profile.spending.savingHorizonSeconds)
    : profile.spending.savingHorizonSeconds;

/**
 * Радиус, в котором свои юниты считаются прикрытием генерала.
 *
 * Выводится, а не задаётся числом: это сумма дальности генерала
 * и дальности юнита. Смысл прямой — на таком расстоянии юнит и генерал
 * достают до одного и того же противника, то есть действительно дерутся
 * вместе. При нынешних двух клетках у обоих получается четыре.
 *
 * Величина растёт от прокачки дальности, и это правильно: дальнобойное
 * войско прикрывает с большего расстояния.
 *
 * Считать вместо этого ВСЕХ живых юнитов было ошибкой, которую замер
 * поймал сразу: в шести случаях из десяти признак «генерал прикрыт»
 * выполнялся, когда рядом с ним не было ни одного своего.
 */
export const escortRadius = (stats: PlayerStats): number =>
  stats.general.range + stats.units[UnitType.Assault].range;

/**
 * Насколько дорогую покупку имеет смысл ждать при таком доходе.
 *
 * Живёт здесь, а не рядом с местом применения, потому что применений
 * стало два: им меряется и терпение к отдельной покупке, и осмысленность
 * неприкосновенного запаса. Разойдись эти две мерки — и получилось бы,
 * что ждать покупки в тридцать тысяч разумно, а держать под неё запас
 * нет, или наоборот.
 */
export const savingLimit = (incomePerTick: number, profile: AiProfile, guarded = false): number =>
  incomePerTick * TICKS_PER_SECOND * horizonSecondsOf(profile, guarded);

/**
 * Неприкосновенный запас фазы в единицах энергии ядра.
 *
 * Держится, только пока достижим. Условие не придирка: цена ЛЮБОЙ покупки
 * складывается с запасом, поэтому недостижимый запас запрещает не крупные
 * траты, а вообще все. В замере на двадцати матчах это стоило целой
 * поздней фазы — 1014 решений подряд, в каждом из которых и постройка,
 * и юнит, и улучшение отвечали «не по карману» при энергии, которой
 * хватало на шесть башен. Ядерных ударов за те же двадцать матчей
 * не случилось ни одного: запас держался под оружие, которое
 * не применялось.
 *
 * Мерка достижимости та же, какой уже меряется терпение к отдельной
 * покупке. Вопрос ведь один и тот же — имеет ли смысл ждать так долго, —
 * и двух ответов на него быть не должно.
 */
export const reserveOf = (
  phase: PhaseProfile,
  incomePerTick: number,
  profile: AiProfile,
  /**
   * Цена волны, под которую копит фаза с запасом `'wave'`.
   *
   * Приходит снаружи, а не считается здесь: тип волны зависит от того,
   * прикрыт ли путь вражескими башнями, и знает об этом рывок. Считать
   * тип второй раз значило бы завести второй источник истины о нём —
   * и однажды они разойдутся.
   */
  wavePrice = 0,
  /** Прикрыт ли путь: от этого зависит, сколько противник готов копить. */
  guarded = false,
  /**
   * Есть ли прямо сейчас цель, оправдывающая удар, и мешает ли ему
   * одна лишь нехватка энергии.
   *
   * Приходит снаружи по той же причине, что и цена волны: обстановку
   * знает обход карты в `findNukeTarget`, и делать его здесь значило бы
   * завести второй обход ради одного числа. Значение по умолчанию —
   * «цели нет»: запас, о котором не сказано, что он нужен, не держится.
   */
  nukeAwaited = false,
): number => {
  // Под удар копится цена пуска при БАЗОВОМ радиусе — нижняя граница,
  // а не точная цена. Настоящая цена зависит от прокачки радиуса, а сюда
  // приходят только фаза и доход: тянуть ради этого характеристики игрока
  // через всю цепочку значило бы связать правило накопления с прокачкой
  // ради поправки, которую съедает первая же секунда дохода.
  //
  // Держат этот запас двое, и оба условия обязательны.
  //
  // Первое — манера. Прежде условие было не нужно: удар стоил полусотни
  // стоимостей юнита и при обычном доходе не набирался ни у кого, кроме
  // терпеливых, — запас сам собой оставался нулевым. Удар подешевел
  // до шестнадцати, и без условия его начали бы копить ВСЕ, то есть
  // каждый профиль стал бы держать в казне мёртвую сумму ради оружия,
  // которое его манера не применяет. Замер показал это прямо: базовый
  // профиль, играющий соперником в `siege.test.ts`, начал придерживать
  // энергию, матч разошёлся, и осадный перестал доходить до единственной
  // за десять минут Теслы.
  //
  // Второе — обстановка, и приходит она снаружи. Держать деньги под удар,
  // которого не по кому нанести, нельзя: замер на двадцати матчах
  // «Стратега» против себя показал 11 651 энергии без движения во второй
  // половине матча против 1 206 у базового профиля, не копящего вовсе.
  // Круг при этом сам себя поддерживает: энергия заперта → нечем
  // производить → войско по пять машин → скопления не набираются →
  // удар не оправдан → запас не тратится.
  const nukeReserve = profile.nuke.invest === true && nukeAwaited ? NUKE_COST : 0;
  const wanted = phase.reserve === 'nuke' ? nukeReserve : phase.reserve === 'wave' ? wavePrice : 0;
  if (wanted <= 0) return 0;

  return wanted <= savingLimit(incomePerTick, profile, guarded) ? wanted : 0;
};

/**
 * Интересен ли удар этой фазе у этой манеры.
 *
 * Дешёвая проверка перед дорогим обходом карты. Фаза говорит, интересен
 * ли удар вообще — в ранних фазах нет, — а `nuke.invest` говорит, растит
 * ли манера ракету. Ни то ни другое не зависит от обстановки, поэтому
 * спрашивается раньше неё.
 */
export const savesForNuke = (phase: PhaseProfile, profile: AiProfile): boolean =>
  phase.reserve === 'nuke' && profile.nuke.invest === true;

/**
 * Фаза, действующая на этом тике.
 *
 * Последняя фаза замыкает список с бесконечным порогом, поэтому поиск
 * всегда что-нибудь находит и запасной вариант нужен лишь формально.
 */
export const phaseAt = (profile: AiProfile, tick: number): PhaseProfile => {
  const seconds = tick / TICKS_PER_SECOND;
  const found = profile.phases.find((phase) => seconds < phase.untilSecond);
  const last = profile.phases[profile.phases.length - 1];

  if (found !== undefined) return found;
  if (last === undefined) throw new Error('профиль без фаз');

  return last;
};

