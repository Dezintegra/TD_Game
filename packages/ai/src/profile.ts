/**
 * Фазы матча базового профиля.
 *
 * Ранняя — вложения в экономику и первые башни у базы. Средняя — поток
 * юнитов и башни ближе к фронту. Поздняя — прокачка боевых веток
 * и ядерный удар.
 *
 * Порядок трат — самая важная строка в каждой фазе. Первая версия
 * противника пыталась купить всё сразу, и штурмовики за 25 энергии
 * при доходе в 10 в секунду выгребали казну раньше, чем очередь доходила
 * до экономики: за восемь минут он ставил ОДНУ постройку и не покупал
 * ни одного улучшения. Одна покупка за решение, в заданном порядке,
 * лечит это полностью.
 */
const BASELINE_PHASES: readonly PhaseProfile[] = [
  {
    untilSecond: 90,
    upgrades: [UpgradeTarget.Economy],
    mix: { [UnitType.Assault]: 4, [UnitType.Sniper]: 1, [UnitType.Grenadier]: 0 },
    // Экономика вперёд всего: вложенное в первую минуту окупается весь матч.
    spend: ['upgrade', 'build', 'train'],
    reserve: 'none',
  },
  {
    untilSecond: 300,
    upgrades: [UpgradeTarget.Economy, UpgradeTarget.UnitAssault, UpgradeTarget.TowerBasic],
    mix: { [UnitType.Assault]: 5, [UnitType.Sniper]: 2, [UnitType.Grenadier]: 1 },
    // Прокачка перед постройками: вложенное в экономику к середине матча
    // окупается, а лишняя башня на пустом месте — почти никогда.
    spend: ['upgrade', 'build', 'train'],
    reserve: 'none',
  },
  {
    // Порог бесконечен: поздняя фаза замыкает список.
    untilSecond: Number.POSITIVE_INFINITY,
    upgrades: [
      UpgradeTarget.UnitAssault,
      UpgradeTarget.UnitGrenadier,
      UpgradeTarget.TowerSniper,
      UpgradeTarget.General,
      UpgradeTarget.Economy,
    ],
    mix: { [UnitType.Assault]: 4, [UnitType.Sniper]: 2, [UnitType.Grenadier]: 3 },
    spend: ['upgrade', 'train', 'build'],
    // Заряд держится в банке, тратится только излишек. Без запаса
    // противник до удара не накопит никогда: юниты и прокачка съедают
    // доход подчистую.
    reserve: 'nuke',
  },
];

/**
 * Базовый профиль.
 *
 * Имя содержит дату появления, и не для красоты: сравнивая матчи через
 * полгода, по имени `baseline-2026-08` сразу видно, что это за линия
 * поведения и насколько она стара, а по имени `default` — ничего.
 *
 * Числа здесь — ровно те, по которым противник играл до выделения
 * профиля. Свойство закреплено эталонным тестом `profile.golden.test.ts`;
 * меняете их намеренно — обновляйте эталон тем же коммитом.
 */
export const BASELINE_PROFILE: AiProfile = deepFreeze({
  id: 'baseline-2026-08',

  movement: {
    // Прицел в непосредственного соседа давал бы ступенчатую траекторию:
    // за одно решение генерал проходит около полутора клеток, и направление
    // менялось бы на каждом шаге сетки, хотя идти надо по прямой.
    lookaheadCells: 3,
    // На наступательном рубеже генерал — приоритетная цель для всего,
    // что стреляет, и без своих войск рядом он не живёт.
    advanceFraction: 0.5,
  },

  building: {
    // Стена сама по себе лишь покупает противнику время на обход; стена
    // перед башней — укрепление, потому что башня стреляет поверх неё,
    // а юниты сквозь неё стрелять не могут.
    wallEvery: 4,
    cellsAroundGeneral: 8,
    shieldRadiusCells: 2,
  },

  spending: {
    // Ждать вечно нельзя: если желаемое стоит десять минут дохода,
    // разумнее тратить на то, что доступно сейчас.
    savingHorizonSeconds: 45,
    // Без этого предела противник впадал в ступор: прокачка каждый раз
    // отвечала «почти хватает, подожди», и он ждал до конца матча,
    // не построив ни одной башни. Восемь решений — это четыре секунды.
    maxWaitDecisions: 8,
    // Не держим в очереди больше нескольких заказов: энергия нужнее живой.
    queueTarget: Math.min(4, PRODUCTION_QUEUE_CAP),
  },

  escort: {
    // Восемь стволов рядом сносят башню за несколько секунд, и генерал
    // проводит под её огнём не всю осаду, а только эти секунды.
    units: 8,
    // Юниты первыми — но только пока сопровождения не набралось. Иначе
    // порядок сломал бы всё: штурмовик вчетверо дешевле башни, и «юниты
    // первыми» без ограничения означает «юниты всегда».
    spend: ['train', 'upgrade', 'build'],
  },

  nuke: {
    worthUnits: 6,
    scanStep: 3,
  },

  posture: {
    // Шесть значений, а не непрерывная величина. Непрерывная давала бы
    // новую цель на каждом решении, и клетка-цель перескакивала бы
    // в другой конец коридора. Именно от этого генерал и метался.
    frontierFractions: [0, 0.15, 0.35, 0.55, 0.75, 0.95],
    // Без допуска рубеж выродился бы в одну клетку, а она запросто
    // окажется непроходимой или уже застроенной.
    bandCells: 3,
    threatRadiusCells: 10,
    // Башня возводится две секунды, значит на минуте успевает окупиться.
    // Брать больше нельзя: за пять минут обстановка меняется
    // до неузнаваемости, и оценка превратилась бы в гадание.
    horizonSeconds: 60,
  },

  phases: BASELINE_PHASES,
});

/**
 * Профиль, ставящий стены вдвое реже базового.
 *
 * Заведён не ради игры, а ради проверки самого механизма: он доказывает,
 * что профиль вообще на что-то влияет. Без такого профиля «профили
 * работают» осталось бы утверждением без свидетеля — базовый ведь обязан
 * повторять прежнее поведение в точности, и по нему различия не увидеть.
 */
export const WALL_LIGHT_PROFILE: AiProfile = deepFreeze({
  ...BASELINE_PROFILE,
  id: 'wall-light-2026-08',
  building: { ...BASELINE_PROFILE.building, wallEvery: 8 },
});

export const DEFAULT_PROFILE_ID = BASELINE_PROFILE.id;

export const PROFILES: Readonly<Record<string, AiProfile>> = deepFreeze({
  [BASELINE_PROFILE.id]: BASELINE_PROFILE,
  [WALL_LIGHT_PROFILE.id]: WALL_LIGHT_PROFILE,
});

/** Профиль по имени. Неизвестное имя — ошибка, а не молчаливый откат. */
export const profileByName = (id: string): AiProfile => {
  const profile = PROFILES[id];
  if (profile === undefined) {
    throw new Error(`неизвестный профиль «${id}»; есть: ${Object.keys(PROFILES).join(', ')}`);
  }

  return profile;
};
