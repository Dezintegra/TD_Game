/**
 * Эталон профиля по умолчанию — страж утверждения «перекладывание констант
 * в профиль поведения не изменило игру».
 *
 * Устроен по образцу `determinism.golden.match.test.ts` в ядре: прогоняем матч
 * фиксированной длины с фиксированным seed и сравниваем контрольную сумму
 * с числом, записанным здесь.
 *
 * Число снято на коде ДО выделения профиля — прогоном той же длины с теми же
 * seed, когда манера игры ещё задавалась константами модулей. Совпадение
 * доказывает, что при переносе пятнадцати с лишним величин ни одна
 * не потерялась и ни в одной не появилось опечатки; такую ошибку иначе
 * не поймать — она не ломает ни типы, ни тесты свойств, а просто делает
 * противника чуть другим.
 *
 * Если тест упал, а профиль по умолчанию менялся намеренно — эталон нужно
 * обновить тем же коммитом, что и правку. Тогда история настройки видна
 * в diff, а не теряется.
 */

const SEED = 20260820;
const SECONDS = 180;
const AI: PlayerId = asPlayerId(1);

/**
 * Снято на правилах изменения `value-towers-honestly`: покупка башни
 * оценивается своей меркой — уроном, горизонтом и курсом энергии, —
 * а не выгодой рубежа генерала; и решение «коплю» перестало обрывать
 * очередь тратам, дающим больше прибавки на единицу энергии.
 *
 * Сдвиг ожидаемый и объясним построчно. Построек шесть против четырёх:
 * до постройки наконец доходит очередь, а прежде она не доходила ни разу,
 * если не стояла в порядке первой. Войско выросло вдвое, с тринадцати
 * машин до двадцати шести, а уровней прокачки стало меньше (17 против
 * 26) — это та же причина с другой стороны: пока войско мало, прокачка
 * умножает почти пустое место и честно проигрывает сравнение и юниту,
 * и башне. Генерал заходит дальше — 0,956 пути против 0,889.
 *
 * Следом добавился разворот постройки (`turn-fire-into-spectacle`).
 * Поведения противника он не трогает вовсе: сектора обстрела нет,
 * разворот мгновенный, выбор цели от него не зависит. Но это величина
 * состояния мира, и она входит в контрольную сумму наравне с разворотом
 * юнита, — поэтому сумма сдвинулась, а наблюдаемые величины профиля
 * (постройки, войско, прокачка, путь генерала) остались прежними.
 *
 * Последним пришло сокращение перезарядки генерала вчетверо
 * (`give-the-general-a-salvo`). Здесь изменились и сумма, и наблюдаемые
 * величины, причём сильно, и разбор стоит того, чтобы его записать.
 *
 * В сценарии играет один противник под управлением компьютера, за игрока
 * с номером один; игрок ноль команд не подаёт вовсе. Но генерал у него
 * есть, и стреляет он сам, без команд, — а теперь вчетверо чаще. Отсюда
 * всё остальное:
 *
 * - войско противника ужалось вдвое, с 26 машин до 12: неподвижный
 *   генерал игрока ноль в одиночку выкашивает подходящую пехоту;
 * - команд стало вдвое больше (154 против 81), а энергии в конце
 *   вчетверо меньше (235 против 996): противник докупает взамен
 *   потерянного вместо того, чтобы копить;
 * - прокачка просела с 17 уровней до 11 — та же причина: энергия уходит
 *   в восполнение потерь;
 * - генерал заходит ДАЛЬШЕ, 1,0444 против 0,9556: он стал сильнее
 *   в бою, и рубеж, на котором его останавливает риск, отодвинулся.
 *
 * Построек по-прежнему шесть, и это хорошо: правка не тронула ни цен,
 * ни времени возведения, ни оценки постройки.
 *
 * В этом слиянии профиль встретил ДВЕ правки правил сразу, и разбор
 * нужен на обе. Манеру игры не меняет ни одна: профиль не тронут ни одной
 * величиной, решения по-прежнему принимаются по состоянию мира.
 *
 * Ветеранские ранги (`earn-the-rank`) сдвигали только сумму: наблюдаемые
 * величины при них не дрогнули ни на единицу. Так и должно быть — ранги
 * меняют ход БОЯ, а постройки, войско, прокачка и путь генерала говорят
 * о тратах и о маршруте, то есть о решениях, принимаемых до того, как
 * выяснится, кто кого перестрелял.
 *
 * Расталкивание (`push-units-apart`) сдвигает и наблюдаемые величины, все
 * сразу: противник стал меньше терять и потому меньше докупать взамен
 * потерянного. Точную причину этот тест не измеряет и утверждать её здесь
 * нечестно; замер изменения показал, что разведённое войско реже
 * оказывается целиком в радиусе одного стрелка.
 *
 * Числа ниже посчитаны на обоих правилах сразу. Порознь эталоны были
 * 1958727995 (только ранги) и 2287587834 (только расталкивание) —
 * в истории они остаются промежуточными.
 *
 *
 * И следом прокачался ядерный удар (`upgrade-nuke-damage-and-radius`).
 * Здесь повторилось то же самое, что и с рангами: сумма сдвинулась,
 * наблюдаемые величины не дрогнули — построек шесть, войска двенадцать,
 * прокачки одиннадцать уровней, генерал на той же доле пути.
 *
 * Причина сдвига не в самом ударе — за три минуты сценария противник
 * до него не доходит. Причина в том, что массив уровней прокачки удлинился
 * на две ветки, а он входит в сумму у каждого игрока целиком, включая
 * человека, который в этом сценарии не делает ничего.
 *
 * Число ниже посчитано на слиянии этой правки с расталкиванием юнитов:
 * порознь эталоны были 3553008627 (только ядерный удар) и 647606585
 * (только расталкивание), и в истории они остаются промежуточными.
 *
 * Последней пришла новая генерация мира (`compact-map-and-island-rocks`),
 * и прошла она двумя шагами с поучительной серединой.
 *
 * После первого шага — поле 38 × 38 при прежнем случайном блуждании —
 * противник заметно скис: построек четыре против шести, войска десять
 * против четырнадцати, энергии на руках 1113 против 852. То есть копил,
 * а не тратил.
 *
 * После второго — посадки скал островками с зазором — всё вернулось
 * и стало живее прежнего: построек шесть, войска тринадцать, прокачки
 * пятнадцать уровней против тринадцати, решений 153 против 94, энергии
 * на руках 742 против 852, генерал доходит до 1,087 пути против 1,0222.
 *
 * Значит, скисал он не от тесноты поля, а от того, во что превращались
 * скалы на тесном поле: кляксы блуждания слипались в цепи до четверти
 * тысячи клеток, вероятный путь петлял между ними, и оценка места под
 * башню упиралась в «коплю». Разнесённые островки эту причину убрали.
 *
 * Третий шаг — раскрытие проходов до трёх клеток — сдвинул только сумму:
 * наблюдаемые величины не дрогнули ни на единицу. Так и должно быть.
 * Раскрытие меняет карту по мелочи, у краёв и в горлах, а решения
 * противника опираются на вероятный путь целиком; путь от этого
 * не переложился.
 *
 * Правил профиля не трогал ни один шаг, но сила противника сдвинулась,
 * и на глаз такое засчитывать нельзя. Проверка ареной заведена записью
 * задачей в `manage/tasks/`.
 *
 * Предыдущие числа: 1907920771 — островки без раскрытия проходов;
 * 1689291615 — поле 38 × 38 со старой генерацией;
 * 2732107945 — карта 48 × 48;

 * И следом — настройка ядерки (`tune-the-nuke`). Здесь повторилось то же,
 * что с раскрытием проходов: сумма сдвинулась, а наблюдаемые величины
 * не дрогнули. Так и должно быть — базовый профиль в ракету
 * не вкладывается и за три минуты сценария ею не бьёт, поэтому ни новая
 * цена пуска, ни откат его решений не касаются. Сумму сдвинули две вещи,
 * до поведения не доходящие вовсе: таблица веток удлинилась на ветку
 * отката (массив уровней входит в сумму у каждого игрока), и в сумму
 * добавлен тик готовности пусковой установки.
 *
 * Совпадение наблюдаемых величин здесь — не формальность, а половина
 * ответа: разойдись хоть одно из них, сдвиг означал бы, что правка задела
 * манеру игры, а не только состав состояния.
 *
 * Число ПЕРЕСНЯТО на слиянии, а не выбрано из двух: карта и правила
 * ядерки меняют разные слагаемые одной суммы.
 *
 * Наблюдаемые величины при этом совпали с теми, что уже стояли в `main`
 * после новой генерации мира, — построек шесть, войска тринадцать,
 * прокачки пятнадцать уровней, энергии 742, решений 153, генерал
 * на 1,087 пути. Это и есть половина ответа: правка ядерки манеру игры
 * не задела.
 *
 * Ещё числа: 1853246947 — новая генерация мира;
 * 3375105465 — настройка ядерки на карте 48 × 48;

 * 647606585 — расталкивание юнитов;
 * 3553008627 — ядерный удар с уроном и прокачкой;
 * 3542048556 — ветеранские ранги;
 * 1337072980 — залп генерала;
 * 1815286486 — разворот постройки; 3349686969 —
 * `value-towers-honestly`; 161109159 —
 * `build-towers-in-force` (постройка группой и достижимый ядерный
 * запас), 502076340 — на пяти изменениях до него.
 *
 * И последней пришла живучесть в выборе места под башню
 * (`fortify-approaches`). Здесь сдвинулось всё сразу, и разбор нужен
 * подробный: правка прямо меняет, куда встают башни.
 *
 * Место выбирается теперь не по одному покрытию ещё не накрытого пути,
 * а по нему вместе с прибавкой к живучести от взаимного прикрытия.
 * Прежняя мерка вычитала накрытые своими клетки и потому уводила башню
 * как можно дальше от своих — разброс был не случайностью, а замыслом
 * алгоритма. Теперь прикрытие тянет обратно, и место оказывается ближе
 * к уже стоящим башням.
 *
 * Отсюда наблюдаемые величины:
 *
 * - построек восемь против шести. Место под прикрытием накрывает меньше
 *   пути, значит быстрее исчерпывается ненакрытое рядом, и следующая
 *   постройка находит себе место чаще;
 * - войска семь против тринадцати, прокачки десять уровней против
 *   пятнадцати, энергии на руках 1541 против 742. Это одна причина
 *   с трёх сторон: покрытие выбранного места стало ниже, а покупка
 *   постройки по-прежнему меряется покрытием, поэтому очередь трат
 *   сдвинулась в сторону накопления;
 * - решений 109 против 153 — та же причина;
 * - генерал доходит до 1,0 пути против 1,087.
 *
 * Последняя строка — предупреждение, а не итог. Спецификация требует,
 * чтобы укрепление не подменяло наступление, и просадка продвижения
 * здесь ровно то, за чем велено следить. Но сценарий эталона — три
 * минуты и одна сторона против неподвижного соперника; судить
 * по нему о наступлении нельзя. Судит прогон арены на seed 2000–2019,
 * и его числа лежат в `openspec/changes/fortify-approaches/baseline.md`.
 *
 * В сравнение ПОКУПОК прибавка к живучести намеренно не пущена: она
 * отвечает на вопрос «куда поставить», а не «стоит ли ставить», и пусти
 * её туда — изменился бы расклад трат, а траты это изменение не трогает
 * по своему же условию. Замер разницы: с `siteValue` в сравнении покупок
 * выходило 108 решений и 1451 энергии против 109 и 1541, а расстановка
 * не менялась вовсе.
 */
const GOLDEN_CHECKSUM = 3742757923;

interface Outcome {
  readonly checksum: number;
  readonly structures: number;
  readonly units: number;
  readonly upgradeLevels: number;
  readonly energy: number;
  readonly commands: number;
  readonly furthestFraction: number;
}

const play = (profile: AiProfile): Outcome => {
  const opponent = createOpponent(AI, SEED, profile);
  const approach = approachOf(createWorld(SEED), AI);
  if (approach === undefined) throw new Error('вероятный путь не посчитан');

  let world = createWorld(SEED);
  let commands = 0;
  let furthest = 0;

  for (let tick = 0; tick < SECONDS * TICKS_PER_SECOND; tick += 1) {
    const issued = opponent.decide(world);
    commands += issued.length;
    world = step(world, issued);

    const general = world.generals[AI];
    if (general === undefined || !general.alive) continue;

    const fromHome = approach.fromHome[cellAt(general.position)] ?? 0;
    if (fromHome > furthest) furthest = fromHome;
  }

  const player = world.players[AI];

  return {
    checksum: checksum(world),
    structures: world.structures.filter(
      (structure) => structure.owner === AI && structure.kind !== StructureKind.Base,
    ).length,
    units: world.units.filter((unit) => unit.owner === AI).length,
    upgradeLevels: player?.upgrades.reduce((sum, upgrade) => sum + upgrade.level, 0) ?? 0,
    energy: player?.energy ?? 0,
    commands,
    furthestFraction: Number((furthest / approach.shortest).toFixed(4)),
  };
};

describe('эталон профиля по умолчанию', () => {
  const outcome = play(BASELINE_PROFILE);

  it('совпадает с контрольной суммой, снятой до выделения профиля', () => {
    expect(outcome.checksum).toBe(GOLDEN_CHECKSUM);
  });

  it('совпадает и по наблюдаемым величинам', () => {
    // Дублирует предыдущую проверку — но не зря. Контрольная сумма
    // говорит только «сошлось» или «не сошлось»; если она разойдётся,
    // именно эти числа покажут, где искать: пропала прокачка, не там
    // построено или генерал не дошёл.
    expect(outcome).toMatchObject({
      structures: 8,
      units: 7,
      upgradeLevels: 10,
      energy: 1541,
      commands: 109,
      furthestFraction: 1,
    });
  });

  it('вызов без профиля равнозначен вызову с профилем по умолчанию', () => {
    // Третий аргумент необязателен намеренно: существующие вызовы
    // в клиенте и в тестах от появления профиля не изменились.
    const opponent = createOpponent(AI, SEED);
    const explicit = createOpponent(AI, SEED, BASELINE_PROFILE);

    let a = createWorld(SEED);
    let b = createWorld(SEED);
    for (let tick = 0; tick < 30 * TICKS_PER_SECOND; tick += 1) {
      a = step(a, opponent.decide(a));
      b = step(b, explicit.decide(b));
    }

    expect(checksum(a)).toBe(checksum(b));
  });
});

describe('профиль действительно влияет на игру', () => {
  const patient: AiProfile = {
    ...BASELINE_PROFILE,
    id: 'test-patient',
    spending: { ...BASELINE_PROFILE.spending, savingHorizonSeconds: 5 },
  };

  it('другой профиль даёт другой матч', () => {
    expect(play(patient).checksum).not.toBe(GOLDEN_CHECKSUM);
  });

  it('профиль, различающийся только частотой стен, снова различим', () => {
    // Обещанная хорошая новость.
    //
    // До `build-towers-in-force` этот тест утверждал ОБРАТНОЕ: оба
    // профиля давали побайтово одинаковый матч, потому что противник
    // строил так мало, что счётчик построек не доходил ни до четвёртой,
    // ни до восьмой, и частота стен ни на что не влияла. В комментарии
    // к нему стояло, что он обязан начать падать, когда постройки
    // вернутся в матч.
    //
    // Постройки вернулись: за три минуты их стало шесть вместо одной,
    // счётчик доходит до четвёртой, и `wallEvery` снова что-то значит.
    expect(play(WALL_LIGHT_PROFILE).checksum).not.toBe(GOLDEN_CHECKSUM);
  });
});
